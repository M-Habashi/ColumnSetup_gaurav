function result = run_parametric_mck_trial()
%RUN_PARAMETRIC_MCK_TRIAL Scratch m/c/k-variable parametric ID trial.

    project_root = 'C:\Users\BOWN1111PC1\Documents\Mohamed\ColumnSetup_gaurav\main';
    output_dir = 'C:\Users\BOWN1111PC1\Documents\Mohamed\ColumnSetup_gaurav\.codex\verification\parametric_mck';
    data_name = 'gg_04_k.mat';
    profile_name = 'gg_04_k.mat';
    specimen_name = 'sp1.mat';
    max_freq_hz = 80;

    cd(project_root)
    addpath(fullfile(project_root, 'analysis', 'system_id'));
    addpath(fullfile(project_root, 'analysis', 'system_id', 'utils'));

    data_file = fullfile(project_root, 'analysis', 'system_id', 'datafiles', data_name);
    profile_file = fullfile(project_root, 'analysis', 'system_id', 'models', 'paarametric', profile_name);
    specimen_file = fullfile(project_root, 'analysis', 'system_id', 'data_speciment', specimen_name);

    experimental_data = load(data_file);
    reference_profile = load(profile_file);
    specimen = load(specimen_file);

    dd = experimental_data.dd;
    dm = experimental_data.dm;
    fs = experimental_data.fs;

    fft_length = 2^15;
    overlap = 2^14;
    [tf_points_all, freq_hz_all, spectra] = xfunc(dd, dm, fs, fft_length, overlap);
    coherence_all = abs(spectra(:,3)).^2 ./ max(spectra(:,1).*spectra(:,2), eps);

    keep_idx = freq_hz_all >= 0.1 & freq_hz_all <= max_freq_hz;
    freq_hz = freq_hz_all(keep_idx);
    tf_points = tf_points_all(keep_idx);
    freq_rad = 2 * pi * freq_hz;

    discrete_tf_estimate = struct( ...
        'config', struct('data_file', data_file, 'f_lim', [0.1 max_freq_hz]), ...
        'dd', dd, ...
        'dm', dm, ...
        'fs', fs, ...
        'tf_points', tf_points(:), ...
        'freq_hz', freq_hz(:), ...
        'freq_rad', freq_rad(:), ...
        'coherence', coherence_all(keep_idx), ...
        'tf_discrete', frd(tf_points(:), freq_rad(:)));

    fit_config = struct( ...
        'mass', specimen.m, ...
        'damping', specimen.c, ...
        'stiffness', max(specimen.k, 1e-6), ...
        'fit_band_hz', [0.5 max_freq_hz], ...
        'magnitude_weight', 3, ...
        'phase_weight', 0.35, ...
        'frequency_weight_exponent', 1, ...
        'frequency_weight_floor_hz', 0, ...
        'num_random_starts', 5, ...
        'max_time', 60, ...
        'display', 'off', ...
        'solver_display', 'off');

    fit_config.initial_params = struct( ...
        'a1b0', reference_profile.a1b0, ...
        'a2', reference_profile.a2, ...
        'a3', reference_profile.a3, ...
        'beta1', reference_profile.beta1, ...
        'beta2', reference_profile.beta2, ...
        'Kp', reference_profile.Kp, ...
        'Ki', reference_profile.Ki, ...
        'mass', specimen.m, ...
        'damping', specimen.c, ...
        'stiffness', max(specimen.k, 1e-6));

    fit = identify_parametric_with_mck(discrete_tf_estimate, fit_config);
    identified = fit.identified_params;

    names = {'a1b0','a2','a3','beta1','beta2','Kp','Ki','mass','damping','stiffness'}';
    current = [reference_profile.a1b0; reference_profile.a2; reference_profile.a3; ...
        reference_profile.beta1; reference_profile.beta2; reference_profile.Kp; ...
        reference_profile.Ki; specimen.m; specimen.c; specimen.k];
    trial = [identified.a1b0; identified.a2; identified.a3; identified.beta1; ...
        identified.beta2; identified.Kp; identified.Ki; identified.mass; ...
        identified.damping; identified.stiffness];
    signed_percent = 100 * (trial - current) ./ current;
    abs_percent = 100 * abs(trial - current) ./ abs(current);
    signed_percent(current == 0) = NaN;
    abs_percent(current == 0) = NaN;

    comparison = table(names, current, trial, signed_percent, abs_percent, ...
        'VariableNames', {'Parameter','Current','Trial','SignedPercentDifference','AbsPercentDifference'});

    result = struct( ...
        'data_name', data_name, ...
        'profile_name', profile_name, ...
        'specimen_name', specimen_name, ...
        'comparison', comparison, ...
        'fit', fit);

    save(fullfile(output_dir, 'parametric_mck_trial_gg_04_k_sp1.mat'), 'result');
    writetable(comparison, fullfile(output_dir, 'parametric_mck_trial_gg_04_k_sp1.csv'));

    fprintf('Data file: %s\n', data_name);
    fprintf('Reference profile: %s\n', profile_name);
    fprintf('Reference specimen: %s\n', specimen_name);
    fprintf('RMS magnitude error: %.6g dB\n', fit.rms_mag_db);
    fprintf('RMS phase error: %.6g deg\n\n', fit.rms_phase_deg);
    disp(comparison)
end

function out = identify_parametric_with_mck(discrete_tf_estimate, fit_config)
    c = defaults(fit_config);
    y = discrete_tf_estimate.tf_points(:);
    w = discrete_tf_estimate.freq_rad(:);
    c.frequency_weight = frequency_weight(w, c);

    fields = {'a1b0','a2','a3','beta1','beta2','Kp','Ki','mass','damping','stiffness'};
    lower = [c.a1b0_bounds(1); c.a2_bounds(1); c.a3_bounds(1); c.beta1_bounds(1); ...
        c.beta2_bounds(1); c.Kp_bounds(1); c.Ki_bounds(1); c.mass_bounds(1); ...
        c.damping_bounds(1); c.stiffness_bounds(1)];
    upper = [c.a1b0_bounds(2); c.a2_bounds(2); c.a3_bounds(2); c.beta1_bounds(2); ...
        c.beta2_bounds(2); c.Kp_bounds(2); c.Ki_bounds(2); c.mass_bounds(2); ...
        c.damping_bounds(2); c.stiffness_bounds(2)];
    lb = log10(lower);
    ub = log10(upper);
    x0 = log10(cellfun(@(f)c.initial_params.(f), fields)).';

    known = log10([ ...
        2.1283e13, 4.2297e6, 3.3, 425, 9.9976e4, 1.0, 0.01, c.mass, c.damping, c.stiffness; ...
        2.1283e13, 4.2297e6, 10, 200, 8e4, 1.5, 0.01, c.mass, c.damping, max(c.stiffness, 1e-6); ...
        1e13, 1e7, 30, 100, 2e5, 2.0, 0.1, 0.5*c.mass, 0.5*c.damping, max(10*c.stiffness, 1e-6); ...
        5e13, 1e6, 1.0, 600, 5e4, 0.5, 0.01, 2*c.mass, 2*c.damping, max(0.1*c.stiffness, 1e-6)]);
    starts = [x0.'; known; lb.' + rand(c.num_random_starts, numel(lb)) .* (ub - lb).'];
    starts = min(max(starts, lb.'), ub.');

    opts = optimoptions('lsqnonlin', 'Display', c.solver_display, ...
        'MaxFunctionEvaluations', c.max_function_evaluations, ...
        'MaxIterations', c.max_iterations, ...
        'StepTolerance', c.step_tolerance, ...
        'FunctionTolerance', c.function_tolerance);
    problem = createOptimProblem('lsqnonlin', 'objective', @(x)err(x, w, y, c), ...
        'x0', x0, 'lb', lb, 'ub', ub, 'options', opts);
    [x, resnorm, exitflag, solver_output, solutions] = run( ...
        MultiStart('Display', c.display, 'MaxTime', c.max_time), ...
        problem, CustomStartPointSet(starts));

    p = pack(10 .^ x);
    [num, den] = model_poly(p);
    fit_resp = freqs(num, den, w);
    mag_target_db = 20 * log10(abs(y) + eps);
    mag_fit_db = 20 * log10(abs(fit_resp) + eps);
    phase_target_deg = unwrap(angle(y)) * 180 / pi;
    phase_fit_deg = unwrap(angle(fit_resp)) * 180 / pi;

    out = struct('identified_params', p, 'parametric_cl', tf(num, den), ...
        'freq_hz', discrete_tf_estimate.freq_hz, 'freq_rad', w, ...
        'fit_resp', fit_resp, 'resnorm', resnorm, 'exitflag', exitflag, ...
        'output', solver_output, 'solutions', solutions, ...
        'mag_target_db', mag_target_db, 'mag_fit_db', mag_fit_db, ...
        'phase_target_deg', phase_target_deg, 'phase_fit_deg', phase_fit_deg, ...
        'rms_mag_db', rms(mag_fit_db - mag_target_db), ...
        'rms_phase_deg', rms(phase_fit_deg - phase_target_deg));
end

function r = err(x, w, y, c)
    [num, den] = model_poly(pack(10 .^ x));
    h = freqs(num, den, w);
    in_band = w >= 2 * pi * c.fit_band_hz(1) & w <= 2 * pi * c.fit_band_hz(2);
    mw = ones(size(w)); mw(in_band) = c.magnitude_weight;
    fw = c.frequency_weight;
    r = [fw .* mw .* (log10(abs(h) + eps) - log10(abs(y) + eps)); ...
        c.phase_weight * fw .* mw .* ((unwrap(angle(h)) - unwrap(angle(y))) / pi)];
    r(~isfinite(r)) = 1e6;
end

function fw = frequency_weight(w, c)
    if c.frequency_weight_exponent == 0
        fw = ones(size(w(:)));
        return
    end

    f = max(w(:) / (2 * pi), c.frequency_weight_floor_hz);
    fw = f .^ (-c.frequency_weight_exponent);
    fw = fw / mean(fw);
end

function p = pack(v)
    p = struct('a1b0', v(1), 'a2', v(2), 'a3', v(3), 'beta1', v(4), ...
        'beta2', v(5), 'Kp', v(6), 'Ki', v(7), 'mass', v(8), ...
        'damping', v(9), 'stiffness', v(10), 'a1', v(1), 'b1', v(4), 'b2', v(5));
end

function [num, den] = model_poly(p)
    m = p.mass; d = p.damping; k = p.stiffness;
    num = [p.Kp * p.a1b0, p.Ki * p.a1b0];
    den = [m, ...
        d + p.a3*m + p.beta1*m, ...
        p.a2 + k + p.a3*d + p.beta1*d + p.beta2*m + p.a3*p.beta1*m, ...
        p.a2*p.beta1 + p.beta2*d + p.a3*k + p.beta1*k + p.a3*p.beta1*d + p.a3*p.beta2*m, ...
        p.a2*p.beta2 + p.beta2*k + p.a3*p.beta2*d + p.a3*p.beta1*k, ...
        p.Kp*p.a1b0 + p.a3*p.beta2*k, ...
        p.Ki*p.a1b0];
end

