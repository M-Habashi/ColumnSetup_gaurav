function export_beautiful_plot_data
%% Export saved-result signals used by the HTML interactive plot.

scriptFolder = fileparts(mfilename('fullpath'));
projectFolder = fileparts(fileparts(scriptFolder));

filePaths = { ...
    fullfile(projectFolder, 'saved_results', 'tests', '20260731', ...
        'instability.mat'), ...
    fullfile(projectFolder, 'saved_results', 'tests', ...
        'successful nonLin tests', 'beautiful.mat'), ...
    fullfile(projectFolder, 'saved_results', 'tests', ...
        'successful nonLin tests', 'beautiful2.mat'), ...
    fullfile(projectFolder, 'saved_results', 'tests', ...
        'successful nonLin tests', 'beautiful3.mat'), ...
    fullfile(projectFolder, 'saved_results', 'tests', ...
        'successful nonLin tests', 'beautiful4.mat')};
fileIds = {'instability', 'beautiful', 'beautiful2', 'beautiful3', ...
    'beautiful4'};
fileNames = {'instability.mat', 'beautiful.mat', 'beautiful2.mat', ...
    'beautiful3.mat', 'beautiful4.mat'};

records = cell(size(filePaths));
maxPlotPoints = 50000;
for fileNumber = 1:numel(filePaths)
    data = load(filePaths{fileNumber}, 'result');
    result = data.result;
    if isfield(result, 'result') && isstruct(result.result)
        result = result.result;
    end

    t = result.t(:);
    dm = result.dm(:);
    fm = result.fm(:);
    fs = result.fs;
    dm_filt_filt = filtfiltDm(dm, fs, 30, 4);

    n = min([numel(t), numel(dm_filt_filt), numel(fm)]);
    t = t(1:n);
    dm = dm(1:n);
    dm_filt_filt = dm_filt_filt(1:n);
    fm = fm(1:n);

    plotIndex = unique([1:ceil(n/maxPlotPoints):n, n]);
    records{fileNumber} = struct( ...
        'id', fileIds{fileNumber}, ...
        'source', fileNames{fileNumber}, ...
        'time', t(plotIndex), ...
        'dm', dm(plotIndex), ...
        'dm_filt_filt', dm_filt_filt(plotIndex), ...
        'fm', fm(plotIndex), ...
        'sample_count', n, ...
        'fs', fs, ...
        'filter_cutoff_hz', 30, ...
        'filter_order', 4);
end

plotData = struct('defaultId', 'instability', 'records', [records{:}]);
jsonText = jsonencode(plotData);
outputFile = fullfile(scriptFolder, 'beautiful_plot_data.js');
fileId = fopen(outputFile, 'w');
fwrite(fileId, ['window.beautifulPlotData = ' jsonText ';'], 'char');
fclose(fileId);
fprintf('Wrote %d records to %s\n', numel(records), outputFile)
end

function y = filtfiltDm(dm, fs, cutoffHz, order)
% Units: dm/y [mm], fs/cutoffHz [Hz].
    [b, a] = butter(order, cutoffHz/(fs/2), 'low');
    y = filtfilt(b, a, dm - dm(1)) + dm(1);
end
