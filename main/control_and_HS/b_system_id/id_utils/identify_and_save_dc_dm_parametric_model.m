function [H_dc_dm_param, parametric_identification, params_path] = ...
        identify_and_save_dc_dm_parametric_model(dc, dm, fs, step_root, ...
        data_file, data_name, specimen, specimen_file, specimen_name, ...
        test_type, fit_config)
%IDENTIFY_AND_SAVE_DC_DM_PARAMETRIC_MODEL Identify and save dc -> dm model.
% The saved MAT variables match control_and_HS/b_system_id/sys_id.m.

    model_output_dir = fullfile(step_root, 'saved_results', 'models');
    if ~exist(model_output_dir, 'dir')
        mkdir(model_output_dir);
    end

    parametric_fit_band_hz = [0.5, fit_config.f_lim(2)];
    parametric_coherence_min = config_value(fit_config, 'coherence_min', 0.8);
    parametric_input_power_range_db = config_value( ...
        fit_config, 'input_power_range_db', 30);

    specimen_si = specimen_params_si(specimen);
    parametric_identification_config = struct( ...
        'mass', specimen_si.mass, ...
        'damping', specimen_si.damping, ...
        'stiffness', specimen_si.stiffness, ...
        'specimen_file', specimen_file, ...
        'fit_band_hz', parametric_fit_band_hz, ...
        'magnitude_weight', 3, ...
        'phase_weight', 0.9, ...
        'frequency_weight_exponent', 0, ...  % the higher -> gives more weight to lower freq. [KEEP THIS COMMENT]
        'frequency_weight_floor_hz', 0.5, ...
        'num_random_starts', 5, ...
        'max_time', 60);

    tf_estimate_config = struct( ...
        'data_file', data_file, ...
        'desc', 'Digital-controller output to measured displacement', ...
        'f_lim', fit_config.f_lim, ...
        'fit_band_hz', parametric_fit_band_hz, ...
        'coherence_min', parametric_coherence_min, ...
        'input_power_range_db', parametric_input_power_range_db, ...
        'fft_length', fit_config.fft_length, ...
        'overlap', fit_config.overlap);
    H_dc_dm_discrete_estimate = build_discrete_tf_estimate( ...
        dc, dm, fs, tf_estimate_config);
    H_dc_dm_discrete_estimate.test_type = test_type;

    parametric_identification = identify_analog_closed_loop_params( ...
        H_dc_dm_discrete_estimate, parametric_identification_config);
    identified_params = parametric_identification.identified_params;
    tf_parametric = parametric_identification.parametric_cl;
    H_dc_dm_param = tf_parametric;

    [~, params_file_name] = fileparts(data_file);
    params_path = fullfile(model_output_dir, sprintf('%s.mat', params_file_name));
    a1b0 = identified_params.a1b0;
    a2 = identified_params.a2;
    a3 = identified_params.a3;
    beta1 = identified_params.beta1;
    beta2 = identified_params.beta2;
    Kp = identified_params.Kp;
    Ki = identified_params.Ki;
    specimen_params = specimen;
    specimen_params.name = specimen_name;
    specimen_params.file = parametric_identification_config.specimen_file;
    specimen_params.m = specimen.m;
    specimen_params.c = specimen.c;
    specimen_params.k = specimen.k;
    id_units = specimen_si.units;

    save(params_path, ...
        'a1b0', ...
        'a2', ...
        'a3', ...
        'beta1', ...
        'beta2', ...
        'Kp', ...
        'Ki', ...
        'specimen_params', ...
        'id_units', ...
        'test_type', ...
        'tf_parametric');

    fprintf('\nIdentified dc -> dm parametric model\n');
    fprintf('Data file = %s\n', data_name);
    fprintf('Specimen parameters = %s\n', specimen_file);
    fprintf('Test type = %s\n', test_type);
    fprintf('Parametric fit points = %d over [%.4g, %.4g] Hz (%s)\n', ...
        H_dc_dm_discrete_estimate.fit_selection.point_count, ...
        H_dc_dm_discrete_estimate.fit_selection.actual_band_hz(1), ...
        H_dc_dm_discrete_estimate.fit_selection.actual_band_hz(2), ...
        H_dc_dm_discrete_estimate.fit_selection.source);
    fprintf('Parametric gate: coherence >= %.4g, input power within %.4g dB\n', ...
        H_dc_dm_discrete_estimate.fit_selection.coherence_min, ...
        H_dc_dm_discrete_estimate.fit_selection.input_power_range_db);
    fprintf('Parametric weights: phase = %.4g, frequency exponent = %.4g\n', ...
        parametric_identification_config.phase_weight, ...
        parametric_identification_config.frequency_weight_exponent);
    fprintf('a1b0 = %.12g\n', identified_params.a1b0);
    fprintf('a2 = %.12g\n', identified_params.a2);
    fprintf('a3 = %.12g\n', identified_params.a3);
    fprintf('beta1 = %.12g\n', identified_params.beta1);
    fprintf('beta2 = %.12g\n', identified_params.beta2);
    fprintf('Kp = %.12g\n', identified_params.Kp);
    fprintf('Ki = %.12g\n', identified_params.Ki);
    fprintf('RMS magnitude error = %.4f dB\n', ...
        parametric_identification.rms_mag_db);
    fprintf('RMS phase error = %.4f deg\n', ...
        parametric_identification.rms_phase_deg);
    fprintf('Saved parametric model = %s\n', params_path);
end

function discrete_tf_estimate = build_discrete_tf_estimate(input_signal, ...
        output_signal, fs, config)
% Build the FRF structure consumed by identify_analog_closed_loop_params.
    [tf_points, freq_hz, spectra] = xfunc(input_signal, output_signal, fs, ...
        config.fft_length, config.overlap);
    coherence = abs(spectra(:,3)).^2 ./ max(spectra(:,1).*spectra(:,2), eps);
    input_power_db = 10*log10(spectra(:,1) + eps);
    finite_idx = isfinite(freq_hz) & isfinite(real(tf_points)) & ...
        isfinite(imag(tf_points)) & isfinite(coherence) & ...
        isfinite(input_power_db);
    band_idx = freq_hz >= config.fit_band_hz(1) & ...
        freq_hz <= config.fit_band_hz(2);
    threshold_idx = band_idx & finite_idx;
    if any(threshold_idx)
        input_power_floor_db = max(input_power_db(threshold_idx)) - ...
            config.input_power_range_db;
    else
        input_power_floor_db = -Inf;
    end
    reliable_idx = threshold_idx & coherence >= config.coherence_min & ...
        input_power_db >= input_power_floor_db;
    if any(reliable_idx)
        keep_idx = reliable_idx;
        selection_source = 'coherence/input-power gated fit band';
    else
        keep_idx = threshold_idx;
        selection_source = 'finite fit-band fallback';
    end
    if ~any(keep_idx)
        error('identify_dc_dm_parametric:NoFitPoints', ...
            'No finite dc -> dm FRF points were found in the parametric fit band.');
    end

    tf_points = tf_points(keep_idx);
    freq_hz = freq_hz(keep_idx);
    freq_rad = 2*pi*freq_hz;
    fit_selection = struct( ...
        'source', selection_source, ...
        'point_count', numel(freq_hz), ...
        'fit_band_hz', config.fit_band_hz, ...
        'actual_band_hz', [min(freq_hz), max(freq_hz)], ...
        'coherence_min', config.coherence_min, ...
        'input_power_range_db', config.input_power_range_db, ...
        'input_power_floor_db', input_power_floor_db);

    discrete_tf_estimate = struct( ...
        'config', config, ...
        'dc', input_signal(:), ...
        'dm', output_signal(:), ...
        'fs', fs, ...
        'tf_points', tf_points(:), ...
        'freq_hz', freq_hz(:), ...
        'freq_rad', freq_rad(:), ...
        'coherence', coherence(keep_idx), ...
        'input_power_db', input_power_db(keep_idx), ...
        'fit_selection', fit_selection, ...
        'tf_discrete', frd(tf_points(:), freq_rad(:)), ...
        'controller', [], ...
        'controller_gains', struct('Kp', NaN, 'Ki', NaN, ...
            'Estimated', true));
end

function value = config_value(config, field_name, default_value)
    if isfield(config, field_name) && ~isempty(config.(field_name))
        value = config.(field_name);
    else
        value = default_value;
    end
end
