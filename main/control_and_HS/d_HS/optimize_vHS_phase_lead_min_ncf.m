%% Optimize vHS phase_lead With Minimum NCF Margin
% Set ncfmargin before running to require a NumPhaseLeadExpNCFMargin value.

clearvars -except phase_lead_optimizer_config ncfmargin ncf_margin ...
    fem_file_override ...
    specimen_file_override exp_specimen_file_override ...
    h_dc_dm_model_file_override pid_gain_override ...
    phase_lead_file_name_override; clc;

script_dir = fileparts(mfilename('fullpath'));
phase_lead_file_name = 'pl_7000_ncf4';
defaults = struct( ...
    'minimum_num_phase_lead_exp_ncf_margin', 0.45, ...
    'optimization_record_fraction', 1.0, ...
    'minimum_optimization_record_fraction', 0.7, ...
    'phase_lead_file_name', phase_lead_file_name, ...
    'max_dc_dm_penalty_weight', 0, ...
    'max_dd_lead_dc_penalty_weight', 0, ...
    'grid_center_hz', [0.75 1 1.5 2 3 4 6 8 12 18 27 40 60 80], ...
    'grid_ratio', [1.01 1.05 1.15 1.3 1.6 2 3 5 8 12 16 20 25], ...
    'start_points', localPhaseLeadStartPoints(), ...
    'fmincon_grid_start_count', 8, ...
    'max_iterations', 80, ...
    'max_function_evaluations', 350, ...
    'compact_optimizer_output', true, ...
    'save_results', true, ...
    'print_best_checkpoint', true, ...
    'save_best_checkpoint', true, ...
    'print_optimizer_progress', true, ...
    'best_checkpoint_interval_trials', 1, ...
    'use_parallel_grid', true);

if exist('phase_lead_optimizer_config', 'var') ...
        && ~isempty(phase_lead_optimizer_config)
    phase_lead_optimizer_config = mergeLocalStruct(defaults, ...
        phase_lead_optimizer_config);
else
    phase_lead_optimizer_config = defaults;
end
phase_lead_optimizer_config.save_results = defaults.save_results;
phase_lead_optimizer_config.save_best_checkpoint = ...
    defaults.save_best_checkpoint;
phase_lead_optimizer_config.minimum_optimization_record_fraction = ...
    defaults.minimum_optimization_record_fraction;
phase_lead_optimizer_config.optimization_record_fraction = max( ...
    phase_lead_optimizer_config.optimization_record_fraction, ...
    defaults.minimum_optimization_record_fraction);
if ~exist('fem_file_override', 'var') || isempty(fem_file_override)
    phase_lead_optimizer_config.fem_file = '';
end
if exist('ncfmargin', 'var') && ~isempty(ncfmargin)
    phase_lead_optimizer_config.minimum_num_phase_lead_exp_ncf_margin = ...
        ncfmargin;
elseif exist('ncf_margin', 'var') && ~isempty(ncf_margin)
    phase_lead_optimizer_config.minimum_num_phase_lead_exp_ncf_margin = ...
        ncf_margin;
end
if exist('phase_lead_file_name_override', 'var') ...
        && ~isempty(phase_lead_file_name_override)
    phase_lead_optimizer_config.phase_lead_file_name = ...
        phase_lead_file_name_override;
end

run(fullfile(script_dir, 'utils_HS', 'optimize_vHS_phase_lead.m'))

function config = mergeLocalStruct(config, override)
fields = fieldnames(override);
for field_id = 1:numel(fields)
    config.(fields{field_id}) = override.(fields{field_id});
end
end

function start_points = localPhaseLeadStartPoints()
start_points = [ ...
    1 1.3; ...
    2 2; ...
    4 3; ...
    8 5; ...
    32 12];
end
