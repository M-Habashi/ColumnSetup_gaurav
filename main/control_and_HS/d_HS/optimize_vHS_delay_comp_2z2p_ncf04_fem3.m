%% Optimize vHS 2Z/2P Delay Compensation With NCF 0.4 For FEM 3
% Optimizes performance while requiring NumDelayCompExpNCFMargin >= 0.4.

clearvars -except phase_lead_optimizer_config ...
    fem_file_override ...
    specimen_file_override exp_specimen_file_override ...
    h_dc_dm_model_file_override pid_gain_override; clc;

script_dir = fileparts(mfilename('fullpath'));
project_root = fileparts(fileparts(script_dir));
defaults = struct( ...
    'phase_lead_section_count', 2, ...
    'minimum_num_delay_comp_exp_ncf_margin', 0.3, ...
    'fem_file', fullfile(project_root, 'saved_results', 'fem', ...
        'fem_sp_1_org_3.mat'), ...
    'best_checkpoint_file', fullfile(project_root, 'saved_results', ...
        'delay_comp', 'vHS_phase_lead_2z2p_ncf04_fem3_best_checkpoint.mat'), ...
    'use_parallel_grid', true);

if exist('phase_lead_optimizer_config', 'var') ...
        && ~isempty(phase_lead_optimizer_config)
    phase_lead_optimizer_config = mergeLocalStruct(defaults, ...
        phase_lead_optimizer_config);
else
    phase_lead_optimizer_config = defaults;
end
phase_lead_optimizer_config.phase_lead_section_count = ...
    defaults.phase_lead_section_count;
phase_lead_optimizer_config.minimum_num_delay_comp_exp_ncf_margin = ...
    defaults.minimum_num_delay_comp_exp_ncf_margin;
phase_lead_optimizer_config.fem_file = defaults.fem_file;
phase_lead_optimizer_config.best_checkpoint_file = ...
    defaults.best_checkpoint_file;

run(fullfile(script_dir, 'utils_HS', 'optimize_vHS_phase_lead.m'))

function config = mergeLocalStruct(config, override)
fields = fieldnames(override);
for field_id = 1:numel(fields)
    config.(fields{field_id}) = override.(fields{field_id});
end
end
