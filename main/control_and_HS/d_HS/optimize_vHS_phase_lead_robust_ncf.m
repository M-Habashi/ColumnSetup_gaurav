%% Optimize vHS phase_lead Robust To Specimen Damage (robust engine)
% Finds the multi-section phase_lead (each 1st-order section a lead OR a
% lag, optional 2nd-order notch sections, unity DC gain) that minimizes
% J4 on the healthy state subject to two hard constraints:
%   1. NCF margin on the healthy identified state >= nominal target
%   2. NCF margin on every damage scenario         >= robust target
% The damage scenarios follow the piecewise damage path through EVERY
% identified damage state listed in damage_states (ordered least ->
% most damaged), so the design keeps its margin as the specimen
% degrades instead of only at the initial state.
%
% == ADDING A FUTURE DAMAGE STATE (e.g. 3k or 1k) ======================
% When the new state has been identified (specimen file from
% a_specimen_id, exp_tf file from sys_id.m), append ONE entry to the
% damage_states list below, keeping the order least -> most damaged:
%
%   'damage_states', struct( ...
%       'label', {'5k', '3k', '1k'}, ...
%       'specimen_file', { ...
%           fullfile(project_root, 'saved_results', 'specimens', 'sp1_5000.mat'), ...
%           fullfile(project_root, 'saved_results', 'specimens', 'sp1_3000.mat'), ...
%           fullfile(project_root, 'saved_results', 'specimens', 'sp1_1000.mat')}, ...
%       'h_dc_dm_model_file', { ...
%           fullfile(project_root, 'saved_results', 'exp_tf', 'tf_sp1_5000_20260627_233333.mat'), ...
%           fullfile(project_root, 'saved_results', 'exp_tf', 'tf_sp1_3000_<stamp>.mat'), ...
%           fullfile(project_root, 'saved_results', 'exp_tf', 'tf_sp1_1000_<stamp>.mat')}), ...
%
% then re-run this script. The damage path gains one segment per state,
% the constraints cover the longer path, and the report/plots gain
% NCF/J4/Stable columns and markers for each identified state. Nothing
% else needs to change.
%
% Optional workspace overrides (same interface as the other scripts):
%   nominal_ncf_target / robust_ncf_target     the two NCF floors
%   minimum_stability_margin_override          closed-loop pole margin floor
%   section_count_override                     number of 1st-order sections
%   notch_count_override                       number of 2nd-order notches
%   specimen_file_override                     healthy specimen file
%   h_dc_dm_model_file_override                healthy exp_tf file
%   fem_file_override                          saved_results/fem file
%   pid_gain_override                          [P I D N] or struct
%   phase_lead_file_name_override              output MAT name
%   phase_lead_robust_config                   struct of engine options
%     (see defaultRobustConfig in utils_HS/optimize_vHS_phase_lead_robust.m;
%      e.g. damage_states, template_healthy_* for new specimens,
%      notch_frequency_bounds_hz, template_lambda_grid)

clearvars -except phase_lead_robust_config ...
    nominal_ncf_target robust_ncf_target section_count_override ...
    minimum_stability_margin_override notch_count_override ...
    fem_file_override specimen_file_override ...
    h_dc_dm_model_file_override pid_gain_override ...
    phase_lead_file_name_override; clc; close all;

script_dir = fileparts(mfilename('fullpath'));
addpath(fullfile(script_dir, 'utils_HS'));
project_root = fileparts(fileparts(script_dir));
addpath(fullfile(project_root, 'helpers', 'utils'));
addpath(fullfile(project_root, 'control_and_HS', 'c_fem_modeling', ...
    'utils_fem'));
addpath(fullfile(project_root, 'results_analysis'));
addpath(fullfile(project_root, 'control_and_HS', 'b_system_id', ...
    'id_utils'));
auth = 0.8;
config = struct( ...
    ... % --- primary tuning controls (edit in this order)
    'pid_gain_override', [0.15*auth 15*auth 0.0015*auth 512], ... % [] uses saved exp_tf PID; e.g. [0.15 20 0.0015 512]
    'target_ncf_margin', 0.40, ...
    'robust_ncf_target', 0.3, ...
    'phase_lead_section_count', 1, ...
    'notch_section_count', 1, ...
    'template_warp_scenarios', [0.9 1.1], ...
    'seed_phase_leads', {{}}, ...
    'minimum_coupled_pole_damping', 0.02, ...
    'coupled_pole_damping_band_hz', [7 16], ...
    'minimum_stability_margin', 1e-4, ...
    ... % --- model and record
    'specimen_file', fullfile(project_root, 'saved_results', ...
        'specimens', 'sp1_7000.mat'), ...
    'h_dc_dm_model_file', fullfile(project_root, 'saved_results', ...
        'exp_tf', 'tf_sp1_7000_20260627_210411.mat'), ...
    'fem_file', fullfile(project_root, 'saved_results', 'fem', ...
        'fem_sp1_7000.mat'), ...
    'template_healthy_specimen_file', fullfile(project_root, ...
        'saved_results', 'specimens', 'sp1_7000.mat'), ...
    'template_healthy_h_dc_dm_model_file', fullfile(project_root, ...
        'saved_results', 'exp_tf', 'tf_sp1_7000_20260627_210411.mat'), ...
    'damage_states', struct( ...
        'label', {'5k'}, ...
        'specimen_file', {fullfile(project_root, 'saved_results', ...
            'specimens', 'sp1_5000.mat')}, ...
        'h_dc_dm_model_file', {fullfile(project_root, 'saved_results', ...
            'exp_tf', 'tf_sp1_5000_20260627_233333.mat')}), ...
    ... % Recommended structure (see docs/phase_lead_robust_guide.html):
    ... % 1 lead + 1 notch, template warped +-10% so the notch cannot
    ... % overfit the measured resonance frequency. For the blunt but
    ... % maximally forgiving lead+lag instead, use section count 2,
    ... % notch count 0.
    'compare_phase_lead_files', ...
        {{'pl_7000_robust.mat', 'pl_7000_ncf40_v2.mat'}}, ...
    'phase_lead_file_name', 'pl_7000_robust_notch', ...
    'save_results', true, ...
    'save_best_checkpoint', true, ...
    'plot_results', true);

if exist('phase_lead_robust_config', 'var') ...
        && ~isempty(phase_lead_robust_config)
    override_fields = fieldnames(phase_lead_robust_config);
    for override_id = 1:numel(override_fields)
        config.(override_fields{override_id}) = ...
            phase_lead_robust_config.(override_fields{override_id});
    end
end

if exist('nominal_ncf_target', 'var') && ~isempty(nominal_ncf_target)
    config.target_ncf_margin = nominal_ncf_target;
end
if exist('robust_ncf_target', 'var') && ~isempty(robust_ncf_target)
    config.robust_ncf_target = robust_ncf_target;
end
if exist('minimum_stability_margin_override', 'var') ...
        && ~isempty(minimum_stability_margin_override)
    config.minimum_stability_margin = minimum_stability_margin_override;
end
if exist('section_count_override', 'var') ...
        && ~isempty(section_count_override)
    config.phase_lead_section_count = section_count_override;
end
if exist('notch_count_override', 'var') ...
        && ~isempty(notch_count_override)
    config.notch_section_count = notch_count_override;
end
if exist('fem_file_override', 'var') && ~isempty(fem_file_override)
    config.fem_file = fem_file_override;
end
if exist('specimen_file_override', 'var') ...
        && ~isempty(specimen_file_override)
    config.specimen_file = specimen_file_override;
end
if exist('h_dc_dm_model_file_override', 'var') ...
        && ~isempty(h_dc_dm_model_file_override)
    config.h_dc_dm_model_file = h_dc_dm_model_file_override;
end
if exist('pid_gain_override', 'var') && ~isempty(pid_gain_override)
    config.pid_gain_override = pid_gain_override;
end

fprintf('\nDefault files used by this optimization:\n')
fprintf('  Nominal NCF target: %.4g\n', config.target_ncf_margin)
fprintf('  Robust NCF target:  %.4g\n', config.robust_ncf_target)
fprintf('  Stability margin:   %.4g\n', config.minimum_stability_margin)
fprintf('  Healthy specimen: %s\n', config.specimen_file)
fprintf('  Healthy exp TF:   %s\n', config.h_dc_dm_model_file)
fprintf('  FEM:              %s\n', config.fem_file)
for damage_id = 1:numel(config.damage_states)
    fprintf('  Damage state %s specimen: %s\n', ...
        config.damage_states(damage_id).label, ...
        config.damage_states(damage_id).specimen_file)
    fprintf('  Damage state %s exp TF:   %s\n', ...
        config.damage_states(damage_id).label, ...
        config.damage_states(damage_id).h_dc_dm_model_file)
end
for seed_id = 1:numel(config.seed_phase_leads)
    fprintf('  Warm-start seed phase_lead: %s\n', ...
        config.seed_phase_leads{seed_id})
end
for compare_id = 1:numel(config.compare_phase_lead_files)
    fprintf('  Comparison phase_lead: %s\n', ...
        config.compare_phase_lead_files{compare_id})
end
if config.save_best_checkpoint
    fprintf(['  Best checkpoint: saved to saved_results\\phase_lead\\' ...
        'vHS_phase_lead_robust_best_checkpoint.mat unless overridden\n'])
end
fprintf(['Use the numbered file tree to choose the healthy specimen, ' ...
    'healthy exp TF, and FEM unless an override variable is set.\n\n'])

if ~exist('specimen_file_override', 'var') || isempty(specimen_file_override)
    fprintf('\nSelect healthy specimen file:\n')
    [~, config.specimen_file, ~] = load_saved_result_file( ...
        project_root, 'specimens');
end
if ~exist('h_dc_dm_model_file_override', 'var') ...
        || isempty(h_dc_dm_model_file_override)
    fprintf('\nSelect healthy experimental transfer-function file:\n')
    [~, config.h_dc_dm_model_file, ~] = load_saved_result_file( ...
        project_root, 'exp_tf');
end
if ~exist('fem_file_override', 'var') || isempty(fem_file_override)
    fprintf('\nSelect FEM file:\n')
    [~, config.fem_file, ~] = load_saved_result_file(project_root, 'fem');
end

config.phase_lead_file_name = '';
while isempty(config.phase_lead_file_name)
    config.phase_lead_file_name = strtrim(input( ...
        'Enter phase_lead output file name: ', 's'));
end

phase_lead_robust_result = optimize_vHS_phase_lead_robust(config);
