function bode
%BODE Plot closed-loop Bode magnitude and phase for controllers A, B, and C.
%   With the "scripted" folder on the MATLAB path, run this figure with:
%       bode
%
%   The horizontal axis is frequency in Hz.  This function intentionally
%   shadows Control System Toolbox's BODE command while the scripted folder
%   is on the path, so it uses FREQRESP to obtain the responses directly.

fs = 4096;                 % RTHS sampling frequency [Hz]
modified = 1;              % 1 = modified experimental mass/lead setup
bw_a = 70; pm_a = 70;      % Controller A: bandwidth [rad/s], PM [deg]
bw_b = 55; pm_b = 55;      % Controller B: bandwidth [rad/s], PM [deg]
bw_c = 40; pm_c = 60;      % Not used by custom C; compatibility only
[target_ncf_c, target_ncf_c_alpha] = ...
    scripted_controller_c_settings;
alphaDegraded = 0.5;       % Experimental stiffness ratio for dashed curves
frequencyHz = logspace(-1, 2, 3000);

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);

options = struct( ...
    'Building_c', 1, ...
    'plot_on', 'n', ...
    'modified', modified, ...
    'consider_damage', 1, ...
    'alpha_start', 1, ...
    'alpha_min', 0.5, ...
    'b_th', 0.13, ...
    'num_add', 0, ...
    'enable_indicator_plot', 0, ...
    'test_name', 'None', ...
    'fs', fs, ...
    'bw_a', bw_a, 'pm_a', pm_a, ...
    'bw_b', bw_b, 'pm_b', pm_b, ...
    'bw_c', bw_c, 'pm_c', pm_c, ...
    'target_ncf_c', target_ncf_c, ...
    'target_ncf_c_alpha', target_ncf_c_alpha, ...
    'start_c', 'C', ...
    'switch_on', 1);

p = scripted_build_trial(options, projectRoot, 1);
innerPlant = scripted_inner_open_loop(p.m_e, p.c_e, p.k_e);
plant = feedback(innerPlant, 1); % Inner unity-PID loop.
degradedStiffness = alphaDegraded * p.k_e;
degradedDamping = 2 * p.z_e * sqrt(degradedStiffness * p.m_e);
degradedInnerPlant = scripted_inner_open_loop(p.m_e, degradedDamping, ...
    degradedStiffness);
degradedPlant = feedback(degradedInnerPlant, 1); % Inner unity-PID loop.
closedLoopA = feedback(p.controller_a * plant, 1);
closedLoopB = feedback(p.controller_b * plant, 1);
closedLoopC = feedback(p.controller_c * plant, 1);
degradedClosedLoopA = feedback(p.controller_a * degradedPlant, 1);
degradedClosedLoopB = feedback(p.controller_b * degradedPlant, 1);
degradedClosedLoopC = feedback(p.controller_c * degradedPlant, 1);
omega = 2 * pi * frequencyHz;
responseA = squeeze(freqresp(closedLoopA, omega));
responseB = squeeze(freqresp(closedLoopB, omega));
responseC = squeeze(freqresp(closedLoopC, omega));
degradedResponseA = squeeze(freqresp(degradedClosedLoopA, omega));
degradedResponseB = squeeze(freqresp(degradedClosedLoopB, omega));
degradedResponseC = squeeze(freqresp(degradedClosedLoopC, omega));

figure('Name', 'Scripted controller Bode responses', 'Color', 'w');

subplot(2, 1, 1);
semilogx(frequencyHz, 20 * log10(abs(responseA)), 'LineWidth', 2, ...
    'Color', '#0a50a1'); hold on;
semilogx(frequencyHz, 20 * log10(abs(responseB)), 'LineWidth', 2, ...
    'Color', '#a9003c');
semilogx(frequencyHz, 20 * log10(abs(responseC)), 'LineWidth', 2, ...
    'Color', '#01746F');
semilogx(frequencyHz, 20 * log10(abs(degradedResponseA)), '--', ...
    'LineWidth', 2, 'Color', '#0a50a1');
semilogx(frequencyHz, 20 * log10(abs(degradedResponseB)), '--', ...
    'LineWidth', 2, 'Color', '#a9003c');
semilogx(frequencyHz, 20 * log10(abs(degradedResponseC)), '--', ...
    'LineWidth', 2, 'Color', '#01746F');
grid on; box on;
ylabel('Magnitude [dB]');
title('Closed-loop Bode response of the three scripted PI controllers');
legend({ ...
    sprintf('Controller A (BW %g rad/s, PM %g deg)', bw_a, pm_a), ...
    sprintf('Controller B (BW %g rad/s, PM %g deg)', bw_b, pm_b), ...
    sprintf('Controller C (NCF target %g at alpha %g)', ...
    target_ncf_c, target_ncf_c_alpha), ...
    sprintf('Controller A (alpha = %g)', alphaDegraded), ...
    sprintf('Controller B (alpha = %g)', alphaDegraded), ...
    sprintf('Controller C (alpha = %g)', alphaDegraded)}, ...
    'Location', 'best');

subplot(2, 1, 2);
semilogx(frequencyHz, unwrap(angle(responseA)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#0a50a1'); hold on;
semilogx(frequencyHz, unwrap(angle(responseB)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#a9003c');
semilogx(frequencyHz, unwrap(angle(responseC)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#01746F');
semilogx(frequencyHz, unwrap(angle(degradedResponseA)) * 180 / pi, '--', ...
    'LineWidth', 2, 'Color', '#0a50a1');
semilogx(frequencyHz, unwrap(angle(degradedResponseB)) * 180 / pi, '--', ...
    'LineWidth', 2, 'Color', '#a9003c');
semilogx(frequencyHz, unwrap(angle(degradedResponseC)) * 180 / pi, '--', ...
    'LineWidth', 2, 'Color', '#01746F');
grid on; box on;
xlabel('Frequency [Hz]');
ylabel('Phase [deg]');
end
