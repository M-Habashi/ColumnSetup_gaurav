function num_pl_cl
%NUM_PL_CL Plot G_num * G_PL * closed-loop Bode responses for A, B, and C.
%   With the "scripted" folder on the MATLAB path, run this figure with:
%       num_pl_cl
%   Each response is G_num(s) * G_PL(s) * C_i(s)G(s)/(1 + C_i(s)G(s)),
%   where G includes the inner unity-PID loop. Frequency is shown in Hz.

fs = 4096;                 % RTHS sampling frequency [Hz]
modified = 1;              % 1 = modified experimental mass/lead setup
bw_a = 70; pm_a = 70;      % Controller A: bandwidth [rad/s], PM [deg]
bw_b = 55; pm_b = 55;      % Controller B: bandwidth [rad/s], PM [deg]
bw_c = 40; pm_c = 60;      % Not used by custom C; compatibility only
[target_ncf_c, target_ncf_c_alpha] = ...
    scripted_controller_c_settings;
frequencyHz = logspace(-1, 2, 3000);

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);

options = struct( ...
    'Building_c', 1, ...
    'plot_on', 'n', ...
    'modified', modified, ...
    'consider_damage', 1, ...
    'alpha_start', 1, ...
    'alpha_min', 0.5, ...
    'b_th', 0.13, ...
    'num_add', 0, ...
    'enable_indicator_plot', 0, ...
    'test_name', 'None', ...
    'fs', fs, ...
    'bw_a', bw_a, 'pm_a', pm_a, ...
    'bw_b', bw_b, 'pm_b', pm_b, ...
    'bw_c', bw_c, 'pm_c', pm_c, ...
    'target_ncf_c', target_ncf_c, ...
    'target_ncf_c_alpha', target_ncf_c_alpha, ...
    'start_c', 'C', ...
    'switch_on', 1);

p = scripted_build_trial(options, projectRoot, 1);
innerPlant = scripted_inner_open_loop(p.m_e, p.c_e, p.k_e);
plant = feedback(innerPlant, 1); % Inner unity-PID loop.
G_num = p.G_num;

if modified == 1
    phaseLead = tf(31.6431547 * [1 49.3502225], [1 1657.846121]);
else
    phaseLead = tf(50.8316336027 * [1 168.6036181018], ...
        [1 8570.3973394443]);
end

responseA = G_num * phaseLead * feedback(p.controller_a * plant, 1);
responseB = G_num * phaseLead * feedback(p.controller_b * plant, 1);
responseC = G_num * phaseLead * feedback(p.controller_c * plant, 1);

omega = 2 * pi * frequencyHz;
responseA = squeeze(freqresp(responseA, omega));
responseB = squeeze(freqresp(responseB, omega));
responseC = squeeze(freqresp(responseC, omega));

figure('Name', 'Numerical and phase-lead weighted closed-loop Bode responses', ...
    'Color', 'w');

subplot(2, 1, 1);
semilogx(frequencyHz, 20 * log10(abs(responseA)), 'LineWidth', 2, ...
    'Color', '#0a50a1'); hold on;
semilogx(frequencyHz, 20 * log10(abs(responseB)), 'LineWidth', 2, ...
    'Color', '#a9003c');
semilogx(frequencyHz, 20 * log10(abs(responseC)), 'LineWidth', 2, ...
    'Color', '#01746F');
grid on; box on;
ylabel('Magnitude [dB]');
title('G_{num} G_{PL} weighted closed-loop Bode response');
legend({ ...
    sprintf('Controller A (BW %g rad/s, PM %g deg)', bw_a, pm_a), ...
    sprintf('Controller B (BW %g rad/s, PM %g deg)', bw_b, pm_b), ...
    sprintf('Controller C (NCF target %g at alpha %g)', ...
    target_ncf_c, target_ncf_c_alpha)}, ...
    'Location', 'best');

subplot(2, 1, 2);
semilogx(frequencyHz, unwrap(angle(responseA)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#0a50a1'); hold on;
semilogx(frequencyHz, unwrap(angle(responseB)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#a9003c');
semilogx(frequencyHz, unwrap(angle(responseC)) * 180 / pi, ...
    'LineWidth', 2, 'Color', '#01746F');
grid on; box on;
xlabel('Frequency [Hz]');
ylabel('Phase [deg]');
end
