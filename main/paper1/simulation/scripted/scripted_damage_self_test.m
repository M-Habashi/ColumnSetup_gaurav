function results = scripted_damage_self_test(projectRoot)
%SCRIPTED_DAMAGE_SELF_TEST Regression checks for both damage formulations.

if nargin == 0
    projectRoot = fileparts(fileparts(mfilename('fullpath')));
end

options = base_options;
modeZero = options;
modeZero.consider_damage = 0;
modeOne = options;
modeOne.consider_damage = 1;
modeOne.alpha_min = 0.5;
modeTwo = options;
modeTwo.consider_damage = 2;
modeTwo.alpha_min = NaN; % Must be ignored outside legacy mode.

modeOneMissingMinimum = rmfield(modeOne, 'alpha_min');
invalidBoucWen = modeTwo;
invalidBoucWen.n = 0.5;
invalidUy = modeTwo;
invalidUy.u_y = 0;
invalidDelta = modeTwo;
invalidDelta.delta_nu = -0.1;
invalidReferenceDeltaNu = modeTwo;
invalidReferenceDeltaNu.reference_delta_nu = -0.1;
invalidReferenceDeltaEta = modeTwo;
invalidReferenceDeltaEta.reference_delta_eta = Inf;
invalidQ = modeTwo;
invalidQ.q = 0;
invalidLseWindow = modeTwo;
invalidLseWindow.lse_window = 0;
partialPhaseLead = modeZero;
partialPhaseLead.lead_gain = 1;
invalidPhaseLead = modeZero;
invalidPhaseLead.lead_gain = 1;
invalidPhaseLead.lead_zero = 10;
invalidPhaseLead.lead_pole = 5;

rng('default');
p = scripted_build_trial(modeTwo, projectRoot, 1);
kInitial = p.alpha_start * p.k_e;
kReferenceInitial = p.alpha_start * p.KE(1, 1);
specimenInitialTangent = p.k_x_specimen + ...
    p.k_w_specimen;
referenceInitialTangent = p.k_x_reference + ...
    p.k_w_reference;

velocity = -0.12;
z = 0.3e-3;
energy = 2e-6;
nu = 1 + p.delta_nu * energy;
eta = 1 + p.delta_eta * energy;
expectedDerivative = (velocity - ...
    nu * p.beta_b * abs(velocity) * z * abs(z) ^ (p.n_bw - 1) - ...
    nu * p.gamma_b * velocity * abs(z) ^ p.n_bw) / eta;
oldWeight = (abs(z) / p.u_y) ^ p.q_damage;
expectedEnergyDerivative = oldWeight * z * velocity;
previousDisplacement = 0.2e-3;
currentDisplacement = 0.45e-3;
increment = currentDisplacement - previousDisplacement;
expectedZNew = z + (increment - ...
    nu * p.beta_b * abs(increment) * z * abs(z) ^ (p.n_bw - 1) - ...
    nu * p.gamma_b * increment * abs(z) ^ p.n_bw) / eta;
newWeight = (abs(expectedZNew) / p.u_y) ^ p.q_damage;
expectedEnergyNew = max(0, energy + ...
    0.5 * (oldWeight * z + newWeight * expectedZNew) * increment);
[actualZNew, actualEnergyNew] = blk_bouc_wen_update( ...
    currentDisplacement, previousDisplacement, z, energy, p);
referenceParameters = p;
referenceParameters.delta_nu = p.reference_delta_nu;
referenceParameters.delta_eta = p.reference_delta_eta;
referenceNu = 1 + referenceParameters.delta_nu * energy;
referenceEta = 1 + referenceParameters.delta_eta * energy;
expectedReferenceZNew = z + (increment - ...
    referenceNu * p.beta_b * abs(increment) * z * ...
        abs(z) ^ (p.n_bw - 1) - ...
    referenceNu * p.gamma_b * increment * abs(z) ^ p.n_bw) / ...
        referenceEta;
referenceNewWeight = ...
    (abs(expectedReferenceZNew) / p.u_y) ^ p.q_damage;
expectedReferenceEnergyNew = max(0, energy + 0.5 * ...
    (oldWeight * z + referenceNewWeight * expectedReferenceZNew) * ...
    increment);
[actualReferenceZNew, actualReferenceEnergyNew] = blk_bouc_wen_update( ...
    currentDisplacement, previousDisplacement, z, energy, ...
    referenceParameters);
[lseAlpha, lseStiffness, lseStartupHeld, lseLowExcitationHeld] = ...
    exact_lse_fit(p);
pNEqualsOne = p;
pNEqualsOne.n_bw = 1;

legacyParameters = p;
legacyParameters.options.consider_damage = 1;
legacyParameters.alpha_min = 0.2;
legacyTime = 100;
legacyAlpha = blk_damage_switch(legacyTime, 1, ...
    legacyParameters.alpha_min, legacyParameters.alpha_start);
referenceState = [0.01; -0.005; 0.003; 0.02; -0.01; 0.004];
legacyReferenceDerivative = blk_reference_dynamics(referenceState, 0.1, ...
    legacyAlpha, 0, legacyParameters);
frozenReferenceDerivative = legacyParameters.AA_R * referenceState + ...
    legacyParameters.BB_R * 0.1;
[legacyGround, legacyGroundMajor] = reversing_ground(legacyParameters, ...
    20, 0.2);
legacyTrial = scripted_engine(legacyParameters, legacyGround);
legacyFrozenReference = blk_reference_response(legacyParameters.sys_r, ...
    legacyGroundMajor, legacyGround.t - legacyGround.t(1));

[groundInput, groundMajor] = reversing_ground(p, 0, 2);
boucWenTrial = scripted_engine(p, groundInput);
linearReference = blk_reference_response(p.sys_r, groundMajor, ...
    groundInput.t);
linearSpecimenForce = kInitial * ...
    boucWenTrial.block_signals.x_internal;
linearReferenceForce = kReferenceInitial * boucWenTrial.Ref_Resp(:, 1);

analysisAtStart = scripted_coupled_damping_table(p);
analysisParameters = p;
analysisParameters.options.consider_damage = 0;
analysisParameters.alpha_min = -123;
analysisParameters.post_yield_ratio = 0.8;
analysisParameters.n_bw = 7;
analysisParameters.u_y_mm = 20;
analysisParameters.u_y = analysisParameters.u_y_mm / 1000;
analysisParameters.sigma = 0.9;
analysisParameters.beta_b = analysisParameters.sigma / ...
    analysisParameters.u_y ^ analysisParameters.n_bw;
analysisParameters.gamma_b = (1 - analysisParameters.sigma) / ...
    analysisParameters.u_y ^ analysisParameters.n_bw;
analysisParameters.delta_nu = 9e6;
analysisParameters.delta_eta = 8e6;
analysisUnaffected = scripted_coupled_damping_table(analysisParameters);

[readableDerivative, hotDerivative] = rhs_pair(p);
derivativeScale = max(1, norm(readableDerivative, inf));

checks = [ ...
    accepts(modeZero); ...
    accepts(modeOne); ...
    accepts(modeTwo); ...
    throws_id(modeOneMissingMinimum, 'scripted:MissingLegacyDamageOption'); ...
    throws_id(invalidBoucWen, 'scripted:BoucWenExponent'); ...
    throws_id(invalidUy, ...
        'scripted:BoucWenUY'); ...
    throws_id(invalidDelta, ...
        'scripted:BoucWenStrengthDegradation'); ...
    throws_id(invalidReferenceDeltaNu, ...
        'scripted:BoucWenReferenceStrengthDegradation'); ...
    throws_id(invalidReferenceDeltaEta, ...
        'scripted:BoucWenReferenceStiffnessDegradation'); ...
    throws_id(invalidQ, 'scripted:BoucWenDamageWeightExponent'); ...
    throws_id(invalidLseWindow, 'scripted:BoucWenLSEWindow'); ...
    throws_id(partialPhaseLead, 'scripted:MissingPhaseLeadOption'); ...
    throws_id(invalidPhaseLead, 'scripted:PhaseLeadParameters'); ...
    p.alpha_min == p.alpha_start; ...
    relative_error(p.u_y_mm, modeTwo.u_y) < 1e-14; ...
    relative_error(p.u_y, modeTwo.u_y / 1000) < 1e-14; ...
    relative_error(p.beta_b_per_mm_n, 0.129055507692) < 1e-12; ...
    relative_error(p.gamma_b_per_mm_n, 0.038716652308) < 1e-12; ...
    relative_error(p.delta_nu, 1e6 * modeTwo.delta_nu) < 1e-14; ...
    relative_error(p.delta_eta, 1e6 * modeTwo.delta_eta) < 1e-14; ...
    relative_error(p.reference_delta_nu, ...
        1e6 * modeTwo.reference_delta_nu) < 1e-14; ...
    relative_error(p.reference_delta_eta, ...
        1e6 * modeTwo.reference_delta_eta) < 1e-14; ...
    p.q_damage == modeTwo.q; ...
    p.lse_window == modeTwo.lse_window; ...
    p.lse_window_samples == round(modeTwo.lse_window * modeTwo.fs); ...
    relative_error(lseAlpha, 0.4) < 1e-12; ...
    relative_error(lseStiffness, 0.4 * p.k_e) < 1e-12; ...
    lseStartupHeld; ...
    lseLowExcitationHeld; ...
    blk_damage_switch(10, 2, NaN, p.alpha_start) == p.alpha_start; ...
    relative_error(specimenInitialTangent, kInitial) < 1e-14; ...
    relative_error(referenceInitialTangent, kReferenceInitial) < 1e-14; ...
    relative_error(p.k_x_specimen, ...
        p.post_yield_ratio * kInitial) < 1e-14; ...
    relative_error(p.k_x_reference, ...
        p.post_yield_ratio * kReferenceInitial) < 1e-14; ...
    derivative_matches(velocity, z, energy, p, expectedDerivative, ...
        expectedEnergyDerivative); ...
    relative_error(actualZNew, expectedZNew) < 1e-14; ...
    relative_error(actualEnergyNew, expectedEnergyNew) < 1e-14; ...
    relative_error(actualReferenceZNew, expectedReferenceZNew) < 1e-14; ...
    relative_error(actualReferenceEnergyNew, ...
        expectedReferenceEnergyNew) < 1e-14; ...
    abs(actualReferenceZNew - actualZNew) > 1e-12; ...
    nu > 1 && eta > 1; ...
    cyclic_degradation_reduces_strength(p); ...
    derivative_is_finite_at_origin(pNEqualsOne); ...
    norm(legacyReferenceDerivative - frozenReferenceDerivative, inf) > 1; ...
    legacyTrial.alpha.Data(1) < legacyParameters.alpha_start; ...
    max(abs(legacyTrial.Ref_Resp - legacyFrozenReference), [], 'all') > ...
        1e-7; ...
    all(isfinite(boucWenTrial.BoucWen.Data), 'all'); ...
    all(isfinite(boucWenTrial.BoucWen_energy.Data), 'all'); ...
    all(boucWenTrial.BoucWen_energy.Data >= 0, 'all'); ...
    max(boucWenTrial.BoucWen_energy.Data(:, 1)) > 0; ...
    max(boucWenTrial.BoucWen_energy.Data(:, 2)) > 0; ...
    max(abs(boucWenTrial.BoucWen.Data(:, 1))) > 1e-5; ...
    max(abs(boucWenTrial.BoucWen.Data(:, 2))) > 1e-5; ...
    max(abs(boucWenTrial.Restoring_force.Data(:, 1) - ...
        linearSpecimenForce)) > 1; ...
    max(abs(boucWenTrial.Restoring_force.Data(:, 2) - ...
        linearReferenceForce)) > 1; ...
    max(abs(boucWenTrial.Ref_Resp - linearReference), [], 'all') > 1e-7; ...
    all(isfinite(boucWenTrial.alpha.Data)); ...
    boucWenTrial.alpha.Data(1) == p.alpha_start; ...
    all(boucWenTrial.alpha.Data >= 0.001 & ...
        boucWenTrial.alpha.Data <= 1); ...
    max(abs(boucWenTrial.alpha.Data - p.alpha_start)) > 1e-3; ...
    all(isfinite(boucWenTrial.LSE_stiffness.Data)); ...
    indicator_tracks_lse_alpha(boucWenTrial, p); ...
    isequaln(analysisAtStart, analysisUnaffected); ...
    width(analysisAtStart) == 3; ...
    norm(readableDerivative - hotDerivative, inf) <= ...
        1e-12 * derivativeScale];

names = { ...
    'accept_no_damage'; ...
    'accept_legacy_damage'; ...
    'accept_degrading_bouc_wen'; ...
    'legacy_requires_alpha_min'; ...
    'reject_invalid_bouc_wen_n'; ...
    'reject_invalid_u_y'; ...
    'reject_negative_delta_nu'; ...
    'reject_negative_reference_delta_nu'; ...
    'reject_invalid_reference_delta_eta'; ...
    'reject_invalid_damage_weight_q'; ...
    'reject_invalid_lse_window'; ...
    'reject_partial_phase_lead_parameters'; ...
    'reject_invalid_phase_lead_parameters'; ...
    'alpha_min_ignored_in_bouc_wen'; ...
    'u_y_public_name'; ...
    'u_y_mm_to_m_conversion'; ...
    'u_y_sigma_to_beta_b'; ...
    'u_y_sigma_to_gamma_b'; ...
    'delta_nu_mm2_to_m2'; ...
    'delta_eta_mm2_to_m2'; ...
    'reference_delta_nu_mm2_to_m2'; ...
    'reference_delta_eta_mm2_to_m2'; ...
    'yield_proximity_exponent'; ...
    'lse_window_public_name'; ...
    'lse_window_sample_count'; ...
    'moving_lse_centered_slope'; ...
    'moving_lse_stiffness'; ...
    'moving_lse_waits_for_full_window'; ...
    'moving_lse_holds_without_excitation'; ...
    'bouc_wen_skips_legacy_profile'; ...
    'specimen_initial_tangent'; ...
    'reference_initial_tangent'; ...
    'specimen_post_yield_ratio'; ...
    'reference_post_yield_ratio'; ...
    'displayed_evolution_equation'; ...
    'major_sample_z_recurrence'; ...
    'trapezoidal_energy_recurrence'; ...
    'reference_major_sample_z_recurrence'; ...
    'reference_trapezoidal_energy_recurrence'; ...
    'reference_degradation_is_independent'; ...
    'degradation_multipliers_activate'; ...
    'cyclic_strength_degrades'; ...
    'finite_at_z_zero_n_one'; ...
    'legacy_reference_degrades_in_simulation'; ...
    'legacy_engine_uses_degraded_alpha'; ...
    'legacy_reference_not_frozen_lsim'; ...
    'finite_bouc_wen_states'; ...
    'finite_bouc_wen_energy'; ...
    'nonnegative_bouc_wen_energy'; ...
    'specimen_energy_accumulates'; ...
