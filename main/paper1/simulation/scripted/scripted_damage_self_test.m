function accepted = accepts(options)
try
    scripted_validate_options(options);
    accepted = true;
catch
    accepted = false;
end
end

function thrown = throws_id(options, expectedIdentifier)
try
    scripted_validate_options(options);
    thrown = false;
catch exception
    thrown = strcmp(exception.identifier, expectedIdentifier);
end
end

function value = relative_error(actual, expected)
value = abs(actual - expected) / max(1, abs(expected));
end

function [alpha, stiffness, startupHeld, lowExcitationHeld] = ...
        exact_lse_fit(p)
fitParameters = p;
fitParameters.lse_window_samples = 4;
fitState = [];
displacement = (0:4).' * 1e-3;
force = 0.4 * p.k_e * displacement + 123;
startupHeld = true;
for sample = 1:numel(displacement)
    [alpha, stiffness, fitState] = blk_moving_lse_stiffness( ...
        displacement(sample), force(sample), fitState, fitParameters);
    if sample < fitParameters.lse_window_samples
        startupHeld = startupHeld && alpha == p.alpha_start;
    end
end

lowState = [];
lowExcitationHeld = true;
lowDisplacement = (0:3).' * (0.001 * p.u_y);
lowForce = -3 * p.k_e * lowDisplacement + 100;
for sample = 1:numel(lowDisplacement)
    [lowAlpha, ~, lowState] = blk_moving_lse_stiffness( ...
        lowDisplacement(sample), lowForce(sample), lowState, fitParameters);
    lowExcitationHeld = lowExcitationHeld && ...
        lowAlpha == p.alpha_start;
end
end

function matches = indicator_tracks_lse_alpha(trial, p)
% The 100-tick slow task publishes at one boundary and holds the alpha-based
% value calculated at the preceding boundary.
calculationSample = 101;
publicationSample = 201;
if height(trial.alpha.Data) < publicationSample
    matches = false;
    return
end
expected = blk_indicator_margin( ...
    trial.alpha.Data(calculationSample), ...
    trial.beta.Data(calculationSample), p, p.use_c);
matches = abs(trial.indicator.Data(publicationSample) - expected) < 1e-12;
end

function matches = derivative_matches(velocity, z, energy, p, ...
        expectedZDerivative, expectedEnergyDerivative)
[actualZDerivative, actualEnergyDerivative] = ...
    blk_bouc_wen_derivative(velocity, z, energy, p);
matches = relative_error(actualZDerivative, expectedZDerivative) < 1e-14 && ...
    relative_error(actualEnergyDerivative, expectedEnergyDerivative) < 1e-14;
end

function finite = derivative_is_finite_at_origin(p)
[zDerivative, energyDerivative] = blk_bouc_wen_derivative(1, 0, 0, p);
finite = isfinite(zDerivative) && isfinite(energyDerivative);
end

function degraded = cyclic_degradation_reduces_strength(p)
displacement = 2e-3 * sin(linspace(0, 16 * pi, 4097)).';
noDegradation = p;
noDegradation.delta_nu = 0;
noDegradation.delta_eta = 0;
zDegraded = 0;
energyDegraded = 0;
zFixed = 0;
energyFixed = 0;
forceDegraded = zeros(size(displacement));
forceFixed = zeros(size(displacement));
for sample = 2:numel(displacement)
    [zDegraded, energyDegraded] = blk_bouc_wen_update( ...
        displacement(sample), displacement(sample - 1), ...
        zDegraded, energyDegraded, p);
    [zFixed, energyFixed] = blk_bouc_wen_update( ...
        displacement(sample), displacement(sample - 1), ...
        zFixed, energyFixed, noDegradation);
    forceDegraded(sample) = blk_bouc_wen_restoring_force( ...
        displacement(sample), zDegraded, p.k_e, p);
    forceFixed(sample) = blk_bouc_wen_restoring_force( ...
        displacement(sample), zFixed, p.k_e, noDegradation);
end
lastCycle = (numel(displacement) - 512):numel(displacement);
degraded = energyDegraded > 0 && ...
    max(abs(forceDegraded(lastCycle))) < max(abs(forceFixed(lastCycle)));
end

function [groundInput, major] = reversing_ground(p, startTime, duration)
time = (startTime:p.dt_rths:startTime + duration).';
halfTime = time(1:end-1) + p.dt_rths / 2;
amplitude = 0.5;
frequency = 3;
major = amplitude * sin(2 * pi * frequency * (time - startTime));
half = amplitude * sin(2 * pi * frequency * (halfTime - startTime));
groundInput = struct('t', time, 'major', major, 'half', half);
end

function [readableDerivative, hotDerivative] = rhs_pair(p)
state = linspace(-2e-3, 2e-3, 24).';
state(21:22) = [0.2e-3; -0.15e-3];
state(23:24) = [2e-6; 1e-6];
time = 1;
estimatedVelocity = 0.025;
held = struct( ...
    'noise_displacement', 2e-7, ...
    'phase_output', 1e-3, ...
    'tracking_output', -2e-3, ...
    'force_delay', 10, ...
    'switch_target', -1, ...
    'event_time', 0, ...
    'step_time', time, ...
    'previous_time', time - p.dt_rths, ...
    'current_x', state(10), ...
    'previous_x', state(10) - estimatedVelocity * p.dt_rths);
readableDerivative = scripted_rhs(state, time, 0.2, held, p);
hotDerivative = scripted_rhs_hot(state, time, 0.2, ...
    held.phase_output, held.tracking_output, held.noise_displacement, ...
    held.force_delay, held.switch_target, held.event_time, ...
    estimatedVelocity, p);
end
