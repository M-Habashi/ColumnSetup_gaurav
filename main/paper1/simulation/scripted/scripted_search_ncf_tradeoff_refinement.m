function trials = scripted_search_ncf_tradeoff_refinement
%SCRIPTED_SEARCH_NCF_TRADEOFF_REFINEMENT Fine A tradeoff-boundary study.

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir)
outputDir = fullfile(projectRoot, 'Results', ...
    'ncf_performance_tradeoff_search');
seedPath = fullfile(outputDir, 'full_seed_trials.csv');
trialPath = fullfile(outputDir, 'refinement_trials.csv');
if ~isfile(seedPath)
    error('scripted:TradeoffSeedsMissing', ...
        'Run scripted_search_ncf_tradeoff_seed_trials first.')
end
seedTrials = readtable(seedPath);
bSeed = seedTrials(seedTrials.PairID == 5, :);
[lastRun, ~] = scripted_last_run_configuration(projectRoot);
options = lastRun.Options;
options.plot_on = 'n';
options.num_add = 0;
options.enable_indicator_plot = 0;
options.switch_on = 0;
options.bw_b = 60;
options.pm_b = 55;
pBase = scripted_build_trial(options, projectRoot, 1);
[groundInput.t, groundInput.major, groundInput.half] = ...
    blk_ground_acceleration(pBase);

bandwidthA = [(75.2:0.2:76.2).'; 75.5];
phaseMarginA = 140 - bandwidthA;
candidateCount = numel(bandwidthA);
if isfile(trialPath)
    trials = readtable(trialPath);
else
    trials = table;
end

plant = scripted_inner_open_loop(pBase.m_e, pBase.c_e, ...
    pBase.alpha_start * pBase.k_e);
trackingPlant = feedback(plant, 1);
controllerB = pidtune(trackingPlant, 'PI', options.bw_b, ...
    pidtuneOptions('PhaseMargin', options.pm_b));
pBase.controller_b = controllerB;
pBase.pi_b_kp = controllerB.Kp;
pBase.pi_b_ki = controllerB.Ki;
bCurve = scripted_ncf_curve_metrics(pBase, controllerB, 1:-0.01:0);
bDamping = scripted_phase_lead_metrics(pBase, 'B', 1);

for index = 1:candidateCount
    if ~isempty(trials) && ismember(index, trials.CandidateID)
        continue
    end
    fprintf('Tradeoff refinement %d/%d: A BW %.3f, PM %.3f\n', ...
        index, candidateCount, bandwidthA(index), phaseMarginA(index))
    controllerA = pidtune(trackingPlant, 'PI', bandwidthA(index), ...
        pidtuneOptions('PhaseMargin', phaseMarginA(index)));
    p = pBase;
    p.controller_a = controllerA;
    p.pi_a_kp = controllerA.Kp;
    p.pi_a_ki = controllerA.Ki;
    p.start_c = 'A';
    p.start_a = true;
    p.use_c = false;
    p.switch_on = false;
    aCurve = scripted_ncf_curve_metrics(p, controllerA, 1:-0.01:0);
    aDamping = scripted_phase_lead_metrics(p, 'A', 1);
    trial = scripted_engine(p, groundInput);
    evaluation = blk_evaluation(trial, p.dt_rths);
    finiteA = all(isfinite(evaluation)) && ...
        all(isfinite(trial.X_m.Data), 'all') && ...
        all(isfinite(trial.Force_act.Data), 'all') && ...
        all(isfinite(trial.PI_command.Data), 'all');
    j4A = evaluation(4);
    j4B = bSeed.J4_B_pct;
    ratio = j4B / j4A;
    maxForceA = max(abs(trial.Force_act.Data), [], 'all');
    j4Difference = j4B - j4A;
    accepted = finiteA && aCurve.MonotonicDecrease && ...
        aCurve.CollapseAlpha >= 0.15 && aCurve.CollapseAlpha <= 0.30 && ...
        bCurve.MonotonicDecrease && bCurve.NCFAlphaPointOne > 0 && ...
        aDamping.DampingPercent > 6 && bDamping.DampingPercent > 6 && ...
        j4A <= 33 && j4Difference >= 5 && ...
        maxForceA < 8900 && bSeed.MaxForce_B_N < 8900;
    row = table(index, bandwidthA(index), phaseMarginA(index), ...
        controllerA.Kp, controllerA.Ki, options.bw_b, options.pm_b, ...
        controllerB.Kp, controllerB.Ki, options.lead_gain, ...
        options.lead_zero, options.lead_pole, aCurve.NCFAlpha1, ...
        aCurve.CollapseAlpha, bCurve.NCFAlpha1, ...
        bCurve.NCFAlphaPointOne, bCurve.NCFAlphaZero, ...
        aDamping.DampingPercent, bDamping.DampingPercent, j4A, j4B, ...
        ratio, j4Difference, maxForceA, bSeed.MaxForce_B_N, finiteA, ...
        accepted, ...
        'VariableNames', {'CandidateID', 'BW_A_rad_s', 'PM_A_deg', ...
        'KpA', 'KiA', 'BW_B_rad_s', 'PM_B_deg', 'KpB', 'KiB', ...
        'LeadGain', 'LeadZero_rad_s', 'LeadPole_rad_s', ...
        'NCF_A_alpha1', 'NCF_A_collapse_alpha', 'NCF_B_alpha1', ...
        'NCF_B_alpha_point_one', 'NCF_B_alpha_zero', ...
        'DampingA_pct', 'DampingB_pct', 'J4_A_pct', 'J4_B_pct', ...
        'J4Ratio_B_over_A', 'J4Difference_pp', 'MaxForce_A_N', ...
        'MaxForce_B_N', ...
        'FiniteA', 'Accepted'});
    trials = [trials; row]; %#ok<AGROW>
    writetable(trials, trialPath)
end
end
