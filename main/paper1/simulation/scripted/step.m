function step
%STEP Plot unit-step responses for the scripted controllers A, B, and C.
%   With the "scripted" folder on the MATLAB path, run this figure with:
%       step
%
%   This command intentionally shadows Control System Toolbox's STEP
%   function while the scripted folder is on the path.  The responses below
%   are calculated with LSIM so the entry point cannot call itself.

% Match the default controller-design settings in SCRIPTED_MAIN.
fs = 4096;                 % RTHS sampling frequency [Hz]
modified = 1;              % 1 = modified experimental mass/lead setup
bw_a = 70; pm_a = 70;      % Controller A: bandwidth [rad/s], PM [deg]
bw_b = 55; pm_b = 55;      % Controller B: bandwidth [rad/s], PM [deg]
bw_c = 40; pm_c = 60;      % Not used by custom C; compatibility only
[target_ncf_c, target_ncf_c_alpha] = ...
    scripted_controller_c_settings;

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);

options = struct( ...
    'Building_c', 1, ...
    'plot_on', 'n', ...
    'modified', modified, ...
    'consider_damage', 1, ...
    'alpha_start', 1, ...
    'alpha_min', 0.5, ...
    'b_th', 0.13, ...
    'num_add', 0, ...
    'enable_indicator_plot', 0, ...
    'test_name', 'None', ...
    'fs', fs, ...
    'bw_a', bw_a, 'pm_a', pm_a, ...
    'bw_b', bw_b, 'pm_b', pm_b, ...
    'bw_c', bw_c, 'pm_c', pm_c, ...
    'target_ncf_c', target_ncf_c, ...
    'target_ncf_c_alpha', target_ncf_c_alpha, ...
    'start_c', 'C', ...
    'switch_on', 1);

p = scripted_build_trial(options, projectRoot, 1);
innerPlant = scripted_inner_open_loop(p.m_e, p.c_e, p.k_e);
plant = feedback(innerPlant, 1); % Inner unity-PID loop.
closedLoopA = feedback(p.controller_a * plant, 1);
closedLoopB = feedback(p.controller_b * plant, 1);
closedLoopC = feedback(p.controller_c * plant, 1);

% Set the horizontal extent from the slowest closed-loop settling time.
settlingTimes = [stepinfo(closedLoopA).SettlingTime, ...
    stepinfo(closedLoopB).SettlingTime, ...
    stepinfo(closedLoopC).SettlingTime];
settlingTimes = settlingTimes(isfinite(settlingTimes) & settlingTimes > 0);
if isempty(settlingTimes)
    error('scripted:StepResponseNotSettled', ...
        'At least one controller response must have a finite settling time.');
end
t_end = ceil(max(settlingTimes) * 1.05 / p.dt_rths) * p.dt_rths;

t = (0:p.dt_rths:t_end).';
unitStep = ones(size(t));
yA = lsim(closedLoopA, unitStep, t);
yB = lsim(closedLoopB, unitStep, t);
yC = lsim(closedLoopC, unitStep, t);

figure('Name', 'Scripted controller step responses', 'Color', 'w');
plot(t, unitStep, 'k--', 'LineWidth', 1.2); hold on; grid on;
plot(t, yA, 'LineWidth', 2, 'Color', '#0a50a1');
plot(t, yB, 'LineWidth', 2, 'Color', '#a9003c');
plot(t, yC, 'LineWidth', 2, 'Color', '#01746F');
xlim([0 t_end]);
xlabel('Time [s]');
ylabel('Amplitude');
title('Unit-step response of the three scripted PI controllers');
legend({'Reference', ...
    sprintf('Controller A (BW %g rad/s, PM %g deg)', bw_a, pm_a), ...
    sprintf('Controller B (BW %g rad/s, PM %g deg)', bw_b, pm_b), ...
    sprintf('Controller C (NCF target %g at alpha %g)', ...
    target_ncf_c, target_ncf_c_alpha)}, ...
    'Location', 'southeast');
end
