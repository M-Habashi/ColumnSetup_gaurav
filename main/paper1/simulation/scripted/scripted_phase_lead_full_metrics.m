 function result = scripted_phase_lead_full_metrics(options, projectRoot, ...
    leadGain, leadZero, leadPole, runFullSimulation)
%SCRIPTED_PHASE_LEAD_FULL_METRICS Evaluate one lead for controllers A and B.

arguments
    options (1,1) struct
    projectRoot (1,:) char
    leadGain (1,1) double {mustBeFinite, mustBePositive}
    leadZero (1,1) double {mustBeFinite, mustBePositive}
    leadPole (1,1) double {mustBeFinite, mustBePositive}
    runFullSimulation (1,1) logical = true
end

options.lead_gain = leadGain;
options.lead_zero = leadZero;
options.lead_pole = leadPole;
options.start_c = 'A';
options.switch_on = 0;

p = scripted_build_trial(options, projectRoot, 1);
dampingA = scripted_phase_lead_metrics(p, 'A', p.alpha_start);
dampingB = scripted_phase_lead_metrics(p, 'B', p.alpha_start);

result = struct( ...
    'LeadGain', leadGain, ...
    'LeadZero_rad_s', leadZero, ...
    'LeadPole_rad_s', leadPole, ...
    'DCGain', leadGain * leadZero / leadPole, ...
    'PoleZeroRatio', leadPole / leadZero, ...
    'DampingA_pct', dampingA.DampingPercent, ...
    'DampingB_pct', dampingB.DampingPercent, ...
    'SpectralRadiusA', dampingA.SpectralRadius, ...
    'SpectralRadiusB', dampingB.SpectralRadius, ...
    'StableA', dampingA.Stable, ...
    'StableB', dampingB.Stable, ...
    'FullEvaluated', false, ...
    'FullFiniteA', false, ...
    'FullFiniteB', false, ...
    'J1_A_ms', NaN, ...
    'J1_B_ms', NaN, ...
    'J4_A_pct', NaN, ...
    'J4_B_pct', NaN, ...
    'MaxForce_A_N', NaN, ...
    'MaxForce_B_N', NaN, ...
    'MaxCommand_A_mm', NaN, ...
    'MaxCommand_B_mm', NaN);

if ~runFullSimulation
    return
end

[trialA, evaluationA] = runController(p, 'A');
[trialB, evaluationB] = runController(p, 'B');
result.FullEvaluated = true;
result.FullFiniteA = trialIsFinite(trialA, evaluationA);
result.FullFiniteB = trialIsFinite(trialB, evaluationB);
result.J1_A_ms = evaluationA(1);
result.J1_B_ms = evaluationB(1);
result.J4_A_pct = evaluationA(4);
result.J4_B_pct = evaluationB(4);
result.MaxForce_A_N = max(abs(trialA.Force_act.Data), [], 'all');
result.MaxForce_B_N = max(abs(trialB.Force_act.Data), [], 'all');
result.MaxCommand_A_mm = 1000 * ...
    max(abs(trialA.PI_command.Data), [], 'all');
result.MaxCommand_B_mm = 1000 * ...
    max(abs(trialB.PI_command.Data), [], 'all');
end

function [trial, evaluation] = runController(p, controllerName)
p.start_c = controllerName;
p.start_a = controllerName == 'A';
p.use_c = false;
p.switch_on = false;
trial = scripted_engine(p);
evaluation = blk_evaluation(trial, p.dt_rths);
end

function finite = trialIsFinite(trial, evaluation)
finite = all(isfinite(evaluation)) && ...
    all(isfinite(trial.X_m.Data), 'all') && ...
    all(isfinite(trial.Force_act.Data), 'all') && ...
    all(isfinite(trial.PI_command.Data), 'all');
end
