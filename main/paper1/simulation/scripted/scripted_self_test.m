function results = scripted_self_test(projectRoot)
%SCRIPTED_SELF_TEST Deterministic SLX-free regression of the first 60 ms.

if nargin == 0
    projectRoot = fileparts(fileparts(mfilename('fullpath')));
end
fs = 4096; % Deterministic regression sampling frequency [Hz].
options = struct('Building_c', 1, 'plot_on', 'n', 'modified', 1, ...
    'consider_damage', 0, 'alpha_start', 1, 'alpha_min', 0.5, ...
    'b_th', 0.13, 'num_add', 0, ...
    'enable_indicator_plot', 0, 'test_name', 'self_test', 'fs', fs, ...
    'bw_a', 80, 'pm_a', 60, 'bw_b', 60, 'pm_b', 60, ...
    'bw_c', 40, 'pm_c', 60, 'target_ncf_c', 0.46, ...
    'target_ncf_c_alpha', 1, ...
    'start_c', 'A', 'switch_on', 1);

rng('default');
p = scripted_build_trial(options, projectRoot, 1);
p.tend = 0.06;
trial = scripted_engine(p);
repeatTrial = scripted_engine(p);
coupledDamping = scripted_coupled_damping_table(p);
controllerCharacteristics = scripted_controller_characteristics_table( ...
    p, [1; 2; 3]);

activeA = true;
switchTarget = -1;
eventTime = 0;
aboveStart = NaN;
[activeA, switchTarget, eventTime, aboveStart, switchedToB] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    aboveStart, 0.2, 0.1, 1, 0.13, 0.15, 2, true);
activeAfterB = activeA;
targetAfterB = switchTarget;
[activeA, switchTarget, eventTime, aboveStart] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    aboveStart, 0.1, 0.16, 2, 0.13, 0.15, 2, true);
[activeA, switchTarget, eventTime, aboveStart] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    aboveStart, 0.16, 0.14, 3, 0.13, 0.15, 2, true);
timerReset = isnan(aboveStart);
[activeA, switchTarget, eventTime, aboveStart] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    aboveStart, 0.14, 0.16, 4, 0.13, 0.15, 2, true);
[activeA, switchTarget, eventTime, ~, switchedToA] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    aboveStart, 0.16, 0.16, 6, 0.13, 0.15, 2, true);
activeAfterA = activeA;
targetAfterA = switchTarget;
timeAfterA = eventTime;
[activeA, switchTarget, eventTime, ~, switchedAgainToB] = ...
    blk_controller_switch_update(activeA, switchTarget, eventTime, ...
    NaN, 0.16, 0.1, 7, 0.13, 0.15, 2, true);

checks = [p.fs == fs; ...
    p.gain == 1; ...
    p.lead_gain == 31.6431547; ...
    p.lead_zero == 49.3502225; ...
    p.lead_pole == 1657.846121; ...
    abs(p.c_e / (2 * sqrt(p.KE(1, 1) * p.m_e)) - p.z_e) < 1e-14; ...
    norm(p.K_r - (p.KN + p.alpha_start * p.KE), 'fro') < 1e-10; ...
    norm(p.sys_r.A - p.AA_R, 'fro') < 1e-12; ...
    numel(trial.t) == 246; ...
    trial.t(end) == 245 / fs; ...
    isequal(trial.Force_act.Data, repeatTrial.Force_act.Data); ...
    isequal(trial.X_m.Data, repeatTrial.X_m.Data); ...
    isfinite(trial.indicator.Data(101)); ...
    all(trial.indicator.Data(1:100) == 0); ...
    isfinite(trial.indicator_a.Data(101)); ...
    isfinite(trial.indicator_b.Data(101)); ...
    all(trial.active_controller_a.Data == 1); ...
    all(trial.switch_event.Data == 0); ...
    all(isfinite(trial.Num_resp.Data), 'all'); ...
    height(coupledDamping) == 3; ...
    width(coupledDamping) == 3; ...
    all(isfinite(coupledDamping{:, 2:end}), 'all'); ...
    height(controllerCharacteristics) == 3; ...
    width(controllerCharacteristics) == 6; ...
    all(isfinite(controllerCharacteristics{:, 2:end}), 'all'); ...
    controllerCharacteristics.P_gain(3) == p.controller_c.Kp; ...
    controllerCharacteristics.I_gain(3) == p.controller_c.Ki; ...
    isequal(controllerCharacteristics.MaxPICommandDisplacement_mm, ...
    [1; 2; 3]); ...
    p.controller_c_report.Feasible; ...
    p.controller_c_report.NCFTolerance == 0.01; ...
    p.controller_c_report.NCFError <= p.controller_c_report.NCFTolerance; ...
    p.controller_c_report.MinimumBandwidth == 20; ...
    p.controller_c_report.Bandwidth >= ...
    p.controller_c_report.MinimumBandwidth; ...
    p.controller_c_report.Alpha == options.target_ncf_c_alpha; ...
    all(trial.beta.Data == 1); ...
    blk_beta_value(-1, 0, 0, 'B', 1) == 0; ...
    blk_beta_value(0, 10, 0, 'A', 0) == 1; ...
    blk_beta_value(1, 10, 0, 'B', 0) == 0; ...
    abs(blk_beta_value(0, 0.125, 0, 'A', 1) - 0.5) < 1e-12 && ...
        blk_beta_value(0, 0.25, 0, 'A', 1) == 0; ...
    abs(blk_beta_value(1, 0.125, 0, 'B', 1) - 0.5) < 1e-12 && ...
        blk_beta_value(1, 0.25, 0, 'B', 1) == 1; ...
    switchedToB && ~activeAfterB && targetAfterB == 0; ...
    timerReset; ...
    switchedToA && activeAfterA && targetAfterA == 1 && timeAfterA == 6; ...
    switchedAgainToB && ~activeA && switchTarget == 0 && eventTime == 7; ...
    blk_damage_switch(0, 0, 0.5, 0.9) == 0.9; ...
    abs(blk_alpha_profile(100, 0.35, 0.9) - 0.35) < 1e-12; ...
    isnan(blk_beta_value(-1, 0, 0, 'C', 1)); ...
    blk_controller_select(1, 2, 3, 0.5, 'C') == 3];
names = {'sampling_frequency'; 'unity_command_gain'; ...
    'default_phase_lead_gain'; 'default_phase_lead_zero'; ...
    'default_phase_lead_pole'; ...
    'modified_experimental_damping_ratio'; 'initial_reference_stiffness'; ...
    'reported_reference_system'; 'sample_count'; ...
    'final_time'; 'repeatable_actuator_force'; ...
    'repeatable_measured_displacement'; 'finite_indicator_value'; ...
    'indicator_rate_hold'; 'finite_controller_a_ncf'; ...
    'finite_controller_b_ncf'; 'initial_active_controller'; ...
    'no_spurious_switch_event'; 'finite_numerical_response'; ...
    'coupled_damping_rows'; 'coupled_damping_columns'; ...
    'finite_coupled_damping'; 'controller_characteristics_rows'; ...
    'controller_characteristics_columns'; ...
    'finite_controller_characteristics'; 'controller_c_p_gain'; ...
    'controller_c_i_gain'; 'controller_command_maxima'; ...
    'controller_c_tune_feasible'; ...
    'controller_c_ncf_tolerance_value'; ...
    'controller_c_ncf_tolerance'; ...
    'controller_c_minimum_bandwidth_value'; ...
    'controller_c_minimum_bandwidth'; 'controller_c_ncf_alpha'; ...
    'default_controller_a'; ...
    'start_controller_b'; 'switch_disabled_a'; 'switch_disabled_b'; ...
    'switch_a_to_b'; 'switch_b_to_a'; 'repeatable_switch_to_b'; ...
    'switch_return_timer_reset'; 'repeatable_switch_to_a'; ...
    'repeatable_second_switch_to_b'; ...
    'initial_stiffness_switch'; ...
    'minimum_stiffness'; ...
    'controller_c_beta'; 'controller_c_select'};
results = table(names, checks, 'VariableNames', {'Check', 'Passed'});
assert(all(checks), 'scripted:SelfTest', ...
    'One or more scripted runtime regression checks failed.')
end
