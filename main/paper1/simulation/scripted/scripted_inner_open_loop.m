function system = scripted_inner_open_loop(mass, damping, stiffness)
%SCRIPTED_INNER_OPEN_LOOP Pure-MATLAB copy of the fifth-order inner plant.

a1 = 2.1283e13;
a2 = 4.2297e6;
a3 = 3.3;
b1 = 425;
b2 = 9.9976e4;

denominator = [mass, ...
    damping + mass * (a3 + b1), ...
    stiffness + (a3 + b1) * damping + a2 + mass * (b1 * a3 + b2), ...
    stiffness * (a3 + b1) + damping * (b1 * a3 + b2) + ...
        b1 * a2 + b2 * a3 * mass, ...
    stiffness * (b1 * a3 + b2) + b2 * a3 * damping + b2 * a2, ...
    b2 * a3 * stiffness];
system = tf(a1, denominator);
end
