function batch = scripted_run_all_paper_cases()
%SCRIPTED_RUN_ALL_PAPER_CASES Run Cases I--IV and preserve their settings.
%   Full signal trajectories and per-case summaries are written to Results.
%   A batch MAT file and human-readable CSV record the inputs and output
%   paths required to identify and reproduce this group of runs.

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
batchId = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));

base = struct( ...
    'Building_c', 1, ...
    'plot_on', 'n', ...
    'modified', 1, ...
    'alpha_start', 1, ...
    'alpha_min', 0.4, ...
    'post_yield_ratio', 0.001, ...
    'n', 8, ...
    'u_y', 1.5, ...
    'sigma', 0.769230769230769, ...
    'delta_nu', 0.03, ...
    'delta_eta', 0.03, ...
    'reference_delta_nu', 0.05, ...
    'reference_delta_eta', 0.05, ...
    'q', 10, ...
    'lse_window', 0.5, ...
    'lead_gain', 31.6431547, ...
    'lead_zero', 49.3502225, ...
    'lead_pole', 1657.846121, ...
    'b_th', 0.15, ...
    'b_th_2', 0.185, ...
    'switch_back_hold', 2, ...
    'switch_transition_duration', 0.25, ...
    'num_add', 0, ...
    'enable_indicator_plot', 0, ...
    'fs', 4096, ...
    'bw_a', 70, ...
    'pm_a', 70, ...
    'bw_b', 55, ...
    'pm_b', 55, ...
    'bw_c', 40, ...
    'pm_c', 60, ...
    'target_ncf_c', 0.40, ...
    'target_ncf_c_alpha', 1, ...
    'consider_damage', 0, ...
    'start_c', 'A', ...
    'switch_on', 0, ...
    'run_name', '', ...
    'test_name', '', ...
    'run_title', '');

caseSettings = repmat(base, 4, 1);
caseTitles = ["Case I"; "Case II"; "Case III"; "Case IV"];
damageModes = [0; 0; 2; 2];
startControllers = ["A"; "B"; "A"; "A"];
switchFlags = [0; 0; 0; 1];

signalFiles = strings(4, 1);
summaryFiles = strings(4, 1);
metrics = zeros(4, 9);
switchTimes = nan(4, 1);

for caseIndex = 1:4
    options = caseSettings(caseIndex);
    options.consider_damage = damageModes(caseIndex);
    options.start_c = char(startControllers(caseIndex));
    options.switch_on = switchFlags(caseIndex);
    options.run_name = sprintf('paper_rerun_%s_case_%02d', ...
        batchId, caseIndex);
    options.test_name = options.run_name;
    options.run_title = char(caseTitles(caseIndex));
    caseSettings(caseIndex) = options;

    fprintf('\nRunning %s (%d of 4)...\n', caseTitles(caseIndex), caseIndex);
    output = scripted_run(options, projectRoot);
    signalFiles(caseIndex) = string(output.ResultFiles{1});
    summaryFiles(caseIndex) = string(output.SummaryFile);
    metrics(caseIndex, :) = output.eval_crit;
    if isfield(output, 'switch_event') && isa(output.switch_event, 'timeseries')
        eventIndex = find(output.switch_event.Data(:) ~= 0, 1, 'first');
        if ~isempty(eventIndex)
            switchTimes(caseIndex) = output.switch_event.Time(eventIndex);
        end
    end
end

caseNumber = (1:4)';
settings = table(caseNumber, caseTitles, damageModes, startControllers, ...
    switchFlags, repmat(base.fs, 4, 1), signalFiles, summaryFiles, ...
    switchTimes, 'VariableNames', {'CaseNumber', 'CaseTitle', ...
    'DamageMode', 'StartController', 'SwitchEnabled', 'SampleRate_Hz', ...
    'SignalFile', 'SummaryFile', 'SwitchTime_s'});
for metricIndex = 1:9
    settings.(sprintf('J%d', metricIndex)) = metrics(:, metricIndex);
end

resultsDir = fullfile(projectRoot, 'Results');
settingsCsv = fullfile(resultsDir, ...
    sprintf('paper_rerun_%s_settings.csv', batchId));
settingsMat = fullfile(resultsDir, ...
    sprintf('paper_rerun_%s_settings.mat', batchId));
writetable(settings, settingsCsv);

batch = struct( ...
    'BatchId', batchId, ...
    'CreatedAt', datetime('now'), ...
    'MatlabVersion', version, ...
    'ProjectRoot', projectRoot, ...
    'EntryPoint', mfilename('fullpath'), ...
    'BaseSettings', base, ...
    'CaseSettings', caseSettings, ...
    'Results', settings, ...
    'SettingsCsv', settingsCsv, ...
    'SettingsMat', settingsMat);
save(settingsMat, 'batch');

disp(settings)
fprintf('\nBatch settings MAT: %s\n', settingsMat);
fprintf('Batch settings CSV: %s\n', settingsCsv);
end
