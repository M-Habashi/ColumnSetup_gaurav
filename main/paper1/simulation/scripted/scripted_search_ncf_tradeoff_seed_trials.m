function trials = scripted_search_ncf_tradeoff_seed_trials
%SCRIPTED_SEARCH_NCF_TRADEOFF_SEED_TRIALS Full nonlinear seed evaluations.
%   Evaluates curve-qualified A/B pairs with the current shared phase lead
%   and checkpoints each result to CSV.

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir)
outputDir = fullfile(projectRoot, 'Results', ...
    'ncf_performance_tradeoff_search');
gridPath = fullfile(outputDir, 'controller_grid.csv');
trialPath = fullfile(outputDir, 'full_seed_trials.csv');
if ~isfile(gridPath)
    error('scripted:TradeoffGridMissing', ...
        'Run scripted_search_ncf_tradeoff_controller_grid first.')
end
controllerGrid = readtable(gridPath);
[lastRun, ~] = scripted_last_run_configuration(projectRoot);
if isempty(lastRun)
    error('scripted:TradeoffNeedsSnapshot', ...
        'Run scripted_main successfully before starting the search.')
end

% IDs refer to the deterministic controller_grid.csv. These combinations
% span the performance-side A curve and robust-side B curve boundary.
pairSpecs = table((1:5).', [96; 80; 64; 96; 80], ...
    [42; 42; 42; 43; 43], 'VariableNames', ...
    {'PairID', 'AControllerID', 'BControllerID'});
if isfile(trialPath)
    trials = readtable(trialPath);
else
    trials = table;
end

for index = 1:height(pairSpecs)
    pairID = pairSpecs.PairID(index);
    if ~isempty(trials) && ismember(pairID, trials.PairID)
        continue
    end
    a = controllerGrid(controllerGrid.CandidateID == ...
        pairSpecs.AControllerID(index), :);
    b = controllerGrid(controllerGrid.CandidateID == ...
        pairSpecs.BControllerID(index), :);
    options = lastRun.Options;
    options.bw_a = a.TargetBandwidth_rad_s;
    options.pm_a = a.TargetPhaseMargin_deg;
    options.bw_b = b.TargetBandwidth_rad_s;
    options.pm_b = b.TargetPhaseMargin_deg;
    fprintf(['Full tradeoff seed %d/%d: A %.3g/%.3g, ', ...
        'B %.3g/%.3g\n'], index, height(pairSpecs), options.bw_a, ...
        options.pm_a, options.bw_b, options.pm_b)
    result = scripted_phase_lead_full_metrics(options, projectRoot, ...
        options.lead_gain, options.lead_zero, options.lead_pole, true);
    j4Difference = result.J4_B_pct - result.J4_A_pct;
    accepted = a.ACurveMatch && b.BCurveMatch && ...
        result.FullFiniteA && result.FullFiniteB && ...
        result.DampingA_pct > 6 && result.DampingB_pct > 6 && ...
        result.J4_A_pct <= 33 && j4Difference >= 5 && ...
        result.J4_B_pct <= 40 && result.MaxForce_A_N < 8900 && ...
        result.MaxForce_B_N < 8900;
    row = [pairSpecs(index, :) table( ...
        a.TargetBandwidth_rad_s, a.TargetPhaseMargin_deg, a.NCFAlpha1, ...
        a.CollapseAlpha, b.TargetBandwidth_rad_s, ...
        b.TargetPhaseMargin_deg, b.NCFAlpha1, b.NCFAlphaPointOne, ...
        b.NCFAlphaZero, result.DampingA_pct, result.DampingB_pct, ...
        result.J4_A_pct, result.J4_B_pct, ...
        result.J4_B_pct / result.J4_A_pct, j4Difference, ...
        result.MaxForce_A_N, ...
        result.MaxForce_B_N, result.FullFiniteA, result.FullFiniteB, ...
        accepted, ...
        'VariableNames', {'BW_A_rad_s', 'PM_A_deg', 'NCF_A_alpha1', ...
        'NCF_A_collapse_alpha', 'BW_B_rad_s', 'PM_B_deg', ...
        'NCF_B_alpha1', 'NCF_B_alpha_point_one', 'NCF_B_alpha_zero', ...
        'DampingA_pct', 'DampingB_pct', 'J4_A_pct', 'J4_B_pct', ...
        'J4Ratio_B_over_A', 'J4Difference_pp', 'MaxForce_A_N', ...
        'MaxForce_B_N', 'FiniteA', 'FiniteB', 'Accepted'})];
    trials = [trials; row]; %#ok<AGROW>
    writetable(trials, trialPath)
end
end
