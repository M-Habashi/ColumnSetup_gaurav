function result = margins_evolve(exportFigure)
%MARGINS_EVOLVE Regenerate manuscript Figure 5 from scripted parameters.
%   The figure plots outer-loop Bode responses as stiffness degrades.
%   MARGINS_EVOLVE uses Controller A and the configuration saved by the
%   latest completed SCRIPTED_MAIN run. The solid curves show the outer
%   open loop at alpha = 1 and 0.3. Dotted magnitude segments show
%   gain margins, while dashed phase segments show the primary phase
%   margins at the lowest-frequency unity-gain crossover.
%
%   MARGINS_EVOLVE(false) opens the figure without exporting it.

if nargin < 1
    exportFigure = true;
end

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);

[lastRun, configurationPath] = ...
    scripted_last_run_configuration(projectRoot);
if isempty(lastRun)
    error('scripted:NoLastRunConfiguration', ...
        ['Run scripted_main before margins_evolve so the figure uses ', ...
        'a saved controller and configuration snapshot.']);
end

p = scripted_build_trial(lastRun.Options, projectRoot, 1);
p.controller_a = controller_from_record(lastRun.ControllerA);

alphaValues = [1, 0.3];
colors = {'#1A1A1A', '#8B1E1E'};
frequencyHz = logspace(-1, 2, 3000);
omega = 2 * pi * frequencyHz;
curveCount = numel(alphaValues);
magnitudeDb = nan(curveCount, numel(frequencyHz));
phaseDeg = nan(curveCount, numel(frequencyHz));
gainMarginDb = nan(1, curveCount);
gainMarginFrequencyHz = nan(1, curveCount);
phaseMarginDeg = nan(1, curveCount);
phaseMarginFrequencyHz = nan(1, curveCount);
closedLoopStable = false(1, curveCount);

for index = 1:curveCount
    alpha = alphaValues(index);
    stiffness = alpha * p.k_e;
    damping = 2 * p.z_e * sqrt(stiffness * p.m_e);
    trackingPlant = feedback(scripted_inner_open_loop( ...
        p.m_e, damping, stiffness), 1);
    outerOpenLoop = p.controller_a * trackingPlant;

    response = squeeze(freqresp(outerOpenLoop, omega));
    magnitudeDb(index, :) = 20 * log10(abs(response));
    phaseDeg(index, :) = unwrap(angle(response)) * 180 / pi;

    marginData = select_primary_margins(allmargin(outerOpenLoop));
    gainMarginDb(index) = marginData.GainMarginDb;
    gainMarginFrequencyHz(index) = ...
        marginData.GainMarginFrequency / (2 * pi);
    phaseMarginDeg(index) = marginData.PhaseMargin;
    phaseMarginFrequencyHz(index) = ...
        marginData.PhaseMarginFrequency / (2 * pi);
    closedLoopStable(index) = marginData.Stable;
end

fig = plot_margin_evolution(frequencyHz, magnitudeDb, phaseDeg, ...
    alphaValues, colors, gainMarginDb, gainMarginFrequencyHz, ...
    phaseMarginDeg, phaseMarginFrequencyHz);

outputPath = fullfile(projectRoot, 'Results', ...
    'scripted_outer_loop_margin_evolution.png');
if exportFigure
    export_tight_800_dpi(fig, outputPath);
    fprintf('Figure 5 PNG: %s\n', outputPath);
end

marginTable = table(alphaValues(:), closedLoopStable(:), ...
    gainMarginDb(:), gainMarginFrequencyHz(:), phaseMarginDeg(:), ...
    phaseMarginFrequencyHz(:), ...
    'VariableNames', {'Alpha', 'ClosedLoopStable', 'GainMargin_dB', ...
    'GainMarginFrequency_Hz', 'PrimaryPhaseMargin_deg', ...
    'PhaseMarginFrequency_Hz'});
fprintf('\nController A outer-loop margin evolution\n');
fprintf('Configuration: %s\n', configurationPath);
disp(marginTable)
fprintf(['The phase values are the primary margins at the ', ...
    'lowest-frequency unity-gain crossover.\n\n']);

result = struct( ...
    'ConfigurationSource', string(configurationPath), ...
    'ControllerA', lastRun.ControllerA, ...
    'Alpha', alphaValues, ...
    'FrequencyHz', frequencyHz, ...
    'MagnitudeDb', magnitudeDb, ...
    'PhaseDeg', phaseDeg, ...
    'GainMarginDb', gainMarginDb, ...
    'GainMarginFrequencyHz', gainMarginFrequencyHz, ...
    'PrimaryPhaseMarginDeg', phaseMarginDeg, ...
    'PhaseMarginFrequencyHz', phaseMarginFrequencyHz, ...
    'ClosedLoopStable', closedLoopStable, ...
    'MarginTable', marginTable, ...
    'Figure', fig, ...
    'FigurePath', string(outputPath));
end

function selected = select_primary_margins(allMargins)
gainRatio = allMargins.GainMargin(:);
gainFrequency = allMargins.GMFrequency(:);
validGain = isfinite(gainRatio) & gainRatio > 0 & ...
    isfinite(gainFrequency) & gainFrequency > 0;
if any(validGain)
    gainRatio = gainRatio(validGain);
    gainFrequency = gainFrequency(validGain);
    gainDb = mag2db(gainRatio);
    [~, gainIndex] = min(abs(gainDb));
    selectedGainDb = gainDb(gainIndex);
    selectedGainFrequency = gainFrequency(gainIndex);
else
    selectedGainDb = Inf;
    selectedGainFrequency = NaN;
end

phaseMargin = allMargins.PhaseMargin(:);
phaseFrequency = allMargins.PMFrequency(:);
validPhase = isfinite(phaseMargin) & isfinite(phaseFrequency) & ...
    phaseFrequency > 0;
if any(validPhase)
    phaseMargin = phaseMargin(validPhase);
    phaseFrequency = phaseFrequency(validPhase);
    [~, phaseIndex] = min(phaseFrequency);
    selectedPhaseMargin = phaseMargin(phaseIndex);
    selectedPhaseFrequency = phaseFrequency(phaseIndex);
else
    selectedPhaseMargin = NaN;
    selectedPhaseFrequency = NaN;
end

selected = struct( ...
    'GainMarginDb', selectedGainDb, ...
    'GainMarginFrequency', selectedGainFrequency, ...
    'PhaseMargin', selectedPhaseMargin, ...
    'PhaseMarginFrequency', selectedPhaseFrequency, ...
    'Stable', logical(allMargins.Stable));
end

function fig = plot_margin_evolution(frequencyHz, magnitudeDb, phaseDeg, ...
        alphaValues, colors, gainMarginDb, gainMarginFrequencyHz, ...
        phaseMarginDeg, phaseMarginFrequencyHz)
figWidth = 6.27;
figHeight = 2.75;
fontName = 'Times New Roman';
fontSize = 9;
curveLineWidth = 1.25;
marginLineWidth = 1.15;

fig = figure('Name', 'Outer-loop margin evolution', ...
    'Units', 'inches', 'Position', [1 1 figWidth figHeight], ...
    'Color', 'w');
layout = tiledlayout(fig, 1, 2, 'TileSpacing', 'compact', ...
    'Padding', 'compact');

axMagnitude = nexttile(layout, 1);
configure_axes(axMagnitude, fontName, fontSize);
hold(axMagnitude, 'on');
yline(axMagnitude, 0, '-', 'Color', [0.55 0.55 0.55], ...
    'LineWidth', 0.6, 'HandleVisibility', 'off');
magnitudeHandles = gobjects(1, numel(alphaValues));
magnitudeLabels = cell(1, numel(alphaValues));
for index = 1:numel(alphaValues)
    magnitudeHandles(index) = semilogx(axMagnitude, frequencyHz, ...
        magnitudeDb(index, :), '-', 'Color', colors{index}, ...
        'LineWidth', curveLineWidth);
    if isfinite(gainMarginFrequencyHz(index)) && ...
            isfinite(gainMarginDb(index))
        semilogx(axMagnitude, ...
            gainMarginFrequencyHz(index) * [1 1], ...
            [-gainMarginDb(index), 0], ':', ...
            'Color', colors{index}, 'LineWidth', marginLineWidth, ...
            'HandleVisibility', 'off');
        plot(axMagnitude, gainMarginFrequencyHz(index), ...
            -gainMarginDb(index), 'o', 'Color', colors{index}, ...
            'MarkerFaceColor', 'w', 'MarkerSize', 3.5, ...
            'HandleVisibility', 'off');
    end
    magnitudeLabels{index} = sprintf( ...
        '$\\alpha=%.1f$: $GM=%.2f$ dB', ...
        alphaValues(index), gainMarginDb(index));
end
xlim(axMagnitude, [1, 100]);
ylim(axMagnitude, [-15, 35]);
xlabel(axMagnitude, 'Frequency [Hz]', 'Interpreter', 'latex');
ylabel(axMagnitude, 'Magnitude [dB]', 'Interpreter', 'latex');
title(axMagnitude, 'Magnitude and gain margin', ...
    'FontName', fontName, 'FontSize', fontSize, ...
    'FontWeight', 'normal');
legend(axMagnitude, magnitudeHandles, magnitudeLabels, ...
    'Interpreter', 'latex', 'FontName', fontName, ...
    'FontSize', fontSize - 1, 'Location', 'northwest');
hold(axMagnitude, 'off');

axPhase = nexttile(layout, 2);
configure_axes(axPhase, fontName, fontSize);
hold(axPhase, 'on');
yline(axPhase, -180, '-', 'Color', [0.55 0.55 0.55], ...
    'LineWidth', 0.6, 'HandleVisibility', 'off');
phaseHandles = gobjects(1, numel(alphaValues));
phaseLabels = cell(1, numel(alphaValues));
for index = 1:numel(alphaValues)
    phaseHandles(index) = semilogx(axPhase, frequencyHz, ...
        phaseDeg(index, :), '-', 'Color', colors{index}, ...
        'LineWidth', curveLineWidth);
    if isfinite(phaseMarginFrequencyHz(index)) && ...
            isfinite(phaseMarginDeg(index))
        semilogx(axPhase, ...
            phaseMarginFrequencyHz(index) * [1 1], ...
            [-180, -180 + phaseMarginDeg(index)], '--', ...
            'Color', colors{index}, 'LineWidth', marginLineWidth, ...
            'HandleVisibility', 'off');
        plot(axPhase, phaseMarginFrequencyHz(index), ...
            -180 + phaseMarginDeg(index), 'o', ...
            'Color', colors{index}, 'MarkerFaceColor', 'w', ...
            'MarkerSize', 3.5, 'HandleVisibility', 'off');
    end
    phaseLabels{index} = sprintf( ...
        '$\\alpha=%.1f$: $PM=%.2f^{\\circ}$', ...
        alphaValues(index), phaseMarginDeg(index));
end
xlim(axPhase, [1, 100]);
ylim(axPhase, [-190, -40]);
xlabel(axPhase, 'Frequency [Hz]', 'Interpreter', 'latex');
ylabel(axPhase, 'Phase [$^{\circ}$]', 'Interpreter', 'latex');
title(axPhase, 'Phase and primary phase margin', ...
    'FontName', fontName, 'FontSize', fontSize, ...
    'FontWeight', 'normal');
legend(axPhase, phaseHandles, phaseLabels, ...
    'Interpreter', 'latex', 'FontName', fontName, ...
    'FontSize', fontSize - 1, 'Location', 'northwest');
hold(axPhase, 'off');
end

function configure_axes(ax, fontName, fontSize)
set(ax, 'XScale', 'log', 'TickLabelInterpreter', 'latex', ...
    'FontName', fontName, 'FontSize', fontSize, ...
    'GridColor', [0.7 0.7 0.7], 'GridLineStyle', '--', ...
    'GridAlpha', 1, 'MinorGridAlpha', 0.35, ...
    'LineWidth', 0.5, 'Box', 'on', 'Layer', 'bottom');
grid(ax, 'on');
end

function export_tight_800_dpi(fig, outputPath)
drawnow;
figureWidth = fig.Position(3);
exportgraphics(fig, outputPath, 'Resolution', 800, ...
    'Units', 'inches', 'Width', figureWidth, 'Padding', 0, ...
    'PreserveAspectRatio', 'on');
end

function controller = controller_from_record(record)
controller = pid(record.Kp, record.Ki, record.Kd, record.Tf);
end
