function [results, controllerResults] = tables(options)
%TABLES Print robustness and local PI data for controllers A, B, and C.
%   [ROBUSTNESS, CONTROLLERS] = TABLES prints the NCF/coupled-damping table
%   followed by P gain, I gain, bandwidth, and phase margin. TABLES(OPTIONS)
%   accepts a complete scripted_run-compatible options structure.

if nargin < 1
    [targetNCFC, targetNCFCAlpha] = scripted_controller_c_settings;
    options = struct( ...
        'Building_c', 1, ...
        'plot_on', 'n', ...
        'modified', 1, ...
        'consider_damage', 0, ...
        'alpha_start', 1, ...
        'alpha_min', 0.5, ...
        'b_th', 0.13, ...
        'num_add', 0, ...
        'enable_indicator_plot', 0, ...
        'test_name', 'None', ...
        'fs', 4096, ...
        'bw_a', 80, 'pm_a', 60, ...
        'bw_b', 60, 'pm_b', 60, ...
        'bw_c', 40, 'pm_c', 60, ...
        'target_ncf_c', targetNCFC, ...
        'target_ncf_c_alpha', targetNCFCAlpha, ...
        'start_c', 'C', ...
        'switch_on', 0);
end

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);

if ~isfield(options, 'alpha_start')
    options.alpha_start = 1;
end
scripted_validate_options(options);
parameters = scripted_build_trial(options, projectRoot, 1);
results = scripted_coupled_damping_table(parameters);
[maximumCommand, ~] = scripted_command_maxima_cache( ...
    projectRoot, parameters);
controllerResults = scripted_controller_characteristics_table( ...
    parameters, maximumCommand);
end
