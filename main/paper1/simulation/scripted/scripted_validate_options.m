function scripted_validate_options(options)
%SCRIPTED_VALIDATE_OPTIONS Validate scripted_main-compatible parameters.

required = {'Building_c', 'plot_on', 'modified', 'consider_damage', ...
    'b_th', 'num_add', 'enable_indicator_plot', 'test_name', 'fs', ...
    'bw_a', 'pm_a', 'bw_b', 'pm_b', 'bw_c', 'pm_c', ...
    'start_c', 'switch_on'};
missing = required(~isfield(options, required));
if ~isempty(missing)
    error('scripted:MissingOption', 'Missing option(s): %s', ...
        strjoin(missing, ', '));
end
if ~(ischar(options.test_name) || ...
        (isstring(options.test_name) && isscalar(options.test_name)))
    error('scripted:RunName', 'test_name must be a character vector or string scalar.')
end
if isfield(options, 'run_name') && ...
        ~(ischar(options.run_name) || ...
        (isstring(options.run_name) && isscalar(options.run_name)))
    error('scripted:RunName', 'run_name must be a character vector or string scalar.')
end
if isfield(options, 'run_title') && ...
        ~(ischar(options.run_title) || ...
        (isstring(options.run_title) && isscalar(options.run_title)))
    error('scripted:RunTitle', ...
        'run_title must be a character vector or string scalar.')
end
if ~isscalar(options.Building_c) || ~ismember(options.Building_c, 1:4)
    error('scripted:BuildingCase', 'Building_c must be an integer from 1 to 4.')
end
if ~isBinaryScalar(options.modified) || ...
        ~isIntegerChoice(options.consider_damage, 0:2)
    error('scripted:BooleanOption', ...
        ['modified must be 0 or 1; consider_damage must be 0 (none), ' ...
        '1 (legacy), or 2 (degrading Bouc-Wen).'])
end
if isfield(options, 'alpha_start')
    alphaStart = options.alpha_start;
else
    alphaStart = 1;
end
if ~isFiniteScalar(alphaStart) || alphaStart < 0 || alphaStart > 1
    error('scripted:InitialStiffness', ...
        'alpha_start must be a finite real scalar from 0 to 1.')
end
if options.consider_damage == 1
    if ~isfield(options, 'alpha_min')
        error('scripted:MissingLegacyDamageOption', ...
            'Legacy damage mode requires alpha_min.')
    end
    if ~isFiniteScalar(options.alpha_min) || options.alpha_min < 0 || ...
            options.alpha_min > 0.75
        error('scripted:MinimumStiffness', ...
            ['In legacy damage mode, alpha_min must be a finite real ' ...
            'scalar from 0 to 0.75.'])
    end
    if options.alpha_min > alphaStart
        error('scripted:StiffnessRange', ...
            ['In legacy damage mode, alpha_min must be less than or ' ...
            'equal to alpha_start.'])
    end
end
if options.consider_damage == 2
    boucWenRequired = {'post_yield_ratio', 'n', 'u_y', 'sigma', ...
        'delta_nu', 'delta_eta', 'q', 'lse_window'};
    missingBoucWen = boucWenRequired(~isfield(options, boucWenRequired));
    if ~isempty(missingBoucWen)
        error('scripted:MissingBoucWenOption', ...
            'Missing degrading Bouc-Wen option(s): %s', ...
            strjoin(missingBoucWen, ', '));
    end
    if ~isFiniteScalar(options.post_yield_ratio) || ...
            options.post_yield_ratio < 0 || ...
            options.post_yield_ratio >= 1
        error('scripted:BoucWenPostYieldRatio', ...
            ['post_yield_ratio must be a finite real scalar [-] from ' ...
            '0 (inclusive) to 1 (exclusive).'])
    end
    if ~isFiniteScalar(options.n) || options.n < 1
        error('scripted:BoucWenExponent', ...
            'n must be a finite real scalar [-] greater than or equal to 1.')
    end
    if ~isFiniteScalar(options.u_y) || options.u_y <= 0
        error('scripted:BoucWenUY', ...
            'u_y must be a positive finite real scalar in mm.')
    end
    if ~isFiniteScalar(options.sigma) || options.sigma <= 0 || ...
            options.sigma >= 1
        error('scripted:BoucWenSigma', ...
            'sigma must be a finite real scalar strictly between 0 and 1.')
    end
    if ~isFiniteScalar(options.delta_nu) || options.delta_nu < 0
        error('scripted:BoucWenStrengthDegradation', ...
            'delta_nu must be a nonnegative finite real scalar in mm^-2.')
    end
    if ~isFiniteScalar(options.delta_eta) || options.delta_eta < 0
        error('scripted:BoucWenStiffnessDegradation', ...
            'delta_eta must be a nonnegative finite real scalar in mm^-2.')
    end
    if isfield(options, 'reference_delta_nu') && ...
            (~isFiniteScalar(options.reference_delta_nu) || ...
            options.reference_delta_nu < 0)
        error('scripted:BoucWenReferenceStrengthDegradation', ...
            ['reference_delta_nu must be a nonnegative finite real ', ...
             'scalar in mm^-2.'])
    end
    if isfield(options, 'reference_delta_eta') && ...
            (~isFiniteScalar(options.reference_delta_eta) || ...
            options.reference_delta_eta < 0)
        error('scripted:BoucWenReferenceStiffnessDegradation', ...
            ['reference_delta_eta must be a nonnegative finite real ', ...
             'scalar in mm^-2.'])
    end
    if ~isFiniteScalar(options.q) || options.q <= 0
        error('scripted:BoucWenDamageWeightExponent', ...
            'q must be a positive finite real scalar.')
    end
    if ~isFiniteScalar(options.lse_window) || options.lse_window <= 0 || ...
            ~isFiniteScalar(options.fs) || options.fs <= 0 || ...
            round(options.lse_window * options.fs) < 2 || ...
            round(options.lse_window * options.fs) > 65536
        error('scripted:BoucWenLSEWindow', ...
            ['lse_window must be a positive duration in seconds that ', ...
            'produces 2 to 65536 samples at fs.'])
    end
end
if isfield(options, 'target_ncf_c') && ...
        (~isFiniteScalar(options.target_ncf_c) || ...
        options.target_ncf_c <= 0 || options.target_ncf_c >= 1)
    error('scripted:ControllerCNcfTarget', ...
        'target_ncf_c must be a finite scalar strictly between 0 and 1.')
end
if isfield(options, 'target_ncf_c_alpha') && ...
        (~isFiniteScalar(options.target_ncf_c_alpha) || ...
        options.target_ncf_c_alpha < 0 || options.target_ncf_c_alpha > 1)
    error('scripted:ControllerCNcfAlpha', ...
        'target_ncf_c_alpha must be a finite scalar from 0 to 1.')
end
phaseLeadFields = {'lead_gain', 'lead_zero', 'lead_pole'};
providedPhaseLead = isfield(options, phaseLeadFields);
if any(providedPhaseLead) && ~all(providedPhaseLead)
    error('scripted:MissingPhaseLeadOption', ...
        'lead_gain, lead_zero, and lead_pole must be provided together.')
end
if all(providedPhaseLead) && ...
        (~isFiniteScalar(options.lead_gain) || options.lead_gain <= 0 || ...
        ~isFiniteScalar(options.lead_zero) || options.lead_zero <= 0 || ...
        ~isFiniteScalar(options.lead_pole) || ...
        options.lead_pole <= options.lead_zero)
    error('scripted:PhaseLeadParameters', ...
        ['lead_gain and lead_zero must be positive finite scalars, and ', ...
        'lead_pole must be finite and greater than lead_zero.'])
end
if ~isscalar(options.num_add) || options.num_add < 0 || ...
        options.num_add ~= floor(options.num_add)
    error('scripted:TrialCount', 'num_add must be a nonnegative integer.')
end
if ~isnumeric(options.fs) || ~isreal(options.fs) || ~isscalar(options.fs) || ...
        ~isfinite(options.fs) || options.fs <= 0
    error('scripted:SamplingFrequency', ...
        'fs must be a positive, finite real scalar in Hz.')
end
if ~isFiniteScalar(options.bw_a) || options.bw_a <= 0 || ...
        ~isFiniteScalar(options.bw_b) || options.bw_b <= 0 || ...
        ~isFiniteScalar(options.bw_c) || options.bw_c <= 0
    error('scripted:ControllerBandwidth', ...
        'bw_a, bw_b, and bw_c must be positive finite scalars in rad/s.')
end
if ~isFiniteScalar(options.pm_a) || options.pm_a <= 0 || ...
        options.pm_a >= 180 || ~isFiniteScalar(options.pm_b) || ...
        options.pm_b <= 0 || options.pm_b >= 180 || ...
        ~isFiniteScalar(options.pm_c) || options.pm_c <= 0 || ...
        options.pm_c >= 180
    error('scripted:ControllerPhaseMargin', ...
        'pm_a, pm_b, and pm_c must be between 0 and 180 degrees.')
end
if ~(ischar(options.start_c) && isrow(options.start_c) && ...
        isscalar(options.start_c)) && ...
        ~(isstring(options.start_c) && isscalar(options.start_c) && ...
        strlength(options.start_c) == 1)
    error('scripted:StartController', 'start_c must be ''A'', ''B'', or ''C''.')
end
if ~ismember(upper(char(options.start_c)), {'A', 'B', 'C'})
    error('scripted:StartController', 'start_c must be ''A'', ''B'', or ''C''.')
end
if ~isFiniteScalar(options.b_th) || options.b_th < 0 || options.b_th >= 1
    error('scripted:SwitchThreshold', ...
        'b_th must be a finite real scalar from 0 (inclusive) to 1 (exclusive).')
end
if isfield(options, 'b_th_2') && ...
        (~isFiniteScalar(options.b_th_2) || options.b_th_2 <= options.b_th || ...
        options.b_th_2 > 1)
    error('scripted:SwitchReturnThreshold', ...
        'b_th_2 must be finite, greater than b_th, and no greater than 1.')
end
if isfield(options, 'switch_back_hold') && ...
        (~isFiniteScalar(options.switch_back_hold) || ...
        options.switch_back_hold <= 0)
    error('scripted:SwitchReturnHold', ...
        'switch_back_hold must be a positive finite duration in seconds.')
end
if isfield(options, 'switch_transition_duration') && ...
        (~isFiniteScalar(options.switch_transition_duration) || ...
        options.switch_transition_duration <= 0)
    error('scripted:SwitchTransitionDuration', ...
        'switch_transition_duration must be a positive finite duration in seconds.')
end
if ~(isnumeric(options.switch_on) || islogical(options.switch_on)) || ...
        ~isreal(options.switch_on) || ~isscalar(options.switch_on) || ...
        ~ismember(options.switch_on, [0 1])
    error('scripted:SwitchOption', 'switch_on must be 0 or 1.')
end
if ~ismember(lower(options.plot_on), {'y', 'n'})
    error('scripted:PlotOption', 'plot_on must be ''y'' or ''n''.')
end
end

function valid = isFiniteScalar(value)
valid = isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value);
end

function valid = isBinaryScalar(value)
valid = (isnumeric(value) || islogical(value)) && isreal(value) && ...
    isscalar(value) && ismember(value, [0 1]);
end

function valid = isIntegerChoice(value, choices)
valid = (isnumeric(value) || islogical(value)) && isreal(value) && ...
    isscalar(value) && isfinite(value) && ismember(value, choices);
end
