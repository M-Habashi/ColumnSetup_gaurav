function comparison = scripted_compare_evaluation_definitions(resultPath, outputPath)
%SCRIPTED_COMPARE_EVALUATION_DEFINITIONS Verify code J metrics against paper definitions.
%   The paper metrics use the equations reproduced in Eqs. (12)--(20):
%   uncentered L2 norms for normalized RMS errors and floor-grouped ordering
%   for J4--J9. The code metrics are returned by BLK_EVALUATION using those
%   same paper definitions and ordering.

if nargin < 1 || strlength(string(resultPath)) == 0
    projectRoot = fileparts(fileparts(mfilename('fullpath')));
    candidates = dir(fullfile(projectRoot, 'Results', ...
        'paper_rerun_*_case_04_Nom_.mat'));
    assert(~isempty(candidates), 'No paper-rerun Case IV result was found.');
    [~, newestIndex] = max([candidates.datenum]);
    resultPath = fullfile(candidates(newestIndex).folder, ...
        candidates(newestIndex).name);
else
    resultPath = char(resultPath);
    projectRoot = fileparts(fileparts(mfilename('fullpath')));
end

saved = load(resultPath);
required = {'X_m', 'Num_resp', 'Ref_Resp', 't'};
assert(all(isfield(saved, required)), ...
    'The saved result does not contain all required evaluation signals.');

xMeasured = saved.X_m.Data(:, 1);
numerical = saved.Num_resp.Data;
reference = saved.Ref_Resp;
time = saved.t(:);
dt = median(diff(time));

% Interpret the paper J1 summation literally as y_n(i)*x_m(i-k) over the
% same nonnegative 0:49-sample search window used by the legacy code.
lags = 0:49;
rawCorrelation = zeros(size(lags));
for lagIndex = 1:numel(lags)
    lag = lags(lagIndex);
    rawCorrelation(lagIndex) = sum(numerical(1+lag:end, 1) .* ...
        xMeasured(1:end-lag));
end
[~, paperDelayIndex] = max(rawCorrelation);

paperValues = zeros(1, 9);
paperValues(1) = round(1000 * lags(paperDelayIndex) * dt, 1);
paperValues(2) = round(100 * norm(xMeasured - numerical(:, 1)) / ...
    norm(numerical(:, 1)), 2);
paperValues(3) = round(100 * max(abs(xMeasured - numerical(:, 1))) / ...
    max(abs(numerical(:, 1))), 2);
paperValues(4) = round(100 * norm(xMeasured - reference(:, 1)) / ...
    norm(reference(:, 1)), 2);
paperValues(5) = round(100 * norm(numerical(:, 2) - reference(:, 2)) / ...
    norm(reference(:, 2)), 2);
paperValues(6) = round(100 * norm(numerical(:, 3) - reference(:, 3)) / ...
    norm(reference(:, 3)), 2);
paperValues(7) = round(100 * max(abs(xMeasured - reference(:, 1))) / ...
    max(abs(reference(:, 1))), 2);
paperValues(8) = round(100 * max(abs(numerical(:, 2) - reference(:, 2))) / ...
    max(abs(reference(:, 2))), 2);
paperValues(9) = round(100 * max(abs(numerical(:, 3) - reference(:, 3))) / ...
    max(abs(reference(:, 3))), 2);

trial = struct('X_m', saved.X_m, 'Num_resp', saved.Num_resp, ...
    'Ref_Resp', saved.Ref_Resp);
codeValues = blk_evaluation(trial, dt);

metric = compose('J%d', (1:9)');
unit = ["ms"; repmat("%", 8, 1)];
paperDefinition = [ ...
    "raw cross-correlation delay"; ...
    "L2 RMS tracking error"; ...
    "peak tracking error"; ...
    "L2 RMS floor 1"; ...
    "L2 RMS floor 2"; ...
    "L2 RMS floor 3"; ...
    "peak floor 1"; ...
    "peak floor 2"; ...
    "peak floor 3"];
codeDefinition = [ ...
    "paper raw cross-correlation delay"; ...
    "L2 RMS tracking error"; ...
    "peak tracking error"; ...
    "L2 RMS floor 1"; ...
    "L2 RMS floor 2"; ...
    "L2 RMS floor 3"; ...
    "peak floor 1"; ...
    "peak floor 2"; ...
    "peak floor 3"];

comparison = table(metric, unit, paperDefinition, paperValues', ...
    codeDefinition, codeValues', paperValues' - codeValues', ...
    'VariableNames', {'Metric', 'Unit', 'PaperDefinition', 'PaperValue', ...
    'CodeDefinition', 'CodeValue', 'PaperMinusCode'});

if nargin < 2 || strlength(string(outputPath)) == 0
    [~, resultName] = fileparts(resultPath);
    outputPath = fullfile(projectRoot, 'Results', ...
        sprintf('%s_paper_vs_code_evaluations.csv', resultName));
else
    outputPath = char(outputPath);
end
writetable(comparison, outputPath);

fprintf('Evaluation source: %s\n', resultPath);
if isfield(saved, 'switch_event')
    event = saved.switch_event;
    if isstruct(event) && isfield(event, 'time')
        fprintf('Saved controller-switch time: %.6g s\n', event.time);
    end
end
disp(comparison)
fprintf('Wrote %s\n', outputPath);
end
