function step_num
%STEP_NUM Simulate a ground-acceleration step through the full RTHS model.
%   With the "scripted" folder on the MATLAB path, run this figure with:
%       step_num
%   This is an exact scripted-model simulation, including the numerical
%   substructure, discrete phase lead, one-sample force delay, actuator,
%   saturation, and experimental substructure. It compares A, B, and C.

fs = 4096;                 % RTHS sampling frequency [Hz]
stepAmplitude = 0.1;       % Ground-acceleration step [m/s^2]
stepTime = 0.1;            % Step start time [s]
simulationEnd = 10;        % Simulation end time [s]
bw_a = 70; pm_a = 70;      % Controller A: bandwidth [rad/s], PM [deg]
bw_b = 55; pm_b = 55;      % Controller B: bandwidth [rad/s], PM [deg]
bw_c = 40; pm_c = 60;      % Not used by custom C; compatibility only
[target_ncf_c, target_ncf_c_alpha] = ...
    scripted_controller_c_settings;

scriptedDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(scriptedDir);
addpath(scriptedDir);
dt = 1 / fs;
t = (0:dt:simulationEnd).';
halfTime = t(1:end-1) + dt / 2;
groundInput = struct( ...
    't', t, ...
    'major', stepAmplitude * double(t >= stepTime), ...
    'half', stepAmplitude * double(halfTime >= stepTime));

controllerNames = {'A', 'B', 'C'};
controllerColors = {'#0a50a1', '#a9003c', '#01746F'};
responses = cell(1, numel(controllerNames));

for index = 1:numel(controllerNames)
    options = struct( ...
        'Building_c', 1, ...
        'plot_on', 'n', ...
        'modified', 1, ...
        'consider_damage', 0, ...
        'alpha_start', 1, ...
        'alpha_min', 0.5, ...
        'b_th', 0.13, ...
        'num_add', 0, ...
        'enable_indicator_plot', 0, ...
        'test_name', 'None', ...
        'fs', fs, ...
        'bw_a', bw_a, 'pm_a', pm_a, ...
        'bw_b', bw_b, 'pm_b', pm_b, ...
        'bw_c', bw_c, 'pm_c', pm_c, ...
        'target_ncf_c', target_ncf_c, ...
        'target_ncf_c_alpha', target_ncf_c_alpha, ...
        'start_c', controllerNames{index}, ...
        'switch_on', 0);
    p = scripted_build_trial(options, projectRoot, 1);
    responses{index} = scripted_engine(p, groundInput);
end

figure('Name', 'Exact numerical-substructure step response', 'Color', 'w');

subplot(2, 1, 1); hold on; grid on; box on;
for index = 1:numel(controllerNames)
    response = responses{index};
    plot(t, response.X_m.Data * 1000, 'LineWidth', 2, ...
        'Color', controllerColors{index});
    plot(t, response.block_signals.phase_output * 1000, '--', ...
        'LineWidth', 1.4, 'Color', controllerColors{index}, ...
        'HandleVisibility', 'off');
end
xline(stepTime, ':k', 'HandleVisibility', 'off');
ylabel('Displacement [mm]');
title('Full RTHS step response: solid = experimental, dashed = phase-lead reference');
legend({'Controller A', 'Controller B', 'Controller C'}, 'Location', 'best');

subplot(2, 1, 2); hold on; grid on; box on;
for index = 1:numel(controllerNames)
    response = responses{index};
    controllerField = lower(['pi_' controllerNames{index}]);
    plot(t, response.block_signals.(controllerField), 'LineWidth', 2, ...
        'Color', controllerColors{index});
end
xline(stepTime, ':k', 'HandleVisibility', 'off');
xlabel('Time [s]');
ylabel('Controller output [V]');
title('Selected continuous PI-controller output');
end
