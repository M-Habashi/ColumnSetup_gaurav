function setup_project_paths(step_root)
%SETUP_PROJECT_PATHS Add local helper and analysis utility folders.

    if nargin < 1 || isempty(step_root)
        step_root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    end

    path_list = { ...
        fullfile(step_root, 'helpers', 'utils'), ...
        fullfile(step_root, 'helpers', 'analysis_visualization'), ...
        fullfile(step_root, 'helpers', 'helper_speedgoat'), ...
        fullfile(step_root, 'helpers', 'helper_simulink'), ...
        fullfile(step_root, 'analysis', 'a_system_id'), ...
        fullfile(step_root, 'analysis', 'a_system_id', 'utils'), ...
        fullfile(step_root, 'analysis', 'b_stability'), ...
        fullfile(step_root, 'analysis', 'b_stability', 'stability_utils')};

    for i = 1:numel(path_list)
        if exist(path_list{i}, 'dir')
            addpath(path_list{i});
        end
    end
end
