function export_lqg_bode_data
%EXPORT_LQG_BODE_DATA Export closed-loop Bode and step responses for HTML.

assets = lqg_assets;
frequencyHz = linspace(0.1, 100, 2000).';
stepTimeSeconds = linspace(0, 3, 1500).';
files = {assets.system_7k, assets.system_5k};
ids = {'7k', '5k'};
labels = {'7k PID closed loop', '5k PID closed loop'};
systems = cell(1, numel(files));

for i = 1:numel(files)
    data = load(files{i}, 'H_dd_dm');
    response = squeeze(freqresp(data.H_dd_dm, 2*pi*frequencyHz));
    stepResponse = step(data.H_dd_dm, stepTimeSeconds);
    [~, source, extension] = fileparts(files{i});
    systems{i} = struct( ...
        'id', ids{i}, ...
        'label', labels{i}, ...
        'source', [source extension], ...
        'lineDash', 'solid', ...
        'magnitudeDb', 20*log10(abs(response(:))), ...
        'phaseDeg', unwrap(angle(response(:)))*180/pi, ...
        'stepResponse', stepResponse(:));
end

refitFile = fullfile(assets.results, 'lqr_7k_six_state_refit.mat');
refit = load(refitFile, 'result');
pidSource = load(assets.system_7k, 'pid_values');
pidValues = pidSource.pid_values;
controller = pid(pidValues.P, pidValues.I, pidValues.D, ...
    1/pidValues.derivative_filter_N, pidValues.dt, ...
    'IFormula', 'ForwardEuler', 'DFormula', 'ForwardEuler');
refittedPlant = c2d(refit.result.refitted_transfer_function, ...
    pidValues.dt, 'zoh');
refittedClosedLoop = feedback(controller*refittedPlant, 1);
refittedResponse = squeeze(freqresp(refittedClosedLoop, ...
    2*pi*frequencyHz));
discreteStepTime = (0:pidValues.dt:stepTimeSeconds(end)).';
discreteStepResponse = step(refittedClosedLoop, discreteStepTime);
refittedStepResponse = interp1(discreteStepTime, ...
    discreteStepResponse(:), stepTimeSeconds, 'linear');
[~, refitSource, refitExtension] = fileparts(refitFile);
refittedSystem = struct( ...
    'id', '7k-refit', ...
    'label', '7k six-state refit + PID', ...
    'source', [refitSource refitExtension], ...
    'lineDash', 'dot', ...
    'magnitudeDb', 20*log10(abs(refittedResponse(:))), ...
    'phaseDeg', unwrap(angle(refittedResponse(:)))*180/pi, ...
    'stepResponse', refittedStepResponse(:));
systems = {systems{1}, refittedSystem, systems{2}};

plotData = struct( ...
    'frequencyHz', frequencyHz, ...
    'frequencyScale', 'linear', ...
    'frequencyRangeHz', [frequencyHz(1), frequencyHz(end)], ...
    'stepTimeSeconds', stepTimeSeconds, ...
    'response', 'H_dd_dm with PID-wrapped 7k six-state refit', ...
    'systems', [systems{:}]);

outputFile = fullfile(fileparts(mfilename('fullpath')), ...
    'lqg_bode_data.js');
fileId = fopen(outputFile, 'w');
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, 'window.lqgBodeData = %s;\n', jsonencode(plotData));
fprintf('Wrote %d frequency and %d step samples to %s\n', ...
    numel(frequencyHz), numel(stepTimeSeconds), outputFile)
end
