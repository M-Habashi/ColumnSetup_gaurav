function export_lqg_bode_data
%EXPORT_LQG_BODE_DATA Export closed-loop Bode and step responses for HTML.

assets = lqg_assets;
frequencyHz = linspace(0.1, 100, 2000).';
stepTimeSeconds = linspace(0, 3, 1500).';
files = {assets.system_7k, assets.system_5k};
ids = {'7k', '5k'};
labels = {'7k closed loop', '5k closed loop'};
systems = cell(1, numel(files));

for i = 1:numel(files)
    data = load(files{i}, 'H_dd_dm');
    response = squeeze(freqresp(data.H_dd_dm, 2*pi*frequencyHz));
    stepResponse = step(data.H_dd_dm, stepTimeSeconds);
    [~, source, extension] = fileparts(files{i});
    systems{i} = struct( ...
        'id', ids{i}, ...
        'label', labels{i}, ...
        'source', [source extension], ...
        'magnitudeDb', 20*log10(abs(response(:))), ...
        'phaseDeg', unwrap(angle(response(:)))*180/pi, ...
        'stepResponse', stepResponse(:));
end

plotData = struct( ...
    'frequencyHz', frequencyHz, ...
    'frequencyScale', 'linear', ...
    'frequencyRangeHz', [frequencyHz(1), frequencyHz(end)], ...
    'stepTimeSeconds', stepTimeSeconds, ...
    'response', 'H_dd_dm', ...
    'systems', [systems{:}]);

outputFile = fullfile(fileparts(mfilename('fullpath')), ...
    'lqg_bode_data.js');
fileId = fopen(outputFile, 'w');
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, 'window.lqgBodeData = %s;\n', jsonencode(plotData));
fprintf('Wrote %d frequency and %d step samples to %s\n', ...
    numel(frequencyHz), numel(stepTimeSeconds), outputFile)
end
