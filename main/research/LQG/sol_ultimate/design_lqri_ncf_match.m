function result = design_lqri_ncf_match
%DESIGN_LQRI_NCF_MATCH Match nominal LQRI and PID normalized NCF measures.

studyFolder = fileparts(mfilename('fullpath'));
lqgFolder = fileparts(studyFolder);
mainFolder = fileparts(fileparts(lqgFolder));
addpath(fullfile(mainFolder, 'control_and_HS', 'b_system_id', ...
    'id_utils'))
modelsData = load(fullfile(lqgFolder, 'results', ...
    'lqr_state_space_models.mat'), 'result');
models = modelsData.result;
system7k = models.system_7k;
refitData = load(system7k.source, 'result');
pidData = load(refitData.result.source, 'pid_values', 'model_metadata');
pidValues = pidData.pid_values;
frequencyBandHz = pidData.model_metadata.fit_config.f_lim;
frequencyScale = models.frequency_scale_rad_per_second;

plant = ss(frequencyScale*system7k.A, frequencyScale*system7k.B, ...
    system7k.C, 0);
discretePlant = c2d(plant, pidValues.dt, 'zoh');
[A, B, C] = ssdata(plant);
pidController = pid(pidValues.P, pidValues.I, pidValues.D, ...
    1/pidValues.derivative_filter_N, pidValues.dt, ...
    'IFormula', 'ForwardEuler', 'DFormula', 'ForwardEuler');
[~, ~, pidMargin] = custom_stability_margins( ...
    pidController*discretePlant, frequencyBandHz);

benchmarkTime = (0:pidValues.dt:8).';
pidOutput = step(feedback(pidController*discretePlant, 1), ...
    benchmarkTime);
pidInput = step(feedback(pidController, discretePlant), benchmarkTime);
trackingError = 1-pidOutput;
integralError = cumtrapz(benchmarkTime, trackingError);
errorLimit = max(abs(trackingError));
integralStateLimit = max(abs(integralError));
inputLimit = max(abs(pidInput));
brysonRawQy = 1/errorLimit^2;
brysonRawQi = 1/integralStateLimit^2;
brysonRawR = 1/inputLimit^2;
brysonWeights = [brysonRawQy, brysonRawQi]/brysonRawR;

augmentedA = [A, zeros(size(A, 1), 1); -C, 0];
augmentedB = [B; 0];
augmentedPlant = ss(augmentedA, augmentedB, eye(size(augmentedA)), ...
    zeros(size(augmentedA, 1), 1));
ru = 1;
matchingTolerance = 0.01;
equilibrium = [A, B; C, 0]\[zeros(size(A, 1), 1); 1];
referenceState = equilibrium(1:end-1);
referenceInput = equilibrium(end);
ratioGrid = logspace(-2, 2, 41);
gridCount = numel(ratioGrid);
costGrid = nan(gridCount);
marginGrid = nan(gridCount);
for i = 1:gridCount
    for j = 1:gridCount
        [costGrid(i, j), marginGrid(i, j)] = candidateMetrics( ...
            log10([ratioGrid(i), ratioGrid(j)]), brysonWeights, ...
            plant, augmentedPlant, C, referenceState, referenceInput, ...
            frequencyBandHz);
    end
end
feasibleGrid = abs(marginGrid-pidMargin) <= matchingTolerance;
distanceGrid = repmat(log10(ratioGrid(:)).^2, 1, gridCount) + ...
    repmat(log10(ratioGrid).^2, gridCount, 1);
feasibleDistance = distanceGrid;
feasibleDistance(~feasibleGrid) = inf;
[~, initialLinearIndex] = min(feasibleDistance(:));
assert(isfinite(feasibleDistance(initialLinearIndex)), ...
    'No Bryson-normalized grid point satisfies the NCF constraint.')
[initialQyIndex, initialQiIndex] = ind2sub(size(costGrid), ...
    initialLinearIndex);
initialLogRatios = log10([ratioGrid(initialQyIndex), ...
    ratioGrid(initialQiIndex)]);
fprintf(['Bryson-grid candidate Qy = %.12g, qi = %.12g, J = %.12g, ' ...
    'NCF = %.12f, indices = [%d %d]\n'], ...
    brysonWeights(1)*ratioGrid(initialQyIndex), ...
    brysonWeights(2)*ratioGrid(initialQiIndex), ...
    costGrid(initialLinearIndex), marginGrid(initialLinearIndex), ...
    initialQyIndex, initialQiIndex)

objective = @(logRatios) sum(logRatios.^2);
constraint = @(logRatios) marginConstraint(logRatios, brysonWeights, ...
    plant, augmentedPlant, C, referenceState, referenceInput, ...
    frequencyBandHz, pidMargin);
options = optimoptions('fmincon', 'Algorithm', 'sqp', ...
    'Display', 'off', 'ConstraintTolerance', 1e-10, ...
    'OptimalityTolerance', 1e-9, 'StepTolerance', 1e-10, ...
    'MaxFunctionEvaluations', 2000, 'MaxIterations', 300);
[optimalLogRatios, ~, exitFlag, solverOutput] = fmincon(objective, ...
    initialLogRatios, [], [], [], [], [-inf, -inf], [inf, inf], ...
    constraint, options);
fprintf('Unbounded refinement exit flag = %d, ratios = [%.12g %.12g]\n', ...
    exitFlag, 10^optimalLogRatios(1), 10^optimalLogRatios(2))
assert(exitFlag > 0, 'The unbounded-qI optimization did not converge.')
optimalWeights = brysonWeights.*10.^optimalLogRatios;
qy = optimalWeights(1);
qi = optimalWeights(2);
penalty = blkdiag(qy*(C.'*C), qi);
[gain, riccatiSolution] = lqi(plant, penalty, ru);
stateGain = gain(1:end-1);
integralGain = gain(end);
[optimalCost, ~, initialDeviation] = candidateMetrics( ...
    optimalLogRatios, brysonWeights, plant, augmentedPlant, C, ...
    referenceState, referenceInput, frequencyBandHz);
[~, ~, lqriMargin] = custom_stability_margins( ...
    gain*augmentedPlant, frequencyBandHz);
absoluteDifference = abs(lqriMargin-pidMargin);
assert(absoluteDifference <= matchingTolerance, ...
    'The LQRI normalized NCF measure does not match the PID target.')

result = struct( ...
    'qy', qy, ...
    'qi', qi, ...
    'ru', ru, ...
    'solver', 'lqi', ...
    'P', riccatiSolution, ...
    'optimal_cost', optimalCost, ...
    'initial_augmented_deviation', initialDeviation, ...
    'state_gain', stateGain, ...
    'integral_gain', integralGain, ...
    'augmented_gain', gain, ...
    'closed_loop_poles_7k', eig(augmentedA-augmentedB*gain), ...
    'pid_normalized_ncf_margin_7k', pidMargin, ...
    'lqri_normalized_ncf_margin_7k', lqriMargin, ...
    'absolute_margin_difference', absoluteDifference, ...
    'matching_tolerance', matchingTolerance, ...
    'frequency_band_hz', frequencyBandHz, ...
    'bryson', struct('error_limit', errorLimit, ...
        'integral_state_limit', integralStateLimit, ...
        'input_limit', inputLimit, 'raw_qy', brysonRawQy, ...
        'raw_qi', brysonRawQi, 'raw_r', brysonRawR, ...
        'normalized_qy', brysonWeights(1), ...
        'normalized_qi', brysonWeights(2), ...
        'benchmark_duration_s', benchmarkTime(end)), ...
    'ratio_grid', ratioGrid, ...
    'qy_grid', brysonWeights(1)*ratioGrid, ...
    'qi_grid', brysonWeights(2)*ratioGrid, ...
    'cost_grid', costGrid, ...
    'margin_grid', marginGrid, ...
    'bryson_distance_grid', distanceGrid, ...
    'feasible_grid', feasibleGrid, ...
    'optimization_exit_flag', exitFlag, ...
    'optimization_output', solverOutput, ...
    'definition', ['Continuous LQRI solved with MATLAB lqi and ' ...
        'independently selected Qy and qi. PID step-response limits set ' ...
        'Bryson-normalized starting weights. An independent two-decade ' ...
        'grid around each weight initializes unbounded positive ' ...
        'refinement of the squared log-distance from the Bryson weights ' ...
        'subject to the nominal PID normalized NCF equality constraint.']);
save(fullfile(studyFolder, 'ncf_matched_lqri.mat'), 'result')

fprintf('NCF-matched LQRI Qy = %.12g, qi = %.12g, R = %.12g\n', ...
    qy, qi, ru)
fprintf('Optimal initial-condition cost = %.12g\n', optimalCost)
fprintf('PID normalized NCF measure = %.12f\n', pidMargin)
fprintf('LQRI normalized NCF measure = %.12f\n', lqriMargin)
fprintf('Absolute difference = %.12g\n', absoluteDifference)
end

function [cost, margin, initialDeviation] = candidateMetrics(logRatios, ...
        brysonWeights, plant, returnRatioPlant, C, referenceState, ...
        referenceInput, frequencyBandHz)
weights = brysonWeights.*10.^logRatios;
qy = weights(1);
qi = weights(2);
try
    [gain, P] = lqi(plant, blkdiag(qy*(C.'*C), qi), 1);
catch
    cost = 1e12;
    margin = 0;
    initialDeviation = nan(numel(referenceState)+1, 1);
    return
end
if size(gain, 2) ~= numel(referenceState)+1
    cost = 1e12;
    margin = 0;
    initialDeviation = nan(numel(referenceState)+1, 1);
    return
end
integralEquilibrium = -(referenceInput + ...
    gain(1:end-1)*referenceState)/gain(end);
initialDeviation = [-referenceState; -integralEquilibrium];
cost = real(initialDeviation.'*P*initialDeviation);
margin = nan;
if ~isempty(returnRatioPlant)
    [~, ~, margin] = custom_stability_margins(gain*returnRatioPlant, ...
        frequencyBandHz);
end
end

function [inequality, equality] = marginConstraint(logRatios, ...
        brysonWeights, plant, returnRatioPlant, C, referenceState, ...
        referenceInput, frequencyBandHz, targetMargin)
[~, margin] = candidateMetrics(logRatios, brysonWeights, plant, ...
    returnRatioPlant, C, ...
    referenceState, referenceInput, frequencyBandHz);
inequality = [];
equality = margin-targetMargin;
end
