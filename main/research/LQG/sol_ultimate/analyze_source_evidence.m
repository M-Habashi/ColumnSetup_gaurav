function result = analyze_source_evidence
%ANALYZE_SOURCE_EVIDENCE Reproduce saved PID and endpoint-model evidence.

studyFolder = fileparts(mfilename('fullpath'));
lqgFolder = fileparts(studyFolder);
modelsData = load(fullfile(lqgFolder, 'results', ...
    'lqr_state_space_models.mat'), 'result');
models = modelsData.result;
refitData = load(models.system_7k.source, 'result');
source7k = refitData.result.source;
source5k = models.system_5k.source;
fields = {'H_dc_dm_xfunc', 'H_dd_dm_xfunc', 'H_dd_dm', ...
    'specimen_params'};
data7k = load(source7k, fields{:});
data5k = load(source5k, fields{:});

frequencyHz = linspace(2, 79.75, 2000).';
plantMismatch = mismatchRow(data7k.H_dc_dm_xfunc, ...
    data5k.H_dc_dm_xfunc, frequencyHz);
pidLoopMismatch = mismatchRow(data7k.H_dd_dm_xfunc, ...
    data5k.H_dd_dm_xfunc, frequencyHz);
channel = {'H_dc_dm'; 'H_dd_dm'};
result = struct;
result.provenance = struct('source_7k', source7k, 'source_5k', source5k);
result.frequency_hz = frequencyHz;
result.measured_endpoint_mismatch = table(channel, ...
    [plantMismatch.RmsMagnitudeDb; pidLoopMismatch.RmsMagnitudeDb], ...
    [plantMismatch.MaxMagnitudeDb; pidLoopMismatch.MaxMagnitudeDb], ...
    [plantMismatch.RmsPhaseDegrees; pidLoopMismatch.RmsPhaseDegrees], ...
    [plantMismatch.MaxPhaseDegrees; pidLoopMismatch.MaxPhaseDegrees], ...
    'VariableNames', {'Channel', 'RmsMagnitudeDb', 'MaxMagnitudeDb', ...
        'RmsPhaseDegrees', 'MaxPhaseDegrees'});

params7k = parameterVector(data7k.specimen_params);
params5k = parameterVector(data5k.specimen_params);
quantity = {'Mass'; 'Damping'; 'Stiffness'; 'NaturalFrequency'; ...
    'DampingRatio'};
unit = {'kg'; 'N s/m'; 'N/m'; 'Hz'; 'dimensionless'};
result.identified_parameters = table(quantity, unit, params7k, params5k, ...
    100*(params5k - params7k)./params7k, params5k./params7k, ...
    'VariableNames', {'Quantity', 'Unit', 'Value7k', 'Value5k', ...
        'PercentChange', 'Ratio5kTo7k'});

time = (0:1/2048:3).';
pid7k = pidRow(data7k.H_dd_dm, time);
pid5k = pidRow(data5k.H_dd_dm, time);
result.saved_pid_step = table( ...
    [pid7k.FinalValue; pid5k.FinalValue], ...
    [pid7k.ErrorPercent; pid5k.ErrorPercent], ...
    [pid7k.SettlingToUnitTargetSeconds; ...
    pid5k.SettlingToUnitTargetSeconds], ...
    'VariableNames', {'FinalValue', 'ErrorPercent', ...
        'SettlingToUnitTargetSeconds'}, 'RowNames', {'7k', '5k'});
frequencyTrackingHz = linspace(2, 80, 2000).';
pidTracking7k = squeeze(freqresp(data7k.H_dd_dm, ...
    2*pi*frequencyTrackingHz));
pidTracking5k = squeeze(freqresp(data5k.H_dd_dm, ...
    2*pi*frequencyTrackingHz));
result.saved_pid_frequency_tracking = table( ...
    [rms(abs(1-pidTracking7k)); rms(abs(1-pidTracking5k))], ...
    [max(abs(1-pidTracking7k)); max(abs(1-pidTracking5k))], ...
    'VariableNames', {'RMSTrackingError', 'MaxTrackingError'}, ...
    'RowNames', {'7k', '5k'});
result.measured_frequency_support_hz = [max([ ...
    min(data7k.H_dc_dm_xfunc.freq_hz), ...
    min(data5k.H_dc_dm_xfunc.freq_hz)]), min([ ...
    max(data7k.H_dc_dm_xfunc.freq_hz), ...
    max(data5k.H_dc_dm_xfunc.freq_hz)])];

save(fullfile(studyFolder, 'source_evidence.mat'), 'result')
disp(result.measured_endpoint_mismatch)
disp(result.identified_parameters)
disp(result.saved_pid_step)
end

function row = mismatchRow(first, second, frequencyHz)
firstResponse = interp1(first.freq_hz, first.points, frequencyHz, 'linear');
secondResponse = interp1(second.freq_hz, second.points, ...
    frequencyHz, 'linear');
magnitudeDifference = mag2db(abs(firstResponse)) - ...
    mag2db(abs(secondResponse));
phaseDifference = rad2deg(unwrap(angle(firstResponse)) - ...
    unwrap(angle(secondResponse)));
row = table(rms(magnitudeDifference), max(abs(magnitudeDifference)), ...
    rms(phaseDifference), max(abs(phaseDifference)), ...
    'VariableNames', {'RmsMagnitudeDb', 'MaxMagnitudeDb', ...
        'RmsPhaseDegrees', 'MaxPhaseDegrees'});
end

function values = parameterVector(parameters)
naturalFrequency = sqrt(parameters.k/parameters.m)/(2*pi);
dampingRatio = parameters.c/(2*sqrt(parameters.k*parameters.m));
values = [parameters.m; parameters.c; parameters.k; naturalFrequency; ...
    dampingRatio];
end

function row = pidRow(system, time)
response = step(system, time);
finalValue = dcgain(system);
lastOutside = find(abs(response - 1) > 0.02, 1, 'last');
if isempty(lastOutside)
    settlingTime = 0;
elseif lastOutside < numel(time)
    settlingTime = time(lastOutside + 1);
else
    settlingTime = Inf;
end
row = table(finalValue, 100*(finalValue - 1), settlingTime, ...
    'VariableNames', {'FinalValue', 'ErrorPercent', ...
        'SettlingToUnitTargetSeconds'});
end
