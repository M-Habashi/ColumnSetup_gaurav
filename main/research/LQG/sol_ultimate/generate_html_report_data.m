function result = generate_html_report_data
%GENERATE_HTML_REPORT_DATA Export reproducible step and Bode plot data.

studyFolder = fileparts(mfilename('fullpath'));
lqgFolder = fileparts(studyFolder);
mainFolder = fileparts(fileparts(lqgFolder));
addpath(fullfile(mainFolder, 'control_and_HS', 'b_system_id', ...
    'id_utils'))
modelsData = load(fullfile(lqgFolder, 'results', ...
    'lqr_state_space_models.mat'), 'result');
designData = load(fullfile(lqgFolder, 'results', ...
    'lqr_baseline_design.mat'), 'result');
lqgiData = load(fullfile(studyFolder, 'lqgi_comparator.mat'), 'result');
ncfData = load(fullfile(studyFolder, 'ncf_matched_lqr.mat'), 'result');
lqriData = load(fullfile(studyFolder, 'ncf_matched_lqri.mat'), 'result');
models = modelsData.result;
design = designData.result;
lqgi = lqgiData.result;
ncfDesign = ncfData.result;
lqriDesign = lqriData.result;
dt = 1/2048;
scale = models.frequency_scale_rad_per_second;

continuous7k = ss(scale*models.system_7k.A, ...
    scale*models.system_7k.B, models.system_7k.C, 0);
continuous5k = ss(scale*models.system_5k.A, ...
    scale*models.system_5k.B, models.system_5k.C, 0);
continuousPlants = {continuous7k, continuous5k};
discretePlants = {c2d(continuous7k, dt, 'zoh'), ...
    c2d(continuous5k, dt, 'zoh')};
nominal = discretePlants{1};

refitData = load(models.system_7k.source, 'result');
source7k = load(refitData.result.source, 'H_dd_dm', 'pid_values');
source5k = load(models.system_5k.source, 'H_dd_dm');
pidLoops = {source7k.H_dd_dm, source5k.H_dd_dm};
pidValues = source7k.pid_values;
pidController = pid(pidValues.P, pidValues.I, pidValues.D, ...
    1/pidValues.derivative_filter_N, pidValues.dt, ...
    'IFormula', 'ForwardEuler', 'DFormula', 'ForwardEuler');

selected = lqgi.selected_index;
KIntegral = lqgi.state_gain(selected, :);
Ki = lqgi.integral_gain(selected);
LDiscrete = dlqe(nominal.A, nominal.B, nominal.C, ...
    lqgi.definition.estimator_q_over_r, 1);
integralLoops = cell(2, 1);
lqrLoops = cell(2, 1);
ncfLqrLoops = cell(2, 1);
ncfLqriLoops = cell(2, 1);
ncfPidLoops = cell(2, 1);
ordinaryLqgLoops = cell(2, 1);
LContinuous = lqe(continuous7k.A, continuous7k.B, ...
    continuous7k.C, 1, 1);
for i = 1:2
    integralLoops{i} = integralReferenceLoop(discretePlants{i}, ...
        nominal, KIntegral, Ki, LDiscrete, dt);
    [A, B, C] = ssdata(continuousPlants{i});
    lqrLoops{i} = ss(A-B*design.K, B*design.nbar, C, 0);
    ncfLqrLoops{i} = ss(A-B*ncfDesign.K, ...
        B*ncfDesign.nbar, C, 0);
    ncfLqriLoops{i} = lqriReferenceLoop(continuousPlants{i}, ...
        lqriDesign.augmented_gain);
    ncfPidLoops{i} = feedback(pidController*discretePlants{i}, 1);
    ordinaryLqgLoops{i} = observerReferenceLoop(continuousPlants{i}, ...
        continuous7k, design.K, design.nbar, LContinuous);
end

stepTime = (0:dt:0.6).';
exportIndex = (1:2:numel(stepTime)).';
result = struct;
result.metadata = struct( ...
    'sample_time_s', dt, ...
    'frequency_band_hz', [0 80], ...
    'ordinary_lqg_q_over_r', 1, ...
    'generated_utc', char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z''')));
result.step = struct('time_s', stepTime(exportIndex), ...
    'condition7k', responseSet(1, stepTime, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops), ...
    'condition5k', responseSet(2, stepTime, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops));

frequencyHz = linspace(0, 80, 321).';
lqrStepTime = (0:dt:1.5).';
lqrStepIndex = (1:2:numel(lqrStepTime)).';
lqriStepTime = (0:dt:8).';
lqriStepIndex = (1:4:numel(lqriStepTime)).';
alphaGrid = linspace(0.2, 1, 9).';
result.bode = struct('frequency_hz', frequencyHz, ...
    'condition7k', bodeSet(1, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops), ...
    'condition5k', bodeSet(2, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops));
result.stiffness_step = stiffnessStepSet(alphaGrid, lqrStepTime, ...
    lqrStepIndex, pidController, discretePlants);
condition = linspace(0, 1, 101).';
result.ncf_design = struct( ...
    'qy', ncfDesign.qy, ...
    'ru', ncfDesign.ru, ...
    'K', ncfDesign.K, ...
    'nbar', ncfDesign.nbar, ...
    'bode', struct('frequency_hz', frequencyHz, ...
        'condition7k', comparisonBodeSet(1, frequencyHz, ...
            ncfPidLoops, ncfLqrLoops), ...
        'condition5k', comparisonBodeSet(2, frequencyHz, ...
            ncfPidLoops, ncfLqrLoops)), ...
    'step', comparisonStepSet(lqrStepTime, lqrStepIndex, ...
        ncfPidLoops, ncfLqrLoops, 'lqr'), ...
    'margin', normalizedNcfSet(models, ncfDesign.K, ...
        pidController, dt, scale, condition, ...
        ncfDesign.frequency_band_hz));
result.lqri_design = struct( ...
    'qy', lqriDesign.qy, ...
    'qi', lqriDesign.qi, ...
    'ru', lqriDesign.ru, ...
    'state_gain', lqriDesign.state_gain, ...
    'integral_gain', lqriDesign.integral_gain, ...
    'bode', struct('frequency_hz', frequencyHz, ...
        'condition7k', lqriComparisonBodeSet(1, frequencyHz, ...
            ncfPidLoops, ncfLqriLoops), ...
        'condition5k', lqriComparisonBodeSet(2, frequencyHz, ...
            ncfPidLoops, ncfLqriLoops)), ...
    'step', comparisonStepSet(lqriStepTime, lqriStepIndex, ...
        ncfPidLoops, ncfLqriLoops, 'lqri'), ...
    'margin', normalizedLqriNcfSet(models, ...
        lqriDesign.augmented_gain, pidController, dt, scale, ...
        condition, lqriDesign.frequency_band_hz));

save(fullfile(studyFolder, 'html_report_plot_data.mat'), 'result')
json = jsonencode(result);
webDataFolder = fullfile(studyFolder, 'LQG_web', 'data');
if ~isfolder(webDataFolder)
    mkdir(webDataFolder)
end
outputFile = fullfile(webDataFolder, 'report-plot-data.js');
fileId = fopen(outputFile, 'w');
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, 'window.SOL_ULTIMATE_PLOT_DATA = %s;\n', json);
fprintf('Saved HTML report plot data to %s\n', outputFile)
end

function output = responseSet(index, time, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops)
output = struct( ...
    'pid', column(step(pidLoops{index}, time), exportIndex), ...
    'lqr', column(step(lqrLoops{index}, time), exportIndex), ...
    'ordinary_lqg', column(step(ordinaryLqgLoops{index}, time), ...
        exportIndex), ...
    'lqgi', column(step(integralLoops{index}, time), exportIndex));
end

function output = bodeSet(index, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops)
systems = {pidLoops{index}, lqrLoops{index}, integralLoops{index}};
names = {'pid', 'lqr', 'lqgi'};
output = struct;
for i = 1:numel(systems)
    response = squeeze(freqresp(systems{i}, 2*pi*frequencyHz));
    output.(names{i}) = struct( ...
        'magnitude_db', column(mag2db(abs(response))), ...
        'phase_deg', column(rad2deg(unwrap(angle(response)))));
end
end

function system = integralReferenceLoop(plant, nominal, K, Ki, L, dt)
[Ap, Bp, Cp] = ssdata(plant);
[An, Bn, Cn] = ssdata(nominal);
stateCount = size(Ap, 1);
A = [Ap, -Bp*K, -Bp*Ki; ...
    L*Cp, An-Bn*K-L*Cn, -Bn*Ki; ...
    -dt*Cp, zeros(1, stateCount), 1];
Br = [zeros(2*stateCount, 1); dt];
Cy = [Cp, zeros(1, stateCount+1)];
system = ss(A, Br, Cy, 0, dt);
end

function system = observerReferenceLoop(plant, nominal, K, nbar, L)
[Ap, Bp, Cp] = ssdata(plant);
[An, Bn, Cn] = ssdata(nominal);
stateCount = size(Ap, 1);
A = [Ap, -Bp*K; L*Cp, An-Bn*K-L*Cn];
Br = [Bp*nbar; Bn*nbar];
Cy = [Cp, zeros(1, stateCount)];
system = ss(A, Br, Cy, 0);
end

function system = lqriReferenceLoop(plant, gain)
[A, B, C] = ssdata(plant);
stateCount = size(A, 1);
augmentedA = [A, zeros(stateCount, 1); -C, 0];
augmentedB = [B; 0];
referenceInput = [zeros(stateCount, 1); 1];
system = ss(augmentedA-augmentedB*gain, referenceInput, ...
    [C, 0], 0);
end

function value = column(value, index)
value = value(:);
if nargin > 1
    value = value(index);
end
end

function output = comparisonBodeSet(index, frequencyHz, pidLoops, lqrLoops)
systems = {pidLoops{index}, lqrLoops{index}};
names = {'pid', 'lqr'};
output = struct;
for i = 1:numel(systems)
    response = squeeze(freqresp(systems{i}, 2*pi*frequencyHz));
    output.(names{i}) = struct( ...
        'magnitude_db', column(mag2db(abs(response))), ...
        'phase_deg', column(rad2deg(unwrap(angle(response)))));
end
end

function output = comparisonStepSet(time, exportIndex, pidLoops, ...
        controllerLoops, controllerName)
output = struct('time_s', time(exportIndex));
for index = 1:2
    conditionName = sprintf('condition%dk', 9-2*index);
    condition = struct('pid', column(step(pidLoops{index}, time), ...
        exportIndex));
    condition.(controllerName) = column(step(controllerLoops{index}, ...
        time), exportIndex);
    output.(conditionName) = condition;
end
end

function output = stiffnessStepSet(alphaGrid, time, exportIndex, ...
        controller, plants)
output = struct('time_s', time(exportIndex), 'alpha', alphaGrid);
for plantIndex = 1:2
    responses = zeros(numel(exportIndex), numel(alphaGrid));
    for alphaIndex = 1:numel(alphaGrid)
        closedLoop = feedback(alphaGrid(alphaIndex)*controller* ...
            plants{plantIndex}, 1);
        responses(:, alphaIndex) = column(step(closedLoop, time), ...
            exportIndex);
    end
    conditionName = sprintf('condition%dk', 9-2*plantIndex);
    output.(conditionName) = responses;
end
end

function output = lqriComparisonBodeSet(index, frequencyHz, pidLoops, ...
        lqriLoops)
systems = {pidLoops{index}, lqriLoops{index}};
names = {'pid', 'lqri'};
output = struct;
for i = 1:numel(systems)
    response = squeeze(freqresp(systems{i}, 2*pi*frequencyHz));
    output.(names{i}) = struct( ...
        'magnitude_db', column(mag2db(abs(response))), ...
        'phase_deg', column(rad2deg(unwrap(angle(response)))));
end
end

function output = normalizedNcfSet(models, K, pidController, dt, scale, ...
        condition, frequencyBandHz)
pidMargin = zeros(size(condition));
lqrMargin = zeros(size(condition));
for i = 1:numel(condition)
    fraction = condition(i);
    A = models.system_7k.A + ...
        fraction*(models.system_5k.A-models.system_7k.A);
    B = models.system_7k.B + ...
        fraction*(models.system_5k.B-models.system_7k.B);
    C = models.system_7k.C + ...
        fraction*(models.system_5k.C-models.system_7k.C);
    continuousPlant = ss(scale*A, scale*B, C, 0);
    discretePlant = c2d(continuousPlant, dt, 'zoh');
    statePlant = ss(scale*A, scale*B, eye(size(A)), ...
        zeros(size(A, 1), 1));
    [~, ~, pidMargin(i)] = custom_stability_margins( ...
        pidController*discretePlant, frequencyBandHz);
    [~, ~, lqrMargin(i)] = custom_stability_margins( ...
        K*statePlant, frequencyBandHz);
end
output = struct('condition', condition, 'pid', pidMargin, ...
    'lqr', lqrMargin);
end

function output = normalizedLqriNcfSet(models, gain, pidController, ...
        dt, scale, condition, frequencyBandHz)
pidMargin = zeros(size(condition));
lqriMargin = zeros(size(condition));
for i = 1:numel(condition)
    fraction = condition(i);
    A = models.system_7k.A + ...
        fraction*(models.system_5k.A-models.system_7k.A);
    B = models.system_7k.B + ...
        fraction*(models.system_5k.B-models.system_7k.B);
    C = models.system_7k.C + ...
        fraction*(models.system_5k.C-models.system_7k.C);
    continuousPlant = ss(scale*A, scale*B, C, 0);
    plant = c2d(continuousPlant, dt, 'zoh');
    augmentedA = [scale*A, zeros(size(A, 1), 1); -C, 0];
    augmentedB = [scale*B; 0];
    augmentedPlant = ss(augmentedA, augmentedB, ...
        eye(size(augmentedA)), zeros(size(augmentedA, 1), 1));
    [~, ~, pidMargin(i)] = custom_stability_margins( ...
        pidController*plant, frequencyBandHz);
    [~, ~, lqriMargin(i)] = custom_stability_margins( ...
        gain*augmentedPlant, frequencyBandHz);
end
output = struct('condition', condition, 'pid', pidMargin, ...
    'lqri', lqriMargin);
end
