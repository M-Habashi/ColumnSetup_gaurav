function result = generate_html_report_data
%GENERATE_HTML_REPORT_DATA Export reproducible step and Bode plot data.

studyFolder = fileparts(mfilename('fullpath'));
lqgFolder = fileparts(studyFolder);
mainFolder = fileparts(fileparts(lqgFolder));
addpath(fullfile(mainFolder, 'control_and_HS', 'b_system_id', ...
    'id_utils'))
modelsData = load(fullfile(lqgFolder, 'results', ...
    'lqr_state_space_models.mat'), 'result');
designData = load(fullfile(lqgFolder, 'results', ...
    'lqr_baseline_design.mat'), 'result');
lqgiData = load(fullfile(studyFolder, 'lqgi_comparator.mat'), 'result');
lqriData = load(fullfile(studyFolder, 'ncf_matched_lqri.mat'), 'result');
optimizedLqr = jsondecode(fileread(fullfile(studyFolder, ...
    'lqr_peak_command_optimization.json')));
optimizedLqi = jsondecode(fileread(fullfile(studyFolder, ...
    'lqi_peak_command_optimization.json')));
models = modelsData.result;
design = designData.result;
lqgi = lqgiData.result;
lqriDesign = lqriData.result;
optimizedK = optimizedLqr.K;
optimizedNbar = optimizedLqr.nbar_7k;
optimizedLqiGain = optimizedLqi.K;
dt = 1/2048;
scale = models.frequency_scale_rad_per_second;

continuous7k = ss(scale*models.system_7k.A, ...
    scale*models.system_7k.B, models.system_7k.C, 0);
continuous5k = ss(scale*models.system_5k.A, ...
    scale*models.system_5k.B, models.system_5k.C, 0);
continuousPlants = {continuous7k, continuous5k};
discretePlants = {c2d(continuous7k, dt, 'zoh'), ...
    c2d(continuous5k, dt, 'zoh')};
nominal = discretePlants{1};

refitData = load(models.system_7k.source, 'result');
source7k = load(refitData.result.source, 'H_dd_dm', 'pid_values');
source5k = load(models.system_5k.source, 'H_dd_dm');
pidLoops = {source7k.H_dd_dm, source5k.H_dd_dm};
pidValues = source7k.pid_values;
pidController = pid(pidValues.P, pidValues.I, pidValues.D, ...
    1/pidValues.derivative_filter_N, pidValues.dt, ...
    'IFormula', 'ForwardEuler', 'DFormula', 'ForwardEuler');

selected = lqgi.selected_index;
KIntegral = lqgi.state_gain(selected, :);
Ki = lqgi.integral_gain(selected);
LDiscrete = dlqe(nominal.A, nominal.B, nominal.C, ...
    lqgi.definition.estimator_q_over_r, 1);
integralLoops = cell(2, 1);
lqrLoops = cell(2, 1);
ncfLqrLoops = cell(2, 1);
ncfLqriLoops = cell(2, 1);
ncfPidLoops = cell(2, 1);
ncfPidReturnLoops = cell(2, 1);
ncfLqrCommandLoops = cell(2, 1);
ncfLqriCommandLoops = cell(2, 1);
ncfPidCommandLoops = cell(2, 1);
ordinaryLqgLoops = cell(2, 1);
LContinuous = lqe(continuous7k.A, continuous7k.B, ...
    continuous7k.C, 1, 1);
for i = 1:2
    integralLoops{i} = integralReferenceLoop(discretePlants{i}, ...
        nominal, KIntegral, Ki, LDiscrete, dt);
    [A, B, C] = ssdata(continuousPlants{i});
    lqrLoops{i} = ss(A-B*design.K, B*design.nbar, C, 0);
    ncfLqrLoops{i} = ss(A-B*optimizedK, ...
        B*optimizedNbar, C, 0);
    ncfLqriLoops{i} = lqriReferenceLoop(continuousPlants{i}, ...
        optimizedLqiGain);
    ncfPidLoops{i} = feedback(pidController*discretePlants{i}, 1);
    ncfPidReturnLoops{i} = pidController*discretePlants{i};
    ncfPidCommandLoops{i} = feedback(pidController, discretePlants{i});
    ncfLqrCommandLoops{i} = lqrReferenceCommand(continuousPlants{i}, ...
        optimizedK, optimizedNbar);
    ncfLqriCommandLoops{i} = lqriReferenceCommand(continuousPlants{i}, ...
        optimizedLqiGain);
    ordinaryLqgLoops{i} = observerReferenceLoop(continuousPlants{i}, ...
        continuous7k, design.K, design.nbar, LContinuous);
end

stepTime = (0:dt:0.6).';
exportIndex = (1:2:numel(stepTime)).';
result = struct;
result.metadata = struct( ...
    'sample_time_s', dt, ...
    'frequency_band_hz', [0 80], ...
    'ordinary_lqg_q_over_r', 1, ...
    'generated_utc', char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ss''Z''')));
result.step = struct('time_s', stepTime(exportIndex), ...
    'condition7k', responseSet(1, stepTime, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops), ...
    'condition5k', responseSet(2, stepTime, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops));

frequencyHz = linspace(0, 80, 321).';
returnFrequencyHz = linspace(0.1, 80, 321).';
lqrStepTime = (0:dt:1.5).';
lqrStepIndex = (1:2:numel(lqrStepTime)).';
lqriStepTime = (0:dt:8).';
lqriTransientEnd = round(0.1/dt)+1;
lqriStepIndex = unique([(1:lqriTransientEnd).'; ...
    (1:4:numel(lqriStepTime)).']);
alphaGrid = linspace(0.2, 1, 9).';
result.bode = struct('frequency_hz', frequencyHz, ...
    'condition7k', bodeSet(1, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops), ...
    'condition5k', bodeSet(2, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops));
result.stiffness_step = stiffnessStepSet(alphaGrid, lqrStepTime, ...
    lqrStepIndex, pidController, discretePlants);
condition = linspace(0, 1, 101).';
result.ncf_design = struct( ...
    'Q', optimizedLqr.Q, ...
    'ru', optimizedLqr.R(1, 1), ...
    'K', optimizedK, ...
    'nbar', optimizedNbar, ...
    'target_command_peak', optimizedLqr.configuration.target_peak, ...
    'command_peak_7k', optimizedLqr.command_peak, ...
    'tracking_loss_7k', optimizedLqr.tracking_loss, ...
    'total_loss_7k', optimizedLqr.total_loss, ...
    'loss_definition', optimizedLqr.loss_definition, ...
    'bode', struct('frequency_hz', returnFrequencyHz, ...
        'condition7k', reconstructedBodeSet(1, returnFrequencyHz, ...
            ncfPidReturnLoops, continuousPlants, ncfLqrLoops, ...
            optimizedNbar), ...
        'condition5k', reconstructedBodeSet(2, returnFrequencyHz, ...
            ncfPidReturnLoops, continuousPlants, ncfLqrLoops, ...
            optimizedNbar)), ...
    'step', comparisonStepSet(lqrStepTime, lqrStepIndex, ...
        ncfPidLoops, ncfLqrLoops, ncfPidCommandLoops, ...
        ncfLqrCommandLoops, 'lqr'), ...
    'margin', fullNcfSet(models, optimizedK, optimizedNbar, ...
        pidController, dt, scale, condition, [0.1 80]));
result.lqri_design = struct( ...
    'optimization_scope', optimizedLqi.optimization_scope, ...
    'evaluation_scope', ['same endpoint-optimized gain evaluated ' ...
        'continuously from 7k to 5k'], ...
    'Q', optimizedLqi.Q, ...
    'QI', optimizedLqi.QI, ...
    'qi', optimizedLqi.QI(1, 1), ...
    'ru', optimizedLqi.R(1, 1), ...
    'state_gain', optimizedLqi.state_gain, ...
    'integral_gain', optimizedLqi.integral_gain, ...
    'target_command_peak', optimizedLqi.configuration.target_peak, ...
    'command_tolerance', optimizedLqi.configuration.command_tolerance, ...
    'command_peak', optimizedLqi.command_peak, ...
    'command_peak_7k', optimizedLqi.command_peak_by_plant.x7k, ...
    'command_peak_5k', optimizedLqi.command_peak_by_plant.x5k, ...
    'tracking_loss', optimizedLqi.tracking_loss, ...
    'tracking_loss_7k', optimizedLqi.tracking_loss_by_plant.x7k, ...
    'tracking_loss_5k', optimizedLqi.tracking_loss_by_plant.x5k, ...
    'spectral_abscissa_7k', ...
        optimizedLqi.spectral_abscissa_by_plant.x7k, ...
    'spectral_abscissa_5k', ...
        optimizedLqi.spectral_abscissa_by_plant.x5k, ...
    'command_penalty', optimizedLqi.command_penalty, ...
    'stability_penalty', optimizedLqi.stability_penalty, ...
    'total_loss', optimizedLqi.total_loss, ...
    'loss_definition', optimizedLqi.loss_definition, ...
    'constraint_definition', optimizedLqi.constraint_definition, ...
    'gradient_norms', optimizedLqi.gradient_norms, ...
    'gradient_check', optimizedLqi.gradient_check, ...
    'bode', struct('frequency_hz', frequencyHz, ...
        'condition7k', lqriComparisonBodeSet(1, frequencyHz, ...
            ncfPidLoops, ncfLqriLoops), ...
        'condition5k', lqriComparisonBodeSet(2, frequencyHz, ...
            ncfPidLoops, ncfLqriLoops)), ...
    'step', comparisonStepSet(lqriStepTime, lqriStepIndex, ...
        ncfPidLoops, ncfLqriLoops, ncfPidCommandLoops, ...
        ncfLqriCommandLoops, 'lqri'), ...
    'margin', normalizedLqriNcfSet(models, ...
        optimizedLqiGain, pidController, dt, scale, ...
        condition, lqriDesign.frequency_band_hz));

save(fullfile(studyFolder, 'html_report_plot_data.mat'), 'result')
json = jsonencode(result);
webDataFolder = fullfile(studyFolder, 'LQG_web', 'data');
if ~isfolder(webDataFolder)
    mkdir(webDataFolder)
end
outputFile = fullfile(webDataFolder, 'report-plot-data.js');
fileId = fopen(outputFile, 'w');
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, 'window.SOL_ULTIMATE_PLOT_DATA = %s;\n', json);
fprintf('Saved HTML report plot data to %s\n', outputFile)
end

function output = responseSet(index, time, exportIndex, pidLoops, ...
        lqrLoops, ordinaryLqgLoops, integralLoops)
output = struct( ...
    'pid', column(step(pidLoops{index}, time), exportIndex), ...
    'lqr', column(step(lqrLoops{index}, time), exportIndex), ...
    'ordinary_lqg', column(step(ordinaryLqgLoops{index}, time), ...
        exportIndex), ...
    'lqgi', column(step(integralLoops{index}, time), exportIndex));
end

function output = bodeSet(index, frequencyHz, pidLoops, lqrLoops, ...
        integralLoops)
systems = {pidLoops{index}, lqrLoops{index}, integralLoops{index}};
names = {'pid', 'lqr', 'lqgi'};
output = struct;
for i = 1:numel(systems)
    response = squeeze(freqresp(systems{i}, 2*pi*frequencyHz));
    output.(names{i}) = struct( ...
        'magnitude_db', column(mag2db(abs(response))), ...
        'phase_deg', column(rad2deg(unwrap(angle(response)))));
end
end

function system = integralReferenceLoop(plant, nominal, K, Ki, L, dt)
[Ap, Bp, Cp] = ssdata(plant);
[An, Bn, Cn] = ssdata(nominal);
stateCount = size(Ap, 1);
A = [Ap, -Bp*K, -Bp*Ki; ...
    L*Cp, An-Bn*K-L*Cn, -Bn*Ki; ...
    -dt*Cp, zeros(1, stateCount), 1];
Br = [zeros(2*stateCount, 1); dt];
Cy = [Cp, zeros(1, stateCount+1)];
system = ss(A, Br, Cy, 0, dt);
end

function system = observerReferenceLoop(plant, nominal, K, nbar, L)
[Ap, Bp, Cp] = ssdata(plant);
[An, Bn, Cn] = ssdata(nominal);
stateCount = size(Ap, 1);
A = [Ap, -Bp*K; L*Cp, An-Bn*K-L*Cn];
Br = [Bp*nbar; Bn*nbar];
Cy = [Cp, zeros(1, stateCount)];
system = ss(A, Br, Cy, 0);
end

function system = lqriReferenceLoop(plant, gain)
[A, B, C] = ssdata(plant);
stateCount = size(A, 1);
augmentedA = [A, zeros(stateCount, 1); -C, 0];
augmentedB = [B; 0];
referenceInput = [zeros(stateCount, 1); 1];
system = ss(augmentedA-augmentedB*gain, referenceInput, ...
    [C, 0], 0);
end

function system = lqrReferenceCommand(plant, gain, referenceGain)
[A, B] = ssdata(plant);
system = ss(A-B*gain, B*referenceGain, -gain, referenceGain);
end

function system = lqriReferenceCommand(plant, gain)
[A, B, C] = ssdata(plant);
stateCount = size(A, 1);
augmentedA = [A, zeros(stateCount, 1); -C, 0];
augmentedB = [B; 0];
referenceInput = [zeros(stateCount, 1); 1];
system = ss(augmentedA-augmentedB*gain, referenceInput, -gain, 0);
end

function value = column(value, index)
value = value(:);
if nargin > 1
    value = value(index);
end
end

function output = reconstructedBodeSet(index, frequencyHz, pidLoops, ...
        plants, closedLoops, referenceGain)
pidResponse = squeeze(freqresp(pidLoops{index}, 2*pi*frequencyHz));
plantResponse = squeeze(freqresp(plants{index}, 2*pi*frequencyHz));
closedResponse = squeeze(freqresp(closedLoops{index}, ...
    2*pi*frequencyHz));
lqrResponse = referenceGain*plantResponse./closedResponse-1;
output = struct( ...
    'pid', struct( ...
        'magnitude_db', column(mag2db(abs(pidResponse))), ...
        'phase_deg', column(rad2deg(unwrap(angle(pidResponse))))), ...
    'lqr', struct( ...
        'magnitude_db', column(mag2db(abs(lqrResponse))), ...
        'phase_deg', column(rad2deg(unwrap(angle(lqrResponse))))));
end

function output = comparisonStepSet(time, exportIndex, pidLoops, ...
        controllerLoops, pidCommandLoops, controllerCommandLoops, ...
        controllerName)
output = struct('time_s', time(exportIndex));
for index = 1:2
    conditionName = sprintf('condition%dk', 9-2*index);
    condition = struct('pid', column(step(pidLoops{index}, time), ...
        exportIndex));
    condition.(controllerName) = column(step(controllerLoops{index}, ...
        time), exportIndex);
    command = struct('pid', column(step(pidCommandLoops{index}, time), ...
        exportIndex));
    command.(controllerName) = column(step( ...
        controllerCommandLoops{index}, time), exportIndex);
    condition.command = command;
    output.(conditionName) = condition;
end
end

function output = stiffnessStepSet(alphaGrid, time, exportIndex, ...
        controller, plants)
output = struct('time_s', time(exportIndex), 'alpha', alphaGrid);
for plantIndex = 1:2
    responses = zeros(numel(exportIndex), numel(alphaGrid));
    for alphaIndex = 1:numel(alphaGrid)
        closedLoop = feedback(alphaGrid(alphaIndex)*controller* ...
            plants{plantIndex}, 1);
        responses(:, alphaIndex) = column(step(closedLoop, time), ...
            exportIndex);
    end
    conditionName = sprintf('condition%dk', 9-2*plantIndex);
    output.(conditionName) = responses;
end
end

function output = lqriComparisonBodeSet(index, frequencyHz, pidLoops, ...
        lqriLoops)
systems = {pidLoops{index}, lqriLoops{index}};
names = {'pid', 'lqri'};
output = struct;
for i = 1:numel(systems)
    response = squeeze(freqresp(systems{i}, 2*pi*frequencyHz));
    output.(names{i}) = struct( ...
        'magnitude_db', column(mag2db(abs(response))), ...
        'phase_deg', column(rad2deg(unwrap(angle(response)))));
end
end

function output = fullNcfSet(models, K, referenceGain, pidController, ...
        dt, scale, condition, frequencyBandHz)
pidLoopMargin = zeros(size(condition));
lqrLoopMargin = zeros(size(condition));
pidLoopPeak = zeros(size(condition));
lqrLoopPeak = zeros(size(condition));
pidFullMargin = zeros(size(condition));
lqrFullMargin = zeros(size(condition));
pidFullPeak = zeros(size(condition));
lqrFullPeak = zeros(size(condition));
reconstructionError = zeros(size(condition));
pidGainMargin = zeros(size(condition));
lqrGainMargin = zeros(size(condition));
pidPhaseMargin = zeros(size(condition));
lqrPhaseMargin = zeros(size(condition));
frequencyHz = logspace(log10(frequencyBandHz(1)), ...
    log10(frequencyBandHz(2)), 10000).';
nominalA = scale*models.system_7k.A;
nominalB = scale*models.system_7k.B;
nominalGramian = lyap(nominalA, nominalB*nominalB.');
stateScale = sqrt(max(real(diag(nominalGramian)), eps));
stateScaleMatrix = diag(stateScale);
normalizedK = K*stateScaleMatrix;
for i = 1:numel(condition)
    fraction = condition(i);
    A = models.system_7k.A + ...
        fraction*(models.system_5k.A-models.system_7k.A);
    B = models.system_7k.B + ...
        fraction*(models.system_5k.B-models.system_7k.B);
    C = models.system_7k.C + ...
        fraction*(models.system_5k.C-models.system_7k.C);
    continuousA = scale*A;
    continuousB = scale*B;
    continuousPlant = ss(continuousA, continuousB, C, 0);
    discretePlant = c2d(continuousPlant, dt, 'zoh');
    pidReturn = pidController*discretePlant;
    pidSensitivity = feedback(1, discretePlant*pidController);
    pidNcf = minreal([1; pidController]*pidSensitivity* ...
        [1, discretePlant], 1e-9, false);
    [pidGamma, pidPeakRad] = hinfnorm(pidNcf);
    pidFullMargin(i) = 1/pidGamma;
    pidFullPeak(i) = pidPeakRad/(2*pi);

    pidResponse = squeeze(freqresp(pidReturn, 2*pi*frequencyHz));
    pidMetric = abs(1+pidResponse)./sqrt(2*(1+abs(pidResponse).^2));
    [pidLoopMargin(i), pidIndex] = min(pidMetric);
    pidLoopPeak(i) = frequencyHz(pidIndex);

    statePlant = ss(continuousA, continuousB, eye(size(A)), ...
        zeros(size(A, 1), 1));
    directLqrReturn = K*statePlant;
    lqrClosed = ss(continuousA-continuousB*K, ...
        continuousB*referenceGain, C, 0);
    plantResponse = squeeze(freqresp(continuousPlant, ...
        2*pi*frequencyHz));
    closedResponse = squeeze(freqresp(lqrClosed, 2*pi*frequencyHz));
    reconstructedLqrReturn = referenceGain*plantResponse./closedResponse-1;
    directLqrResponse = squeeze(freqresp(directLqrReturn, ...
        2*pi*frequencyHz));
    lqrMetric = abs(1+reconstructedLqrReturn)./ ...
        sqrt(2*(1+abs(reconstructedLqrReturn).^2));
    [lqrLoopMargin(i), lqrIndex] = min(lqrMetric);
    lqrLoopPeak(i) = frequencyHz(lqrIndex);
    reconstructionError(i) = max(abs(reconstructedLqrReturn- ...
        directLqrResponse)./max(1, abs(directLqrResponse)));

    normalizedStatePlant = ss(continuousA, continuousB, ...
        stateScaleMatrix\eye(size(A)), zeros(size(A, 1), 1));
    lqrSensitivity = feedback(ss(eye(size(A))), ...
        normalizedStatePlant*normalizedK);
    lqrNcf = minreal([ss(eye(size(A))); ss(normalizedK)]* ...
        lqrSensitivity*[ss(eye(size(A))), normalizedStatePlant], ...
        1e-9, false);
    [lqrGamma, lqrPeakRad] = hinfnorm(lqrNcf);
    lqrFullMargin(i) = 1/lqrGamma;
    lqrFullPeak(i) = lqrPeakRad/(2*pi);

    [pidGainMargin(i), pidPhaseMargin(i)] = ...
        custom_stability_margins(pidReturn, frequencyBandHz);
    [lqrGainMargin(i), lqrPhaseMargin(i)] = ...
        custom_stability_margins(directLqrReturn, frequencyBandHz);
end
lqrGainMargin(~isfinite(lqrGainMargin)) = 1e6;
pidGainMargin(~isfinite(pidGainMargin)) = 1e6;
lqrPhaseMargin(~isfinite(lqrPhaseMargin)) = 1e6;
pidPhaseMargin(~isfinite(pidPhaseMargin)) = 1e6;
output = struct( ...
    'condition', condition, ...
    'pid', pidLoopMargin, ...
    'lqr', lqrLoopMargin, ...
    'peak_frequency_hz', struct('pid', pidLoopPeak, ...
        'lqr', lqrLoopPeak), ...
    'gain_margin_db', struct('pid', pidGainMargin, ...
        'lqr', lqrGainMargin), ...
    'phase_margin_deg', struct('pid', pidPhaseMargin, ...
        'lqr', lqrPhaseMargin), ...
    'definition', ['Primary normalized scalar loop margin. The LQR return ' ...
        'ratio is reconstructed from the closed-loop reference response as ' ...
        'Nbar*Gy/Tr-1 before applying the same loop metric as PID.'], ...
    'reconstruction_max_relative_error', reconstructionError, ...
    'full_ncf', struct( ...
        'pid', pidFullMargin, ...
        'lqr', lqrFullMargin, ...
        'peak_frequency_hz', struct('pid', pidFullPeak, ...
            'lqr', lqrFullPeak), ...
        'definition', ['Secondary full H-infinity normalized-coprime-factor ' ...
            'diagnostic. LQR states use one fixed nominal 7k ' ...
            'controllability-Gramian normalization.']), ...
    'frequency_plot_band_hz', frequencyBandHz, ...
    'lqr_state_normalization', ...
        'fixed nominal-7k controllability-Gramian diagonal RMS', ...
    'lqr_state_scale_7k', stateScale);
end

function output = normalizedLqriNcfSet(models, gain, pidController, ...
        dt, scale, condition, frequencyBandHz)
pidMargin = zeros(size(condition));
lqriMargin = zeros(size(condition));
lqriSpectralAbscissa = zeros(size(condition));
for i = 1:numel(condition)
    fraction = condition(i);
    A = models.system_7k.A + ...
        fraction*(models.system_5k.A-models.system_7k.A);
    B = models.system_7k.B + ...
        fraction*(models.system_5k.B-models.system_7k.B);
    C = models.system_7k.C + ...
        fraction*(models.system_5k.C-models.system_7k.C);
    continuousPlant = ss(scale*A, scale*B, C, 0);
    plant = c2d(continuousPlant, dt, 'zoh');
    augmentedA = [scale*A, zeros(size(A, 1), 1); -C, 0];
    augmentedB = [scale*B; 0];
    lqriSpectralAbscissa(i) = max(real(eig( ...
        augmentedA-augmentedB*gain)));
    augmentedPlant = ss(augmentedA, augmentedB, ...
        eye(size(augmentedA)), zeros(size(augmentedA, 1), 1));
    [~, ~, pidMargin(i)] = custom_stability_margins( ...
        pidController*plant, frequencyBandHz);
    [~, ~, lqriMargin(i)] = custom_stability_margins( ...
        gain*augmentedPlant, frequencyBandHz);
end
output = struct('condition', condition, 'pid', pidMargin, ...
    'lqri', lqriMargin, ...
    'lqri_spectral_abscissa_per_s', lqriSpectralAbscissa);
end
