function result = design_lqr_ncf_match
%DESIGN_LQR_NCF_MATCH Match the nominal LQR and PID normalized NCF margins.

studyFolder = fileparts(mfilename('fullpath'));
lqgFolder = fileparts(studyFolder);
mainFolder = fileparts(fileparts(lqgFolder));
addpath(fullfile(mainFolder, 'control_and_HS', 'b_system_id', ...
    'id_utils'))
modelsData = load(fullfile(lqgFolder, 'results', ...
    'lqr_state_space_models.mat'), 'result');
models = modelsData.result;
system7k = models.system_7k;
refitData = load(system7k.source, 'result');
pidData = load(refitData.result.source, 'pid_values', 'model_metadata');
pidValues = pidData.pid_values;
frequencyBandHz = pidData.model_metadata.fit_config.f_lim;
frequencyScale = models.frequency_scale_rad_per_second;

plant = ss(frequencyScale*system7k.A, frequencyScale*system7k.B, ...
    system7k.C, 0);
discretePlant = c2d(plant, pidValues.dt, 'zoh');
pidController = pid(pidValues.P, pidValues.I, pidValues.D, ...
    1/pidValues.derivative_filter_N, pidValues.dt, ...
    'IFormula', 'ForwardEuler', 'DFormula', 'ForwardEuler');
[~, ~, pidMargin] = custom_stability_margins( ...
    pidController*discretePlant, frequencyBandHz);
statePlant = ss(frequencyScale*system7k.A, ...
    frequencyScale*system7k.B, eye(size(system7k.A)), ...
    zeros(size(system7k.A, 1), 1));

ru = 1;
options = optimset('Display', 'off', 'TolX', 1e-10);
optimalLogRatio = fzero(@(logRatio) marginDifference(logRatio, ...
    system7k, statePlant, frequencyBandHz, pidMargin), ...
    [2.25 2.5], options);
qy = 10^optimalLogRatio;
[K, ~, closedLoopPoles7k] = lqr(system7k.A, system7k.B, ...
    qy*(system7k.C.'*system7k.C), ru);
nbar = -1/(system7k.C*((system7k.A-system7k.B*K) \ system7k.B));
[~, ~, lqrMargin] = custom_stability_margins(K*statePlant, ...
    frequencyBandHz);
absoluteDifference = abs(lqrMargin-pidMargin);
matchingTolerance = 0.01;
assert(absoluteDifference <= matchingTolerance, ...
    'The LQR normalized NCF margin does not match the PID target.')

result = struct( ...
    'qy', qy, ...
    'ru', ru, ...
    'qy_over_ru', qy/ru, ...
    'K', K, ...
    'nbar', nbar, ...
    'closed_loop_poles_7k', closedLoopPoles7k, ...
    'pid_normalized_ncf_margin_7k', pidMargin, ...
    'lqr_normalized_ncf_margin_7k', lqrMargin, ...
    'absolute_margin_difference', absoluteDifference, ...
    'matching_tolerance', matchingTolerance, ...
    'frequency_band_hz', frequencyBandHz, ...
    'definition', ['Band-limited loop-only normalized Nyquist distance ' ...
        'used by custom_stability_margins.']);
save(fullfile(studyFolder, 'ncf_matched_lqr.mat'), 'result')

fprintf('NCF-matched qy = %.12g, ru = %.12g\n', qy, ru)
fprintf('PID normalized NCF margin = %.12f\n', pidMargin)
fprintf('LQR normalized NCF margin = %.12f\n', lqrMargin)
fprintf('Absolute difference = %.12g\n', absoluteDifference)
end

function difference = marginDifference(logRatio, system, plant, ...
        frequencyBandHz, targetMargin)
K = lqr(system.A, system.B, ...
    10^logRatio*(system.C.'*system.C), 1);
[~, ~, margin] = custom_stability_margins(K*plant, frequencyBandHz);
difference = margin-targetMargin;
end
