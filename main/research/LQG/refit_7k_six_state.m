function result = refit_7k_six_state
%REFIT_7K_SIX_STATE Refit the measured 7k H_dc_dm data with six poles.

rng(0)
assets = lqg_assets;
source = load(assets.system_7k, 'H_dc_dm', 'H_dc_dm_xfunc', ...
    'H_dc_dm_fit_info');

frequencyHz = source.H_dc_dm_xfunc.freq_hz(:);
frequencyRad = 2*pi*frequencyHz;
measuredResponse = source.H_dc_dm_xfunc.points(:);
fitData = idfrd(reshape(measuredResponse, [1 1 numel(measuredResponse)]), ...
    frequencyRad, 0, 'FrequencyUnit', 'rad/s');
options = tfestOptions('Display', 'off', 'EnforceStability', true);
options.SearchOptions.MaxIterations = 1000;
refittedTransferFunction = tf(tfest(fitData, 6, 4, options));
[refittedStateSpace, hankelSingularValues] = ...
    balreal(ss(refittedTransferFunction));
refittedStateSpace.InputName = 'dc';
refittedStateSpace.OutputName = 'dm';

originalMeasuredFit = squeeze(freqresp(source.H_dc_dm, frequencyRad));
refittedMeasuredFit = squeeze(freqresp(refittedTransferFunction, ...
    frequencyRad));
measuredMagnitudeDb = 20*log10(abs(measuredResponse) + eps);
measuredPhaseDeg = unwrap(angle(measuredResponse))*180/pi;
originalMagnitudeErrorDb = 20*log10(abs(originalMeasuredFit) + eps) - ...
    measuredMagnitudeDb;
refittedMagnitudeErrorDb = 20*log10(abs(refittedMeasuredFit) + eps) - ...
    measuredMagnitudeDb;
originalPhaseErrorDeg = unwrap(angle(originalMeasuredFit))*180/pi - ...
    measuredPhaseDeg;
refittedPhaseErrorDeg = unwrap(angle(refittedMeasuredFit))*180/pi - ...
    measuredPhaseDeg;

comparisonFrequencyHz = linspace(0.1, 100, 2000).';
comparisonFrequencyRad = 2*pi*comparisonFrequencyHz;
originalResponse = squeeze(freqresp(source.H_dc_dm, ...
    comparisonFrequencyRad));
refittedResponse = squeeze(freqresp(refittedTransferFunction, ...
    comparisonFrequencyRad));
complexDifference = refittedResponse(:) - originalResponse(:);
magnitudeDifferenceDb = 20*log10(abs(refittedResponse) + eps) - ...
    20*log10(abs(originalResponse) + eps);
phaseDifferenceDeg = unwrap(angle(refittedResponse))*180/pi - ...
    unwrap(angle(originalResponse))*180/pi;

stepTimeSeconds = linspace(0, 3, 1500).';
originalStep = step(source.H_dc_dm, stepTimeSeconds);
refittedStep = step(refittedTransferFunction, stepTimeSeconds);
stepDifference = refittedStep(:) - originalStep(:);

result = struct;
result.source = assets.system_7k;
result.original_transfer_function = source.H_dc_dm;
result.refitted_transfer_function = refittedTransferFunction;
result.state_space = refittedStateSpace;
result.A = refittedStateSpace.A;
result.B = refittedStateSpace.B;
result.C = refittedStateSpace.C;
result.D = refittedStateSpace.D;
result.hankel_singular_values = hankelSingularValues;
result.model = struct( ...
    'poles', 6, ...
    'zeros', 4, ...
    'states', order(refittedStateSpace), ...
    'stable', isstable(refittedStateSpace), ...
    'controllability_rank', rank(ctrb(refittedStateSpace.A, ...
        refittedStateSpace.B)), ...
    'observability_rank', rank(obsv(refittedStateSpace.A, ...
        refittedStateSpace.C)));
result.measured_fit = struct( ...
    'frequency_range_hz', [frequencyHz(1), frequencyHz(end)], ...
    'original_rms_magnitude_error_db', rms(originalMagnitudeErrorDb), ...
    'refitted_rms_magnitude_error_db', rms(refittedMagnitudeErrorDb), ...
    'original_rms_phase_error_deg', rms(originalPhaseErrorDeg), ...
    'refitted_rms_phase_error_deg', rms(refittedPhaseErrorDeg));
result.original_model_difference = struct( ...
    'frequency_range_hz', [comparisonFrequencyHz(1), ...
        comparisonFrequencyHz(end)], ...
    'max_absolute_complex_error', max(abs(complexDifference)), ...
    'max_relative_complex_error', max(abs(complexDifference) ./ ...
        max(abs(originalResponse(:)), eps)), ...
    'rms_magnitude_error_db', rms(magnitudeDifferenceDb), ...
    'max_magnitude_error_db', max(abs(magnitudeDifferenceDb)), ...
    'rms_phase_error_deg', rms(phaseDifferenceDeg), ...
    'max_phase_error_deg', max(abs(phaseDifferenceDeg)), ...
    'step_range_s', [stepTimeSeconds(1), stepTimeSeconds(end)], ...
    'rms_step_error', rms(stepDifference), ...
    'max_step_error', max(abs(stepDifference)));

outputFile = fullfile(assets.results, 'lqr_7k_six_state_refit.mat');
save(outputFile, 'result')
fprintf('7k six-state refit saved to %s\n', outputFile)
fprintf('Measured fit RMS: magnitude %.6g dB, phase %.6g deg\n', ...
    result.measured_fit.refitted_rms_magnitude_error_db, ...
    result.measured_fit.refitted_rms_phase_error_deg)
fprintf('Original model RMS difference: magnitude %.6g dB, phase %.6g deg\n', ...
    result.original_model_difference.rms_magnitude_error_db, ...
    result.original_model_difference.rms_phase_error_deg)
fprintf('Original model max step error: %.6g\n', ...
    result.original_model_difference.max_step_error)
end
