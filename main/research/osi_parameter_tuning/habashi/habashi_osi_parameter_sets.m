function [new_params, current_params] = habashi_osi_parameter_sets(projectFolder)
%HABASHI_OSI_PARAMETER_SETS Editable fable OSI tuning parameters.

if nargin < 1 || isempty(projectFolder)
    script_root = fileparts(mfilename('fullpath'));
    projectFolder = fileparts(fileparts(fileparts(script_root)));
end

%% Model Used To Build The OSI Runtime Parameters
exp_tf_file = fullfile(projectFolder, 'saved_results', 'exp_tf', ...
    'tf_sp1_5000_20260627_233333.mat');

%% Category A - Slow ST Branch: Accurate Margin Level
window_s = 5.0;
hop_s = 0.25;
segment_s = 1.0;
margin_filter_n = 3;
freq_medfilt_n = 3;
slow_filt_alpha = 0.2;
gamma_alpha = 0.01;
gamma_quiet = 0.15;
input_power_range_db = 35;
sidelobe_db = 25;
min_bins = 5;
threshold = [];        % [] keeps this equal to target_outer_ncf.
warm_updates = 4;
residual_floor = 0.03;

%% Category B - Residual Branch: Quiet-Band Growth Watcher
residual_band_hz = [28 100];
z_on = 4.0;
z_off = 2.0;
res_on_n = 4;
res_hold_s = 5;
res_min_growth_db = 3;
res_match_hz = 3;
sigma0_floor = 0.15;

%% Category C - Fast Path / Quick-Dip Guards
fast_segment_s = 0.25;
fast_ring_n = 3;
fast_min_bins = 3;
fast_st_nu = 1.25;
fast_st_h = 4.5;
fast_babs_offset = 0.10;
fast_amove_frac = 0.02;
fast_d_sig_floor = 0.30;
fast_burst_nu = 1.0;
fast_burst_h = 6.0;
fast_burst_bands = [28 44; 44 60; 62 78; 78 94; 94 100];
fast_sig_floor = 0.20;
fast_pin_lo = 0.25;
fast_pin_hi = 4.0;
fast_pin_alpha = 0.04;

%% Category D - Regime And Calibration
regime_hops = 8;
cal_skip_s = 10;
cal_windows = 80;
cal_min_windows = 24;
cal_timeout_hops = 600;
cal_reject_factor = 4;
cal_restart_rejects = 12;
bl_adapt_tau_s = 100;
bl_adapt_max_db = 3;

%% Category E - Authority Law
% Setpoint / smoothing
target_outer_ncf = 0.50;
b_filt_tau_s = 0.4;

% Drop / shed
down_deadband = 0.01;
down_confirm_n = 2;
down_power = 1.5;
down_rate = 2.0;
down_settle_s = 1.25;
re_shed_delta = 0.02;
sev_frac = 0.60;

% Severe
sev_down_rate = 8.0;

% Recovery
up_deadband = 0.02;
up_hold_s = 1.5;
up_rate = 0.08;
up_rate_blind = 0.02;
up_prop = 3.0;

% Anti-flicker
min_step = 0.02;

% Prediction
fable_pred_enable = true;
use_pred = 1;
pred_guard = 0.03;
pred_floor_frac = 0.90;

% Fast-trip response
trip_drop = 0.6; % default 0.6; multiplier after fast trip, 1.0 disables instant trip drop
trip_power = 1.0; % default 1.5; with trip_drop = 1.0, disables b_fast-sized instant trip drops
trip_cool_s = 5.0;
trip_undo_s = 2.5;
self_move_gate_s = 1.5;
self_move_frac = 0.02;

% Post-event latch
latch_relax = 1.15;
latch_decay_tau_s = 1;

% Bounds / cadence
osi_gain_min = 0.08;
a_max = 1.00;
osi_gain_initial = 1.00;
dt_update = 0.125;

if isempty(threshold)
    threshold_value = target_outer_ncf;
else
    threshold_value = threshold;
end

new_osi = struct( ...
    'window_s', window_s, ...
    'hop_s', hop_s, ...
    'segment_s', segment_s, ...
    'margin_filter_n', margin_filter_n, ...
    'freq_medfilt_n', freq_medfilt_n, ...
    'slow_filt_alpha', slow_filt_alpha, ...
    'gamma_alpha', gamma_alpha, ...
    'gamma_quiet', gamma_quiet, ...
    'input_power_range_db', input_power_range_db, ...
    'sidelobe_db', sidelobe_db, ...
    'min_bins', min_bins, ...
    'threshold', threshold_value, ...
    'warm_updates', warm_updates, ...
    'residual_floor', residual_floor, ...
    'residual_band_hz', residual_band_hz, ...
    'z_on', z_on, ...
    'z_off', z_off, ...
    'res_on_n', res_on_n, ...
    'res_hold_s', res_hold_s, ...
    'res_min_growth_db', res_min_growth_db, ...
    'res_match_hz', res_match_hz, ...
    'sigma0_floor', sigma0_floor, ...
    'fast_segment_s', fast_segment_s, ...
    'fast_ring_n', fast_ring_n, ...
    'fast_min_bins', fast_min_bins, ...
    'fast_st_nu', fast_st_nu, ...
    'fast_st_h', fast_st_h, ...
    'fast_babs_offset', fast_babs_offset, ...
    'fast_amove_frac', fast_amove_frac, ...
    'fast_d_sig_floor', fast_d_sig_floor, ...
    'fast_burst_nu', fast_burst_nu, ...
    'fast_burst_h', fast_burst_h, ...
    'fast_burst_bands', fast_burst_bands, ...
    'fast_sig_floor', fast_sig_floor, ...
    'fast_pin_lo', fast_pin_lo, ...
    'fast_pin_hi', fast_pin_hi, ...
    'fast_pin_alpha', fast_pin_alpha, ...
    'regime_hops', regime_hops, ...
    'cal_skip_s', cal_skip_s, ...
    'cal_windows', cal_windows, ...
    'cal_min_windows', cal_min_windows, ...
    'cal_timeout_hops', cal_timeout_hops, ...
    'cal_reject_factor', cal_reject_factor, ...
    'cal_restart_rejects', cal_restart_rejects, ...
    'bl_adapt_tau_s', bl_adapt_tau_s, ...
    'bl_adapt_max_db', bl_adapt_max_db);

new_auth = struct( ...
    'b_filt_tau_s', b_filt_tau_s, ...
    'down_deadband', down_deadband, ...
    'down_confirm_n', down_confirm_n, ...
    'down_power', down_power, ...
    'down_rate', down_rate, ...
    'down_settle_s', down_settle_s, ...
    're_shed_delta', re_shed_delta, ...
    'sev_frac', sev_frac, ...
    'sev_down_rate', sev_down_rate, ...
    'up_deadband', up_deadband, ...
    'up_hold_s', up_hold_s, ...
    'up_rate', up_rate, ...
    'up_rate_blind', up_rate_blind, ...
    'up_prop', up_prop, ...
    'min_step', min_step, ...
    'use_pred', use_pred, ...
    'pred_guard', pred_guard, ...
    'pred_floor_frac', pred_floor_frac, ...
    'trip_drop', trip_drop, ...
    'trip_power', trip_power, ...
    'trip_cool_s', trip_cool_s, ...
    'trip_undo_s', trip_undo_s, ...
    'self_move_gate_s', self_move_gate_s, ...
    'self_move_frac', self_move_frac, ...
    'latch_relax', latch_relax, ...
    'latch_decay_tau_s', latch_decay_tau_s, ...
    'a_max', a_max, ...
    'dt_update', dt_update);

new_params = struct( ...
    'name', 'new', ...
    'projectFolder', projectFolder, ...
    'exp_tf_file', exp_tf_file, ...
    'target_outer_ncf', target_outer_ncf, ...
    'osi_gain_min', osi_gain_min, ...
    'osi_gain_initial', osi_gain_initial, ...
    'fable_pred_enable', fable_pred_enable, ...
    'osi_override', new_osi, ...
    'auth_override', new_auth);

current_params = struct( ...
    'name', 'current', ...
    'projectFolder', projectFolder, ...
    'exp_tf_file', exp_tf_file, ...
    'target_outer_ncf', 0.50, ...
    'osi_gain_min', 0.08, ...
    'osi_gain_initial', 1.00, ...
    'fable_pred_enable', true, ...
    'osi_override', struct(), ...
    'auth_override', struct());
end
